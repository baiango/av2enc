def build_inventory(root: Path, src_rel: str) -> dict:
    src_root = (root / src_rel).resolve()
    if not src_root.is_dir():
        raise SystemExit(f"inventory: source directory not found: {src_root}")

    ignored: list[str] = []
    records = walk_sources(src_root, ignored)
    for rec in records:
        rec.rel = relpath(rec.path, root)

    cmake = parse_cmake(root, src_root)
    by_dir = find_scripts(src_root)

    # git tracking (read-only; tolerated when git is unavailable)
    tracked: set[str] = set()
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z"],
            capture_output=True, check=False)
        if out.returncode == 0:
            tracked = {p for p in out.stdout.decode("utf-8", "replace").split("\0") if p}
    except OSError:
        pass

    # include resolution index
    basename_index: dict[str, list[Path]] = defaultdict(list)
    for rec in records:
        basename_index[rec.path.name].append(rec.path)

    def resolve(inc: str, path: Path) -> str | None:
        for cand in (path.parent / inc, src_root / inc, root / inc):
            try:
                if cand.is_file() and cand.resolve().is_relative_to(root.resolve()):
                    return relpath(cand.resolve(), root)
            except (OSError, ValueError):
                continue
        matches = basename_index.get(Path(inc).name, [])
        if len(matches) == 1:
            return relpath(matches[0].resolve(), root)
        return None

    include_edges: dict[str, list[str]] = defaultdict(list)
    unresolved: list[dict[str, str]] = []
    include_targets: dict[str, set[str]] = defaultdict(set)  # target -> includers
    for rec in records:
        for inc in quoted_includes(rec.clean):
            target = resolve(inc, rec.path)
            if target is None:
                unresolved.append({"from": rec.rel, "include": inc})
                continue
            if target != rec.rel and target not in include_edges[rec.rel]:
                include_edges[rec.rel].append(target)
            include_targets[target].add(rec.rel)

    # test / gate sources and the files they reference
    test_sources = [r for r in records if is_test_name(r.path.name)]
    gate_sources = [r for r in records if is_gate_name(r.path.name) or "/gate/" in r.rel]
    test_targets: set[str] = set()
    gate_targets: set[str] = set()
    for t in test_sources:
        test_targets.add(t.rel)
        for inc in quoted_includes(t.clean):
            tgt = resolve(inc, t.path)
            if tgt:
                test_targets.add(tgt)
    for g in gate_sources:
        gate_targets.add(g.rel)
        for inc in quoted_includes(g.clean):
            tgt = resolve(inc, g.path)
            if tgt:
                gate_targets.add(tgt)

    scripts = generator_scripts(root, src_root)
    script_texts = {}
    for s in scripts:
        script_texts[s] = read_text(s) or ""

    files = []
    top = defaultdict(lambda: {"files": 0, "loc": 0, "in_cmake": 0,
                               "no_test": 0, "no_gate": 0})
    helper_defs: dict[str, list[dict]] = {h: [] for h in HELPERS}
    helper_files: dict[str, set[str]] = {h: set() for h in HELPERS}
    helper_mentions_raw: dict[str, set[str]] = {h: set() for h in HELPERS}

    for rec in records:
        in_cmake, cmake_lists, targets, globbed = cmake_for(rec.path, root, cmake)
        parts = Path(rec.rel).parts
        dir_key = parts[1] if len(parts) > 2 else "(root)"
        top[dir_key]["files"] += 1
        top[dir_key]["loc"] += rec.loc
        if in_cmake:
            top[dir_key]["in_cmake"] += 1

        direct_scripts = by_dir.get(str(rec.path.parent.resolve()), [])
        # nearest ancestor gate/build scripts (for dirs with a gate/ subtree)
        gate_evidence: list[str] = []
        p = rec.path.parent
        while True:
            for name in by_dir.get(str(p.resolve()), []):
                if "gate" in Path(name).name or "test" in Path(name).name:
                    gate_evidence.append(name)
            if p == src_root or p.parent == p:
                break
            p = p.parent

        # test presence: self, same-stem test, or a test that includes this file
        test_ev: list[str] = []
        if rec.rel in test_targets:
            test_ev.append(rec.rel if is_test_name(rec.path.name) else "included by test")
        stem = rec.path.stem
        for t in test_sources:
            if t.path.parent == rec.path.parent and (
                    t.path.stem == stem or t.path.stem == f"{stem}_test"
                    or t.path.name == f"{stem}_test{t.path.suffix}"):
                test_ev.append(t.rel)
                break
        test_present = bool(test_ev)

        gate_present = bool(gate_evidence) or rec.rel in gate_targets
        if rec.rel in gate_targets and not gate_evidence:
            gate_evidence.append("included by gate source")

        namespaces = namespaces_in(rec.clean)
        for h in HELPERS:
            if re.search(r"\b" + re.escape(h) + r"\b", rec.clean):
                helper_files[h].add(rec.rel)
            if re.search(r"\b" + re.escape(h) + r"\b", rec.text):
                helper_mentions_raw[h].add(rec.rel)
            for line, sig in helper_definitions(rec.clean, rec.text, h):
                helper_defs[h].append({"path": rec.rel, "line": line,
                                       "signature": sig})

        head = "\n".join(rec.text.splitlines()[:80]).lower()
        marker = next((m for m in GENERATED_MARKERS if m in head), None)
        gen = likely_generator(rec.path, scripts, script_texts, root) if marker else None

        if not test_present:
            top[dir_key]["no_test"] += 1
        if not gate_present:
            top[dir_key]["no_gate"] += 1

        files.append({
            "path": rec.rel,
            "loc": rec.loc,
            "ext": rec.path.suffix.lower(),
            "git_tracked": rec.rel in tracked,
            "in_cmake": in_cmake,
            "cmake_lists": cmake_lists,
            "cmake_targets": targets,
            "cmake_glob": globbed,
            "build_scripts": direct_scripts,
            "gate_scripts": sorted(set(gate_evidence)),
            "namespaces": namespaces,
            "test_present": test_present,
            "test_evidence": sorted(set(test_ev))[:6],
            "gate_present": gate_present,
            "generated": bool(marker),
            "generated_marker": marker,
            "generator": gen,
        })

    # orphans: source not in CMake and no build script in its directory
    orphans = [f["path"] for f in files
               if not f["in_cmake"] and not f["build_scripts"]
               and not is_test_name(Path(f["path"]).name)
               and not is_gate_name(Path(f["path"]).name)
               and "/gate/" not in f["path"]]

    duplicate_report = {}
    for h in HELPERS:
        defs = helper_defs[h]
        files_with_def = sorted({d["path"] for d in defs})
        duplicate_report[h] = {
            "definition_count": len(defs),
            "definition_file_count": len(files_with_def),
            "files_mentioning": len(helper_files[h]),
            "files_mentioning_raw": len(helper_mentions_raw[h]),
            "duplicate": len(files_with_def) > 1,
            "definitions": defs,
        }

    node_list = [f["path"] for f in files]
    sccs = strongly_connected(node_list, include_edges)

    total_loc = sum(f["loc"] for f in files)
    build_scripts = sorted({s for scripts in by_dir.values() for s in scripts})
    compiled = [f for f in files if f["ext"] in (".cpp", ".cc", ".cxx", ".cu")
                and f["in_cmake"]]

    summary = {
        "source_files": len(files),
        "total_loc": total_loc,
        "tracked_source_files": sum(1 for f in files if f["git_tracked"]),
        "untracked_source_files": sum(1 for f in files if not f["git_tracked"]),
        "compiled_translation_units": len(compiled),
        "in_cmake_files": sum(1 for f in files if f["in_cmake"]),
        "build_scripts": len(build_scripts),
        "generated_files": sum(1 for f in files if f["generated"]),
        "files_without_test": sum(1 for f in files if not f["test_present"]),
        "files_without_gate": sum(1 for f in files if not f["gate_present"]),
        "orphan_files": len(orphans),
        "include_edges": sum(len(v) for v in include_edges.values()),
        "unresolved_includes": len(unresolved),
        "include_sccs": len(sccs),
        "ignored_build_dirs": len(ignored),
    }

    plan_documented = {
        "source_files": 689,
        "compiled_translation_units": 375,
        "lines_under_src": 223000,
        "standalone_build_scripts": 124,
        "round2_definers": 56,
        "qlookup_definers": 19,
        "clip3_definers": 19,
        "note": "Numbers transcribed from docs/refactor-plan.md; the code and "
                "tests are authoritative when they disagree.",
    }

    return {
        "schema": 1,
        "tool": "tools/refactor/inventory.py",
        "generated_at": __import__("datetime").datetime.now().astimezone().isoformat(
            timespec="seconds"),
        "root": str(root),
        "src": src_rel,
        "summary": summary,
        "plan_vs_observed": {
            "documented": plan_documented,
            "observed": {
                "source_files": summary["source_files"],
                "tracked_source_files": summary["tracked_source_files"],
                "compiled_translation_units": summary["compiled_translation_units"],
                "lines_under_src": total_loc,
                "build_scripts": summary["build_scripts"],
                "round2_definers": duplicate_report["Round2"]["definition_file_count"],
                "round2_files_mentioning_raw": duplicate_report["Round2"]["files_mentioning_raw"],
                "qlookup_definers": duplicate_report["qlookup"]["definition_file_count"],
                "clip3_definers": duplicate_report["Clip3"]["definition_file_count"],
            },
        },
        "top_level": {k: top[k] for k in sorted(top)},
        "helpers": duplicate_report,
        "include_graph": {
            "nodes": node_list,
            "edges": [{"from": k, "to": v} for k, v in sorted(include_edges.items())
                      for v in v],
            "unresolved": unresolved,
            "strongly_connected": sccs,
        },
        "orphans": orphans,
        "ignored_directories": sorted(set(ignored)),
        "files": files,
    }


