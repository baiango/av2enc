#!/usr/bin/env python3
"""Read-only source inventory for the folder refactor (Phase 0).

The tool never builds, moves, or edits source.  It walks the working tree
(not just git) so in-flight, untracked feature directories are included, skips
build artefact directories, and emits JSON + Markdown reports.

Usage:
    python3 tools/refactor/inventory.py
    python3 tools/refactor/inventory.py --json refactor/inventory.json \
        --markdown refactor/inventory.md

The reports contain, per source file:
  * physical LOC
  * whether it is named in CMakeLists.txt (and which target)
  * its directory's build*.sh scripts
  * namespaces declared in the file
  * test / gate presence (with evidence)
  * generated-file marker and the likely generator script
plus:
  * duplicate definitions of the shared helpers (Round2, Round2Signed,
    Clip1/Clip3, qlookup, get_qindex, coeff_cdf_slice)
  * an include graph of quoted includes, unresolved includes and SCCs
  * a top-level-directory summary and plan-vs-observed metrics

Exit status: 0 on success, 2 on bad arguments / output path under src/.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path

SOURCE_EXTS = {".cpp", ".cc", ".cxx", ".cu", ".cuh", ".h", ".hh", ".hpp", ".inl"}
TEST_EXTS = SOURCE_EXTS
BUILD_DIR_RE = re.compile(r"^(build|build[-_].*|cmake-build-.*)$")
SKIP_DIR_NAMES = {"__pycache__", ".git", ".hg", ".svn", "node_modules", ".cache"}
HELPERS = ("Round2", "Round2Signed", "Clip1", "Clip3", "qlookup", "get_qindex",
           "coeff_cdf_slice")
GENERATED_MARKERS = (
    "do not edit", "auto-generated", "autogenerated", "generated by",
    "generated from", "code generated", "this file is generated",
    "machine generated", "generated file",
)
CONTROL_WORDS = {"if", "while", "for", "switch", "return", "catch", "sizeof",
                 "decltype", "static_assert", "case", "throw", "elseif"}
GENERATOR_RE = re.compile(r"^(generate|gen).*\.py$|.*_gen\.py$|.*_tables?\.py$")


# ---------------------------------------------------------------------------
# text helpers (all preserve byte offsets so line numbers stay valid)
# ---------------------------------------------------------------------------

def strip_comments(text: str) -> str:
    """Replace // and /* */ comments with spaces, preserving newlines.

    String and character literals are copied verbatim so callers can still
    read #include "..." paths and inspect quoted text.
    """
    out = list(text)
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            j = text.find("\n", i)
            if j < 0:
                j = n
            for k in range(i, j):
                out[k] = " "
            i = j
        elif c == "/" and i + 1 < n and text[i + 1] == "*":
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            for k in range(i, j):
                if text[k] != "\n":
                    out[k] = " "
            i = j
        elif c in ('"', "'"):
            quote = c
            j = i + 1
            while j < n:
                if text[j] == "\\":
                    j += 2
                    continue
                if text[j] == quote:
                    j += 1
                    break
                j += 1
            i = j
        else:
            i += 1
    return "".join(out)


def line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def read_text(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None


def relpath(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


# ---------------------------------------------------------------------------
# CMake parsing
# ---------------------------------------------------------------------------

@dataclass
class CMakeInfo:
    mentions: dict[str, list[str]] = field(default_factory=dict)  # src path -> cmake files
    targets: dict[str, list[str]] = field(default_factory=dict)   # src path -> target names
    glob_dirs: list[tuple[Path, set[str]]] = field(default_factory=list)
    glob_exclusions: list[re.Pattern[str]] = field(default_factory=list)


def parse_cmake(root: Path, src_root: Path) -> CMakeInfo:
    info = CMakeInfo()
    cmake_files = sorted(
        p for p in root.rglob("CMakeLists.txt")
        if "build" not in p.relative_to(root).parts[0]
    )
    for cm in cmake_files:
        text = read_text(cm)
        if text is None:
            continue
        cm_rel = relpath(cm, root)

        # literal src/... tokens
        for m in re.finditer(r"src/[A-Za-z0-9_./+-]+\.(?:cpp|cc|cxx|cu|cuh)", text):
            path = m.group(0).replace("//", "/")
            info.mentions.setdefault(path, []).append(cm_rel)

        # add_library / add_executable target blocks: map literal sources to target
        for m in re.finditer(r"add_(?:library|executable)\s*\(\s*([A-Za-z0-9_]+)", text):
            target = m.group(1)
            start = m.end()
            depth, i = 1, start
            while i < len(text) and depth:
                if text[i] == "(":
                    depth += 1
                elif text[i] == ")":
                    depth -= 1
                i += 1
            block = text[start:i]
            for sm in re.finditer(r"src/[A-Za-z0-9_./+-]+\.(?:cpp|cc|cxx|cu|cuh)", block):
                info.targets.setdefault(sm.group(0), []).append(target)
            for sm in re.finditer(r"src/[A-Za-z0-9_./+-]+\.(?:cpp|cc|cxx|cu|cuh)", block):
                info.mentions.setdefault(sm.group(0), []).append(cm_rel)

        # file(GLOB_RECURSE VAR ... "${VAR_DIR}/*.cu") handling
        var_values: dict[str, Path] = {}
        for m in re.finditer(r'set\s*\(\s*([A-Za-z0-9_]+)\s+"([^"]+)"', text):
            raw_value = m.group(2)
            raw_value = raw_value.replace("${CMAKE_CURRENT_SOURCE_DIR}", str(root))
            raw_value = raw_value.replace("${PROJECT_SOURCE_DIR}", str(root))
            raw_value = raw_value.replace("${CMAKE_SOURCE_DIR}", str(root))
            var_values[m.group(1)] = (root / raw_value).resolve() if not Path(raw_value).is_absolute() else Path(raw_value).resolve()
        for m in re.finditer(r"file\s*\(\s*GLOB_RECURSE\b", text):
            start = m.end()
            depth, i = 1, start
            while i < len(text) and depth:
                if text[i] == "(":
                    depth += 1
                elif text[i] == ")":
                    depth -= 1
                i += 1
            block = text[start:i]
            exts: set[str] = set()
            for pm in re.finditer(r'\$\{([A-Za-z0-9_]+)\}/([^")\s]+)', block):
                base = var_values.get(pm.group(1))
                if base is None:
                    continue
                pat = pm.group(2)
                if pat.startswith("*."):
                    exts.add("." + pat[2:])
            if exts:
                for var, base in var_values.items():
                    if f"${{{var}}}" in block:
                        info.glob_dirs.append((base, exts))
        for m in re.finditer(r'list\s*\(\s*FILTER\b[^)]*EXCLUDE\s+REGEX\s+"([^"]+)"', text):
            try:
                info.glob_exclusions.append(re.compile(m.group(1)))
            except re.error:
                pass
    # de-duplicate
    for k in list(info.mentions):
        info.mentions[k] = sorted(set(info.mentions[k]))
    for k in list(info.targets):
        info.targets[k] = sorted(set(info.targets[k]))
    return info


def cmake_for(path: Path, root: Path, info: CMakeInfo) -> tuple[bool, list[str], list[str], bool]:
    rel = relpath(path, root)
    cmake_lists = info.mentions.get(rel, [])
    targets = info.targets.get(rel, [])
    globbed = False
    for base, exts in info.glob_dirs:
        try:
            path.resolve().relative_to(base)
        except ValueError:
            continue
        if path.suffix in exts:
            excluded = any(p.search(str(path)) for p in info.glob_exclusions)
            if not excluded:
                globbed = True
                targets = targets + ["av2enc_m1_gpu"]
    return bool(cmake_lists or globbed), cmake_lists, sorted(set(targets)), globbed


