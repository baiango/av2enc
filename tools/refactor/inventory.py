def main(argv: list[str]) -> int:
    here = Path(__file__).resolve()
    default_root = here.parents[2]
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(default_root),
                    help="repository root (default: inferred from this script)")
    ap.add_argument("--src", default="src", help="source directory, relative to root")
    ap.add_argument("--json", default="refactor/inventory.json",
                    help="JSON output path, relative to root")
    ap.add_argument("--markdown", default="refactor/inventory.md",
                    help="Markdown output path, relative to root")
    ap.add_argument("--quiet", action="store_true", help="only print the summary line")
    args = ap.parse_args(argv)

    root = Path(args.root).resolve()
    src_root = (root / args.src).resolve()
    for out in (args.json, args.markdown):
        out_path = (root / out).resolve()
        try:
            out_path.relative_to(src_root)
        except ValueError:
            continue
        print(f"inventory: refusing to write under {src_root}: {out_path}", file=sys.stderr)
        return 2

    inv = build_inventory(root, args.src)
    json_path = root / args.json
    md_path = root / args.markdown
    json_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(inv, indent=2) + "\n", encoding="utf-8")
    md_path.write_text(render_markdown(inv), encoding="utf-8")

    s = inv["summary"]
    print(f"inventory: {s['source_files']} source files, {s['total_loc']} LOC, "
          f"{s['compiled_translation_units']} compiled TUs, "
          f"{s['build_scripts']} build scripts, "
          f"{s['untracked_source_files']} untracked files")
    print(f"inventory: wrote {json_path}")
    print(f"inventory: wrote {md_path}")
    if not args.quiet:
        print("inventory: helper definitions: " + ", ".join(
            f"{h}={inv['helpers'][h]['definition_file_count']}"
            for h in HELPERS))
        print(f"inventory: include graph: {len(inv['include_graph']['nodes'])} nodes, "
              f"{len(inv['include_graph']['edges'])} edges, "
              f"{len(inv['include_graph']['unresolved'])} unresolved, "
              f"{len(inv['include_graph']['strongly_connected'])} SCC(s)")
        print(f"inventory: orphans: {s['orphan_files']}, "
              f"no-test: {s['files_without_test']}, "
              f"no-gate: {s['files_without_gate']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
