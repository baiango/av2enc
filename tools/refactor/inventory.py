def render_markdown(inv: dict) -> str:
    s = inv["summary"]
    lines: list[str] = []
    add = lines.append
    add("# Source inventory (Phase 0)")
    add("")
    add(f"Generated by `{inv['tool']}` at {inv['generated_at']}.")
    add("")
    add("Read-only snapshot of the working tree, including untracked in-flight "
        "feature directories. Build directories and other artefacts are skipped.")
    add("")
    add("## Summary")
    add("")
    add("| Metric | Value |")
    add("|---|---:|")
    for key in ("source_files", "tracked_source_files", "untracked_source_files",
                "total_loc", "compiled_translation_units", "in_cmake_files",
                "build_scripts", "generated_files", "files_without_test",
                "files_without_gate", "orphan_files", "include_edges",
                "unresolved_includes", "include_sccs", "ignored_build_dirs"):
        add(f"| {key.replace('_', ' ')} | {s[key]:,} |")
    add("")
    add("### Plan vs observed")
    add("")
    add("| Metric | docs/refactor-plan.md | observed |")
    add("|---|---:|---:|")
    pv = inv["plan_vs_observed"]
    for key, doc_key in (
            ("source_files", "source_files"),
            ("compiled_translation_units", "compiled_translation_units"),
            ("lines_under_src", "lines_under_src"),
            ("build_scripts", "standalone_build_scripts"),
            ("round2_definers", "round2_definers"),
            ("qlookup_definers", "qlookup_definers"),
            ("clip3_definers", "clip3_definers")):
        add(f"| {key.replace('_', ' ')} | {pv['documented'][doc_key]:,} | "
            f"{pv['observed'][key]:,} |")
    add("")
    add("The plan table is dated; the observed column is the contract for this "
        "snapshot.")
    add("")
    add("## Top-level directories under `src/`")
    add("")
    add("| Directory | Files | LOC | In CMake | No test | No gate |")
    add("|---|---:|---:|---:|---:|---:|")
    for k, v in inv["top_level"].items():
        label = "`src/` (root files)" if k == "(root)" else f"`src/{k}`"
        add(f"| {label} | {v['files']:,} | {v['loc']:,} | {v['in_cmake']:,} | "
            f"{v['no_test']:,} | {v['no_gate']:,} |")
    add("")
    add("## Shared-helper definitions")
    add("")
    add("A definition is a function body (`){`), not a call site. Duplicates "
        "must be consolidated in Phase 5.")
    add("")
    add("| Helper | Definitions | Files | Files mentioning (code) | Files mentioning (raw) | Duplicate? |")
    add("|---|---:|---:|---:|---:|---|")
    for h in HELPERS:
        d = inv["helpers"][h]
        add(f"| `{h}` | {d['definition_count']} | {d['definition_file_count']} | "
            f"{d['files_mentioning']} | {d['files_mentioning_raw']} | "
            f"{'**yes**' if d['duplicate'] else 'no'} |")
    add("")
    for h in HELPERS:
        d = inv["helpers"][h]
        if not d["definitions"]:
            continue
        add(f"### `{h}` definitions")
        add("")
        for item in d["definitions"]:
            add(f"- `{item['path']}:{item['line']}` — `{item['signature']}`")
        add("")
    add("## Generated files")
    add("")
    gen = [f for f in inv["files"] if f["generated"]]
    if not gen:
        add("No generated-file markers found.")
    else:
        add("| File | Marker | Likely generator |")
        add("|---|---|---|")
        for f in gen:
            add(f"| `{f['path']}` | {f['generated_marker']} | "
                f"{('`' + f['generator'] + '`') if f['generator'] else '**unknown**'} |")
    add("")
    add("## Include graph")
    add("")
    add(f"- Nodes: {len(inv['include_graph']['nodes']):,}")
    add(f"- Quoted-include edges: {inv['include_graph']['edges'] and len(inv['include_graph']['edges']) or 0:,}")
    add(f"- Unresolved quoted includes: {len(inv['include_graph']['unresolved']):,}")
    add(f"- Non-trivial strongly connected components: {len(inv['include_graph']['strongly_connected'])}")
    add("")
    if inv["include_graph"]["unresolved"]:
        add("### Unresolved quoted includes")
        add("")
        for u in inv["include_graph"]["unresolved"][:80]:
            add(f"- `{u['from']}` → `{u['include']}`")
        if len(inv["include_graph"]["unresolved"]) > 80:
            add(f"- … {len(inv['include_graph']['unresolved']) - 80} more (see JSON)")
        add("")
    if inv["include_graph"]["strongly_connected"]:
        add("### Include cycles (SCCs)")
        add("")
        for comp in inv["include_graph"]["strongly_connected"]:
            add(f"- {', '.join('`' + c + '`' for c in comp)}")
        add("")
    add("## Orphan files")
    add("")
    add("Source files that are neither named in CMake nor covered by a "
        "directory `build*.sh`, and are not tests/gates. These are candidates "
        "for the Phase 0/1 cleanup, not for a move.")
    add("")
    if not inv["orphans"]:
        add("None.")
    else:
        for p in inv["orphans"][:200]:
            add(f"- `{p}`")
        if len(inv["orphans"]) > 200:
            add(f"- … {len(inv['orphans']) - 200} more (see JSON)")
    add("")
    add("## Files")
    add("")
    add("`CMake` = named in a CMakeLists.txt (or covered by its GLOB); "
        "`target` = inferred owning target; `gen` = generated-file marker.")
    add("")
    add("| File | LOC | CMake | target | build*.sh | namespace(s) | test | gate | gen |")
    add("|---|---:|:---:|---|---|---|---|:---:|:---:|:---:|")
    for f in inv["files"]:
        build = "<br>".join(f"`{Path(b).name}`" for b in f["build_scripts"]) or "-"
        tgt = ", ".join(f["cmake_targets"]) or "-"
        ns = ", ".join(f["namespaces"]) or "-"
        add(f"| `{f['path']}` | {f['loc']:,} | "
            f"{'yes' + (' (glob)' if f['cmake_glob'] else '') if f['in_cmake'] else '-'} | "
            f"{tgt} | {build} | {ns} | "
            f"{'yes' if f['test_present'] else '-'} | "
            f"{'yes' if f['gate_present'] else '-'} | "
            f"{'yes' if f['generated'] else '-'} |")
    add("")
    return "\n".join(lines) + "\n"


