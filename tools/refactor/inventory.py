@dataclass
class FileRec:
    path: Path
    rel: str
    text: str
    clean: str
    loc: int


def walk_sources(src_root: Path, ignored: list[str]) -> list[FileRec]:
    records: list[FileRec] = []
    for dirpath, dirnames, filenames in os.walk(src_root):
        dpath = Path(dirpath)
        kept = []
        for d in sorted(dirnames):
            full = dpath / d
            if d in SKIP_DIR_NAMES or BUILD_DIR_RE.match(d) or d == "_cache":
                try:
                    ignored.append(relpath(full, src_root.parent))
                except ValueError:
                    ignored.append(str(full))
                continue
            kept.append(d)
        dirnames[:] = kept
        for name in sorted(filenames):
            p = dpath / name
            if p.suffix.lower() not in SOURCE_EXTS:
                continue
            text = read_text(p)
            if text is None:
                continue
            clean = strip_comments(text)
            loc = text.count("\n") + (0 if text.endswith("\n") else 1)
            records.append(FileRec(p, relpath(p, p.parents[0]), text, clean, loc))
    # FileRec.rel was only a placeholder; recompute against repo root later
    return records


# ---------------------------------------------------------------------------
# namespaces, includes, helpers
# ---------------------------------------------------------------------------

def namespaces_in(clean: str) -> list[str]:
    found = set()
    for m in re.finditer(r"\bnamespace\s+([A-Za-z_]\w*(?:::\w+)*)\s*\{", clean):
        found.add(m.group(1))
    if re.search(r"\bnamespace\s*\{", clean):
        found.add("(anonymous)")
    return sorted(found)


def quoted_includes(clean: str) -> list[str]:
    return [m.group(1) for m in re.finditer(
        r'^[ \t]*#[ \t]*include[ \t]*"([^"]+)"', clean, re.MULTILINE)]


def matching_paren(text: str, open_idx: int) -> int | None:
    depth = 0
    i = open_idx
    while i < len(text):
        c = text[i]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return None


def helper_definitions(clean: str, raw: str, symbol: str) -> list[tuple[int, str]]:
    """Return [(line, signature)] for definitions of symbol (calls excluded)."""
    defs: list[tuple[int, str]] = []
    pat = re.compile(r"\b" + re.escape(symbol) + r"\s*\(")
    for m in pat.finditer(clean):
        open_idx = clean.find("(", m.start())
        if open_idx < 0:
            continue
        # reject calls: look at the preceding non-space token/char.  `&` and
        # `*` are intentionally allowed: they are common in return types
        # (`const QpSlice& coeff_cdf_slice`), and a call followed by `{` is
        # not valid C++ outside a control statement (handled below).
        j = m.start() - 1
        while j >= 0 and clean[j].isspace():
            j -= 1
        if j >= 0 and clean[j] in "=.,?:([!":
            continue
        prev_word = ""
        k = j
        while k >= 0 and (clean[k].isalnum() or clean[k] == "_"):
            k -= 1
        prev_word = clean[k + 1:j + 1]
        if prev_word in CONTROL_WORDS:
            continue
        close_idx = matching_paren(clean, open_idx)
        if close_idx is None:
            continue
        tail = clean[close_idx + 1:close_idx + 400]
        t = 0
        while t < len(tail) and tail[t].isspace():
            t += 1
        # qualifiers between ) and {
        rest = tail[t:]
        # allow const/noexcept/override/final/&/&&/try and a trailing return type
        if rest.startswith("->"):
            brace = rest.find("{")
            semi = rest.find(";")
            if brace < 0 or (0 <= semi < brace):
                continue
            after = rest[brace:brace + 1]
        else:
            q = re.match(
                r"(?:(?:const|noexcept(?:\([^)]*\))?|override|final|try|&&|&)\s*)*",
                rest)
            after = rest[q.end():q.end() + 1] if q else ""
        if after != "{":
            continue
        line = line_of(clean, m.start())
        raw_line = raw.splitlines()[line - 1].strip() if raw.splitlines() else symbol
        # include a little context from the signature line only; keep it short
        sig = re.sub(r"\s+", " ", raw_line)[:180]
        defs.append((line, sig))
    # de-duplicate identical line hits
    return sorted(set(defs))


# ---------------------------------------------------------------------------
# tests / gates / generated
# ---------------------------------------------------------------------------

def is_test_name(name: str) -> bool:
    return bool(re.search(r"(^test_|_test\.|_test$|\.test\.)", name))


def is_gate_name(name: str) -> bool:
    return bool(re.search(r"(^gate_|_gate\.|_gate$|gate\.cpp$)", name))


def find_scripts(src_root: Path) -> dict[str, list[str]]:
    by_dir: dict[str, list[str]] = defaultdict(list)
    for dirpath, dirnames, filenames in os.walk(src_root):
        dirnames[:] = [d for d in dirnames if not BUILD_DIR_RE.match(d)
                       and d not in SKIP_DIR_NAMES and d != "_cache"]
        dpath = Path(dirpath)
        for name in filenames:
            if name.startswith("build") and name.endswith(".sh"):
                by_dir[str(dpath.resolve())].append(
                    relpath(dpath / name, src_root.parent))
    return by_dir


def generator_scripts(root: Path, src_root: Path) -> list[Path]:
    out = []
    for base in (src_root, root / "tools", root / "spec"):
        if not base.exists():
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = [d for d in dirnames if not BUILD_DIR_RE.match(d)
                           and d not in SKIP_DIR_NAMES and d != "_cache"]
            for name in filenames:
                if GENERATOR_RE.match(name):
                    out.append(Path(dirpath) / name)
    return sorted(set(out))


def likely_generator(path: Path, scripts: list[Path], script_texts: dict[Path, str],
                     root: Path) -> str | None:
    # same directory first; otherwise require the script to name the file
    for s in scripts:
        if s.parent == path.parent:
            return relpath(s, root)
    for s in scripts:
        text = script_texts.get(s, "")
        if path.name not in text and path.stem not in text:
            continue
        if path.parent in s.parents or s.parent in path.parents:
            return relpath(s, root)
    for s in scripts:
        if path.name in script_texts.get(s, ""):
            return relpath(s, root)
    return None


# ---------------------------------------------------------------------------
# include graph / SCC
# ---------------------------------------------------------------------------

def strongly_connected(nodes: list[str], edges: dict[str, list[str]]) -> list[list[str]]:
    """Iterative Tarjan to keep recursion depth out of the picture."""
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    on_stack: set[str] = set()
    stack: list[str] = []
    result: list[list[str]] = []
    counter = 0
    for start in nodes:
        if start in index:
            continue
        work: list[tuple[str, int]] = [(start, 0)]
        index[start] = low[start] = counter
        counter += 1
        stack.append(start)
        on_stack.add(start)
        while work:
            node, pi = work[-1]
            nbrs = edges.get(node, [])
            if pi < len(nbrs):
                work[-1] = (node, pi + 1)
                nxt = nbrs[pi]
                if nxt not in index:
                    index[nxt] = low[nxt] = counter
                    counter += 1
                    stack.append(nxt)
                    on_stack.add(nxt)
                    work.append((nxt, 0))
                elif nxt in on_stack:
                    low[node] = min(low[node], index[nxt])
            else:
                work.pop()
                if work:
                    parent = work[-1][0]
                    low[parent] = min(low[parent], low[node])
                if low[node] == index[node]:
                    comp = []
                    while True:
                        w = stack.pop()
                        on_stack.discard(w)
                        comp.append(w)
                        if w == node:
                            break
                    if len(comp) > 1 or (len(comp) == 1 and comp[0] in edges.get(comp[0], [])):
                        result.append(sorted(comp))
    return sorted(result)


