#!/usr/bin/env python3
"""Generate src/pipeline/planner/effort_table.inc from the measured table.

The runtime selector must be deterministic and offline, so the measured feature
table is compiled in.  This script is the only writer of the generated include:

  tools/effort/gen_table.py --table tools/effort/effort_table.json \
      --out src/pipeline/planner/effort_table.inc
  tools/effort/gen_table.py --check ...     # non-zero if the include is stale

It refuses to emit a row whose measurements are missing.  Excluded features
still need the measured fields (that is how the exclusion is justified); they
carry eligible=false and an exclude_reason.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def die(msg: str) -> "None":
    raise SystemExit(f"gen_table: error: {msg}")


def cstr(value: str) -> str:
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            die(f"non-ASCII character in generated string: {value!r}")
    return '"' + "".join(out) + '"'


def num(value, field: str) -> float:
    if value is None or not isinstance(value, (int, float)):
        die(f"missing numeric field '{field}'")
    return float(value)


def opt_num(value) -> float:
    return float(value) if isinstance(value, (int, float)) else 0.0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--table", default=str(ROOT / "tools" / "effort" / "effort_table.json"))
    ap.add_argument("--out", default=str(ROOT / "src" / "pipeline" / "planner" /
                                        "effort_table.inc"))
    ap.add_argument("--check", action="store_true",
                    help="fail if the output file is not what would be generated")
    args = ap.parse_args()

    table_path = Path(args.table).expanduser().resolve()
    if not table_path.is_file():
        die(f"table not found: {table_path} (run tools/effort/effort_calibrate.py)")
    table = json.loads(table_path.read_text())
    features = table.get("features")
    if not isinstance(features, list) or not features:
        die("table has no features")
    ranking = table.get("ranking") or []
    if not ranking:
        die("table has no ranking")

    required = ["flag", "mode", "score", "d_cvvdp_pct", "d_time_pct", "d_rate_pct",
                "bitrate_anchor_kbps", "resolution_class", "repeats", "confidence",
                "source", "eligible"]
    for row in features:
        for key in required:
            if key not in row:
                die(f"feature {row.get('flag', '?')}: missing field '{key}'")
        if not isinstance(row["eligible"], bool):
            die(f"feature {row['flag']}: eligible must be true or false")
        if not row["eligible"] and not row.get("exclude_reason"):
            die(f"feature {row['flag']}: excluded row has no exclude_reason")
        if not isinstance(row["repeats"], int) or row["repeats"] < 1:
            die(f"feature {row['flag']}: bad repeat count")
        if row["confidence"] not in ("high", "medium", "low"):
            die(f"feature {row['flag']}: bad confidence")

    lines: list[str] = []
    lines.append("// Generated by tools/effort/gen_table.py. Do not edit by hand.")
    lines.append("// Source: tools/effort/effort_table.json")
    lines.append("//")
    lines.append("// Scores are host-specific. Re-run tools/effort/effort_calibrate.py")
    lines.append("// on the target host; see docs/effort.md.")
    lines.append("")
    lines.append("struct Feature {")
    lines.append("  const char* flag;")
    lines.append("  int mode;  // 0 = still, 1 = video")
    lines.append("  double score;")
    lines.append("  double marginal_score;  // <0: -1 = not measured, -2 = measured ineligible")
    lines.append("  double marginal_d_time_pct;")
    lines.append("  double marginal_d_rate_pct;")
    lines.append("  double d_cvvdp_pct;")
    lines.append("  double d_time_pct;")
    lines.append("  double d_rate_pct;")
    lines.append("  double anchor_kbps;")
    lines.append("  const char* resolution_class;")
    lines.append("  int repeats;")
    lines.append("  const char* confidence;")
    lines.append("  const char* source;")
    lines.append("  bool eligible;")
    lines.append("  const char* exclude_reason;")
    lines.append("  const char* conflicts[4];")
    lines.append("  bool requires_cfl;")
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr Feature kFeatures[] = {")
    for row in features:
        mode = {"still": 0, "video": 1}.get(row["mode"])
        if mode is None:
            die(f"feature {row['flag']}: mode must be still or video")
        if row.get("marginal_score") is None:
            marginal = -1.0
        elif row.get("marginal_eligible") is False:
            marginal = -2.0
        else:
            marginal = float(row["marginal_score"])
        reason = row.get("exclude_reason")
        conflicts = list(row.get("conflicts", []))
        if len(conflicts) > 4:
            die(f"feature {row['flag']}: too many conflicts")
        conflict_text = ", ".join(
            cstr(c) if c is not None else "nullptr"
            for c in conflicts + [None] * (4 - len(conflicts)))
        lines.append(
            "    {%s, %d, %.1f, %.1f, %.4f, %.4f, %.4f, %.4f, %.4f, %.1f, %s, %d, %s, %s, %s, %s, "
            "{%s}, %s}," % (
                cstr(row["flag"]), mode,
                num(row["score"], f"{row['flag']}.score"), marginal,
                opt_num(row.get("marginal_d_time_pct")),
                opt_num(row.get("marginal_d_rate_pct")),
                num(row["d_cvvdp_pct"], f"{row['flag']}.d_cvvdp_pct"),
                num(row["d_time_pct"], f"{row['flag']}.d_time_pct"),
                num(row["d_rate_pct"], f"{row['flag']}.d_rate_pct"),
                num(row["bitrate_anchor_kbps"], f"{row['flag']}.bitrate_anchor_kbps"),
                cstr(row["resolution_class"]), row["repeats"],
                cstr(row["confidence"]), cstr(row["source"]),
                "true" if row["eligible"] else "false",
                cstr(reason) if reason else "nullptr",
                conflict_text,
                "true" if row.get("requires_cfl") else "false"))
    lines.append("};")
    lines.append("inline constexpr int kFeatureCount = %d;" % len(features))
    lines.append("")

    prefix = table.get("prefix_validation")
    lines.append("struct PrefixValidation {")
    lines.append("  const char* flags;")
    lines.append("  double additive_score;")
    lines.append("  double score;")
    lines.append("  double d_time_pct;")
    lines.append("  double d_rate_pct;")
    lines.append("  bool measured;")
    lines.append("};")
    if prefix:
        flags_text = " ".join(prefix.get("flags") or [])
        lines.append("inline constexpr PrefixValidation kPrefixValidation = {")
        lines.append("    %s, %.1f, %.1f, %.4f, %.4f, %s};" % (
            cstr(flags_text),
            num(prefix.get("additive_score"), "prefix.additive_score"),
            opt_num(prefix.get("score")),
            opt_num(prefix.get("measured_d_time_pct")),
            opt_num(prefix.get("measured_d_rate_pct")),
            "true" if prefix.get("measured_d_time_pct") is not None else "false"))
    else:
        lines.append("inline constexpr PrefixValidation kPrefixValidation = "
                     "{\"\", 0.0, 0.0, 0.0, 0.0, false};")
    lines.append("")

    host = table.get("host", {}).get("cpu_model") or "unknown"
    metric = table.get("metric", {})
    fixture = table.get("fixture", {})
    fixture_path = fixture.get("path", "?")
    try:
        fixture_path = str(Path(fixture_path).resolve().relative_to(ROOT))
    except (ValueError, OSError):
        pass
    fixture_text = "%s (%dx%d, %s)" % (
        fixture_path, fixture.get("width", 0),
        fixture.get("height", 0), fixture.get("resolution_class", "?"))
    lines.append("inline constexpr double kScoreAnchorKbps = %.1f;" %
                 num(table.get("score_anchor_kbps"), "score_anchor_kbps"))
    lines.append("inline constexpr double kScoreScale = %.8f;" %
                 num(table.get("score_scale"), "score_scale"))
    lines.append("inline constexpr const char* kCalibrationHost = %s;" % cstr(host))
    lines.append("inline constexpr const char* kCalibrationMetric = %s;" % cstr(
        "%s %s (%s)" % (metric.get("name", "?"), metric.get("version", "?"),
                        metric.get("display", "?"))))
    lines.append("inline constexpr const char* kCalibrationFixture = %s;" % cstr(fixture_text))
    lines.append("inline constexpr bool kPsnrFallback = %s;" %
                 ("true" if metric.get("psnr_fallback") else "false"))
    lines.append("")
    uncal = table.get("uncalibrated") or []
    if uncal:
        lines.append("inline constexpr const char* kUncalibrated[] = {")
        for item in uncal:
            lines.append("    %s," % cstr(str(item)))
        lines.append("};")
        lines.append("inline constexpr int kUncalibratedCount = %d;" % len(uncal))
    else:
        lines.append("inline constexpr const char* kUncalibrated[] = {nullptr};")
        lines.append("inline constexpr int kUncalibratedCount = 0;")
    lines.append("")

    text = "\n".join(lines)
    out = Path(args.out).expanduser().resolve()
    if args.check:
        if not out.is_file():
            die(f"generated include missing: {out}")
        if out.read_text() != text:
            die(f"{out} is stale; run tools/effort/gen_table.py")
        print(f"gen_table: {out} is up to date")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"gen_table: wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
