// Device-side AV2 warp prediction, corner generation and sample collection.
//
// SHARED WITH EMULATION. This header is the single transcription of the
// arithmetic. It is compiled twice:
//   * by nvcc for the kernels in `warp_stack.cu` (`__device__` is real);
//   * by the host compiler for `warp_stack_host_ref.cpp` and the emulation
//     test, with `__device__`/`__forceinline__` stubbed.
// There is no second implementation, so bit-exact CPU-vs-GPU parity follows
// from the shared code, not from a tolerance.
//
// Normative sources:
//   §7.12.2.3/.4  generate points from corners, get_warp_motion_vector_xy_pos
//   §7.12.3       find warp samples / add sample / above_sample_stored
//   §7.13.3.19    block warp (8x8 sections)
//   §7.13.3.20    extended warp (4x4 sections, unscaled and scaled refs)
//   §7.13.3.21    setup shear (via the shared advanced header)
//   §7.13.3.23    reduce_warp_model / get_warp_translation / least squares
//
// The block/extended predictors accept any 1..64 sample block. Bit depth is a
// job property: 8-bit reads uint8_t, 10-bit reads uint16_t, and the final clip
// uses `1 << bit_depth`. The filter arithmetic is bit-depth independent (§9.5
// filters sum to 128), which is why a 10-bit sample produces a 10-bit result
// through the same `Round2` chain.

#include <cstddef>
#include <cstdint>

#include "warp_stack_types.h"

#if defined(__CUDACC__)
#define AV2ENC_WS_HD __host__ __device__
#define AV2ENC_WS_DEV __device__
#else
#define AV2ENC_WS_HD
#define AV2ENC_WS_DEV
#endif

namespace av2enc::cuda::warpstack {

// ---------------------------------------------------------------------------
// Generic plane read
// ---------------------------------------------------------------------------

template <typename Sample>
struct WarpPlane {
  const Sample* data = nullptr;
  int stride = 0;
  int max_x = 0;
  int max_y = 0;
};

template <typename Sample>
AV2ENC_WS_DEV inline int ws_read(const WarpPlane<Sample>& ref, int row, int col) {
  return static_cast<int>(
      ref.data[static_cast<std::ptrdiff_t>(row) * static_cast<std::ptrdiff_t>(ref.stride) +
               static_cast<std::ptrdiff_t>(col)]);
}


