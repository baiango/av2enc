AV2ENC_WS_HD inline bool ws_needs_extended(const ia::WarpParams& params, int w, int h,
                                           int ref_w, int ref_h, int frame_w, int frame_h) {
  return !ia::setup_shear(params).valid || w < 8 || h < 8 ||
         ia::is_scaled_ref(ref_w, ref_h, frame_w, frame_h);
}

// ---------------------------------------------------------------------------
// §7.13.3.19 block warp, 8x8 section.
// Mirrors advanced/warp_common.h exactly, generalised to any sample type.
// ---------------------------------------------------------------------------

AV2ENC_WS_DEV inline bool ws_block_prepare(const ia::WarpParams& params, int x, int y, int i8,
                                           int j8, int sub_x, int sub_y,
                                           ia::BlockWarpState* state) {
  const ia::ShearParams shear = ia::setup_shear(params);
  if (!shear.valid) {
    return false;
  }
  const int src_x = (x + j8 * 8 + 4) << sub_x;
  const int src_y = (y + i8 * 8 + 4) << sub_y;
  const int dst_x = params.p[2] * src_x + params.p[3] * src_y + params.p[0];
  const int dst_y = params.p[4] * src_x + params.p[5] * src_y + params.p[1];
  const int x4 = dst_x >> sub_x;
  const int y4 = dst_y >> sub_y;
  state->shear = shear;
  state->ix4 = x4 >> ia::kWarpedModelPrecBits;
  state->sx4 = x4 & ((1 << ia::kWarpedModelPrecBits) - 1);
  state->iy4 = y4 >> ia::kWarpedModelPrecBits;
  state->sy4 = y4 & ((1 << ia::kWarpedModelPrecBits) - 1);
  return true;
}

template <typename Sample>
AV2ENC_WS_DEV inline std::int32_t ws_block_intermediate_value(const WarpPlane<Sample>& ref,
                                                              const ia::BlockWarpState& state,
                                                              int i1, int i2) {
  const ia::ShearParams& shear = state.shear;
  const int ref_row = ia::clip3(0, ref.max_y, state.iy4 + i1);
  const int sx = state.sx4 + shear.alpha * i2 + shear.beta * i1;
  const int offs = ia::round2(sx, ia::kWarpedDiffPrecBits) + ia::kWarpZeroPhase;
  const int taps =
      offs >= 0 && offs < ia::kWarpedFilterRows ? offs : ia::kWarpZeroPhase;
  int s = 0;
  for (int i3 = 0; i3 < ia::kWarpedFilterTaps; ++i3) {
    const int col = ia::clip3(0, ref.max_x, state.ix4 + i2 - 3 + i3);
    s += static_cast<int>(kWarpedFiltersTable[taps][i3]) *
         ws_read(ref, ref_row, col);
  }
  return ia::round2(s, ia::kInterRound0);
}

AV2ENC_WS_DEV inline std::int16_t ws_block_store_value(const ia::BlockWarpState& state, int i1,
                                                       int i2,
                                                       const std::int32_t* intermediate,
                                                       int inter_round1, bool clip_output,
                                                       int bit_depth) {
  const ia::ShearParams& shear = state.shear;
  const int sy = state.sy4 + shear.gamma * i2 + shear.delta * i1;
  const int offs = ia::round2(sy, ia::kWarpedDiffPrecBits) + ia::kWarpZeroPhase;
  const int taps =
      offs >= 0 && offs < ia::kWarpedFilterRows ? offs : ia::kWarpZeroPhase;
  int s = 0;
  for (int i3 = 0; i3 < ia::kWarpedFilterTaps; ++i3) {
    s += static_cast<int>(kWarpedFiltersTable[taps][i3]) *
         intermediate[(i1 + i3 + 4) * ia::kBlockWarpCols + (i2 + 4)];
  }
  const int value = ia::round2(s, inter_round1);
  return static_cast<std::int16_t>(clip_output ? ia::clip1(value, bit_depth) : value);
}

AV2ENC_WS_DEV inline void ws_block_store(const ia::BlockWarpState& state, int i8, int j8,
                                         int block_w, int block_h, int inter_round1,
                                         bool clip_output, int out_x0, int out_y0,
                                         const std::int32_t* intermediate, std::int16_t* dst,
                                         int dst_stride, int bit_depth) {
  for (int i1 = -4; i1 < 4; ++i1) {
    const int local_y = i8 * 8 + i1 + 4;
    if (local_y < 0 || local_y >= block_h) {
      continue;
    }
    std::int16_t* dst_row =
        dst + static_cast<std::ptrdiff_t>(out_y0 + local_y) * dst_stride + out_x0;
    for (int i2 = -4; i2 < 4; ++i2) {
      const int local_x = j8 * 8 + i2 + 4;
      if (local_x < 0 || local_x >= block_w) {
        continue;
      }
      dst_row[local_x] = ws_block_store_value(state, i1, i2, intermediate, inter_round1,
                                              clip_output, bit_depth);
    }
  }
}

template <typename Sample>
AV2ENC_WS_DEV inline void ws_block_section(const ia::WarpParams& params,
                                           const WarpPlane<Sample>& ref, int x, int y, int i8,
                                           int j8, int block_w, int block_h, int sub_x, int sub_y,
                                           int inter_round1, bool clip_output, int out_x0,
                                           int out_y0, std::int32_t* intermediate,
                                           std::int16_t* dst, int dst_stride, int bit_depth) {
  ia::BlockWarpState state{};
  if (!ws_block_prepare(params, x, y, i8, j8, sub_x, sub_y, &state)) {
    return;
  }
  for (int t = 0; t < ia::kBlockWarpRows * ia::kBlockWarpCols; ++t) {
    const int i1 = t / ia::kBlockWarpCols - 7;
    const int i2 = t % ia::kBlockWarpCols - 4;
    intermediate[t] = ws_block_intermediate_value(ref, state, i1, i2);
  }
  ws_block_store(state, i8, j8, block_w, block_h, inter_round1, clip_output, out_x0, out_y0,
                 intermediate, dst, dst_stride, bit_depth);
}

// ---------------------------------------------------------------------------
// §7.13.3.20 extended warp, 4x4 section.
// ---------------------------------------------------------------------------

AV2ENC_WS_DEV inline bool ws_ext_prepare(const ia::WarpParams& params, int last_x, int last_y,
                                         const ia::ExtWarpContext& ctx, int x, int y, int i4,
                                         int j4, ia::ExtWarpSection* out) {
  const int i8 = i4 >> 1;
  const int j8 = j4 >> 1;
  const int bbox_w = ctx.block_w < 8 ? ctx.block_w : 8;
  const int bbox_h = ctx.block_h < 8 ? ctx.block_h : 8;
  const int sub_x = ctx.sub_x;
  const int sub_y = ctx.sub_y;

  int mv[2] = {0, 0};
  ia::get_sub_block_warp_mv(params, ctx.plane, sub_x, sub_y, x + j8 * 8, y + i8 * 8, bbox_w,
                            bbox_h, 0, mv);
  mv[0] = ia::clamp_mv_row(mv[0], ctx.mi_row, ctx.bh4, ctx.mi_rows);
  mv[1] = ia::clamp_mv_col(mv[1], ctx.mi_col, ctx.bw4, ctx.mi_cols);

  const ia::MvScaleOutput scale = ia::motion_vector_scaling(
      ctx.plane, sub_x, sub_y, x + j8 * 8, y + i8 * 8, mv, false, ctx.ref_w, ctx.ref_h,
      ctx.frame_w, ctx.frame_h);

  int first_x = scale.start_x >> ia::kScaleSubpelBits;
  int first_y = scale.start_y >> ia::kScaleSubpelBits;
  first_x = ia::clip3(0, last_x, first_x - 3);
  first_y = ia::clip3(0, last_y, first_y - 3);
  const int bbox_last_x = ia::clip3(
      0, last_x, ((scale.start_x + scale.step_x * (bbox_w - 1)) >> ia::kScaleSubpelBits) + 4);
  const int bbox_last_y = ia::clip3(
      0, last_y, ((scale.start_y + scale.step_y * (bbox_h - 1)) >> ia::kScaleSubpelBits) + 4);

  const int src_x = (x + j4 * 4 + 2) << sub_x;
  const int src_y = (y + i4 * 4 + 2) << sub_y;
  const int dst_x = params.p[2] * src_x + params.p[3] * src_y + params.p[0];
  const int dst_y = params.p[4] * src_x + params.p[5] * src_y + params.p[1];

  out->scaled = ctx.scaled;
  out->first_x = first_x;
  out->first_y = first_y;
  out->bbox_last_x = bbox_last_x;
  out->bbox_last_y = bbox_last_y;
  out->out_x4 = dst_x >> sub_x;
  out->out_y4 = dst_y >> sub_y;
  out->step_x = 0;
  out->step_y = 0;

  if (ctx.scaled) {
    const int x_scale = ((ctx.ref_w << ia::kRefScaleShift) + ctx.frame_w / 2) / ctx.frame_w;
    const int y_scale = ((ctx.ref_h << ia::kRefScaleShift) + ctx.frame_h / 2) / ctx.frame_h;
    out->out_x4 -= 2 << ia::kWarpedModelPrecBits;
    out->out_y4 -= 2 << ia::kWarpedModelPrecBits;
    out->out_x4 = ia::round2_signed(out->out_x4 * x_scale, ia::kRefScaleShift);
    out->out_y4 = ia::round2_signed(out->out_y4 * y_scale, ia::kRefScaleShift);
    out->step_x = ia::round2_signed(x_scale, ia::kRefScaleShift - ia::kScaleSubpelBits)
                  << (ia::kWarpedModelPrecBits - ia::kScaleSubpelBits);
    out->step_y = ia::round2_signed(y_scale, ia::kRefScaleShift - ia::kScaleSubpelBits)
                  << (ia::kWarpedModelPrecBits - ia::kScaleSubpelBits);
  }

  out->iy4 = out->out_y4 >> ia::kWarpedModelPrecBits;
  out->sy4 = out->out_y4 & ((1 << ia::kWarpedModelPrecBits) - 1);
  out->ix4 = out->out_x4 >> ia::kWarpedModelPrecBits;
  out->sx4 = out->out_x4 & ((1 << ia::kWarpedModelPrecBits) - 1);
  out->rows = ctx.scaled ? ia::ext_warp_intermediate_rows(out->out_y4, out->step_y) : 9;
  return out->rows > 0 && out->rows <= ia::kExtWarpRows;
}

template <typename Sample>
AV2ENC_WS_DEV inline std::int32_t ws_ext_intermediate_value(const WarpPlane<Sample>& ref,
                                                            const ia::ExtWarpSection& sec,
                                                            int idx) {
  if (!sec.scaled) {
    const int k = idx / 4 - 4;
    const int l = idx % 4 - 2;
    const int offs_x =
        ia::clip3(0, ia::kExtWarpFilterRows - 1, ia::round2(sec.sx4, ia::kExtWarpRoundBits));
    const int int_y = ia::clip3(sec.first_y, sec.bbox_last_y, sec.iy4 + k);
    int s = 0;
    for (int m = 0; m < ia::kExtWarpTaps; ++m) {
      const int col = ia::clip3(sec.first_x, sec.bbox_last_x, sec.ix4 + l - 2 + m);
      s += static_cast<int>(kExtWarpedFiltersTable[offs_x][m]) *
           ws_read(ref, int_y, col);
    }
    return ia::round2(s, ia::kInterRound0);
  }
  const int k = idx / 4;
  const int l = idx % 4;
  const int int_y = ia::clip3(sec.first_y, sec.bbox_last_y, sec.iy4 + k - 2);
  const int pos = sec.out_x4 + sec.step_x * l;
  const int ix4 = pos >> ia::kWarpedModelPrecBits;
  const int sx4 = pos & ((1 << ia::kWarpedModelPrecBits) - 1);
  const int offs =
      ia::clip3(0, ia::kExtWarpFilterRows - 1, ia::round2(sx4, ia::kExtWarpRoundBits));
  int s = 0;
  for (int m = 0; m < ia::kExtWarpTaps; ++m) {
    const int col = ia::clip3(sec.first_x, sec.bbox_last_x, ix4 - 2 + m);
    s += static_cast<int>(kExtWarpedFiltersTable[offs][m]) * ws_read(ref, int_y, col);
  }
  return ia::round2(s, ia::kInterRound0);
}

AV2ENC_WS_DEV inline std::int16_t ws_ext_store_value(const ia::ExtWarpSection& sec, int k, int l,
                                                     const std::int32_t* intermediate,
                                                     int inter_round1, bool clip_output,
                                                     int bit_depth) {
  int value;
  if (!sec.scaled) {
    const int offs_y =
        ia::clip3(0, ia::kExtWarpFilterRows - 1, ia::round2(sec.sy4, ia::kExtWarpRoundBits));
    int s = 0;
    for (int m = 0; m < ia::kExtWarpTaps; ++m) {
      s += static_cast<int>(kExtWarpedFiltersTable[offs_y][m]) *
           intermediate[(k + m + 2) * ia::kExtWarpCols + (l + 2)];
    }
    value = ia::round2(s, inter_round1);
  } else {
    const int pos = sec.out_y4 + sec.step_y * k;
    const int iy_off = (pos >> ia::kWarpedModelPrecBits) - sec.iy4;
    const int sy4 = pos & ((1 << ia::kWarpedModelPrecBits) - 1);
    const int offs =
        ia::clip3(0, ia::kExtWarpFilterRows - 1, ia::round2(sy4, ia::kExtWarpRoundBits));
    int s = 0;
    for (int m = 0; m < ia::kExtWarpTaps; ++m) {
      s += static_cast<int>(kExtWarpedFiltersTable[offs][m]) *
           intermediate[(iy_off + m) * ia::kExtWarpCols + l];
    }
    value = ia::round2(s, inter_round1);
  }
  return static_cast<std::int16_t>(clip_output ? ia::clip1(value, bit_depth) : value);
}

AV2ENC_WS_DEV inline void ws_ext_store(const ia::ExtWarpContext& ctx,
                                       const ia::ExtWarpSection& sec, int i4, int j4,
                                       const std::int32_t* intermediate, std::int16_t* dst,
                                       int dst_stride, int bit_depth) {
  const int k_begin = sec.scaled ? 0 : -2;
  const int l_begin = sec.scaled ? 0 : -2;
  for (int k = k_begin; k < k_begin + 4; ++k) {
    const int local_y = sec.scaled ? i4 * 4 + k : i4 * 4 + k + 2;
    if (local_y < 0 || local_y >= ctx.block_h) {
      continue;
    }
    for (int l = l_begin; l < l_begin + 4; ++l) {
      const int local_x = sec.scaled ? j4 * 4 + l : j4 * 4 + l + 2;
      if (local_x < 0 || local_x >= ctx.block_w) {
        continue;
      }
      dst[static_cast<std::ptrdiff_t>(ctx.dst_y + local_y) * dst_stride + ctx.dst_x +
          local_x] = ws_ext_store_value(sec, k, l, intermediate, ctx.inter_round1,
                                        ctx.clip_output, bit_depth);
    }
  }
}

template <typename Sample>
AV2ENC_WS_DEV inline bool ws_ext_section(const ia::WarpParams& params,
                                         const WarpPlane<Sample>& ref,
                                         const ia::ExtWarpContext& ctx, int x, int y, int i4,
                                         int j4, std::int32_t* intermediate,
                                         std::int16_t* dst, int dst_stride, int bit_depth) {
  ia::ExtWarpSection sec{};
  if (!ws_ext_prepare(params, ref.max_x, ref.max_y, ctx, x, y, i4, j4, &sec)) {
    return false;
  }
  const int entries = sec.rows * ia::kExtWarpCols;
  for (int t = 0; t < entries; ++t) {
    intermediate[t] = ws_ext_intermediate_value(ref, sec, t);
  }
  ws_ext_store(ctx, sec, i4, j4, intermediate, dst, dst_stride, bit_depth);
  return true;
}

// ---------------------------------------------------------------------------
// Batched prediction body. `tid`/`nthr` replace threadIdx/blockDim so the host
// emulation can call this with (0, 1) and no CUDA runtime symbols.
// ---------------------------------------------------------------------------

AV2ENC_WS_DEV inline bool ws_job_valid(const WarpPredictJob& job) {
  if (job.ref == nullptr || job.ref_stride <= 0 || job.ref_max_x < 0 || job.ref_max_y < 0 ||
      job.ref_stride < job.ref_max_x + 1) {
    return false;
  }
  if (job.geom.rect.w <= 0 || job.geom.rect.w > 64 || job.geom.rect.h <= 0 ||
      job.geom.rect.h > 64) {
    return false;
  }
  if (job.geom.frame_w <= 0 || job.geom.frame_h <= 0) {
    return false;
  }
  if (job.geom.bit_depth != 8 && job.geom.bit_depth != 10) {
    return false;
  }
  if (job.dst == nullptr || job.dst_stride <= 0) {
    return false;
  }
  if (job.path < kWarpPathAuto || job.path > kWarpPathExtended) {
    return false;
  }
  return true;
}

template <typename Sample>
AV2ENC_WS_DEV inline void ws_predict_job_device(const WarpPredictJob& job, int tid, int nthr,
                                                std::int32_t* intermediate,
                                                WarpPredictResult* result) {
  WarpPredictResult r{};
  if (!ws_job_valid(job) || intermediate == nullptr || nthr <= 0) {
    r.status = 1;
    if (tid == 0 && result != nullptr) {
      *result = r;
    }
    return;
  }

  const int w = job.geom.rect.w;
  const int h = job.geom.rect.h;
  const int bit_depth = job.geom.bit_depth;
  const ia::ShearParams shear = ia::setup_shear(job.params);
  r.shear_valid = shear.valid ? 1 : 0;

  int path = job.path;
  if (path == kWarpPathAuto) {
    path = ws_needs_extended(job.params, w, h, job.geom.ref_w, job.geom.ref_h,
                             job.geom.frame_w, job.geom.frame_h)
               ? kWarpPathExtended
               : kWarpPathBlock;
  }
  r.path = path;

  const int inter_round1 =
      job.compound ? ia::kInterRound1Compound : ia::kInterRound1Single;
  const bool clip_output = job.compound == 0;
  const WarpPlane<Sample> ref{static_cast<const Sample*>(job.ref), job.ref_stride,
                              job.ref_max_x, job.ref_max_y};

  if (path == kWarpPathBlock) {
    for (int i8 = 0; i8 <= (h - 1) >> 3; ++i8) {
      for (int j8 = 0; j8 <= (w - 1) >> 3; ++j8) {
        ia::BlockWarpState state{};
        if (!ws_block_prepare(job.params, job.geom.rect.x, job.geom.rect.y, i8, j8,
                              job.geom.sub_x, job.geom.sub_y, &state)) {
          continue;
        }
        __syncthreads();
        for (int t = tid; t < ia::kBlockWarpRows * ia::kBlockWarpCols; t += nthr) {
          const int i1 = t / ia::kBlockWarpCols - 7;
          const int i2 = t % ia::kBlockWarpCols - 4;
          intermediate[t] = ws_block_intermediate_value(ref, state, i1, i2);
        }
        __syncthreads();
        for (int t = tid; t < 64; t += nthr) {
          const int i1 = t / 8 - 4;
          const int i2 = t % 8 - 4;
          const int local_y = i8 * 8 + i1 + 4;
          const int local_x = j8 * 8 + i2 + 4;
          if (local_y < 0 || local_y >= h || local_x < 0 || local_x >= w) {
            continue;
          }
          job.dst[static_cast<std::ptrdiff_t>(job.geom.dst_y + local_y) * job.dst_stride +
                  job.geom.dst_x + local_x] =
              ws_block_store_value(state, i1, i2, intermediate, inter_round1, clip_output,
                                   bit_depth);
        }
        ++r.sections;
      }
    }
  } else {
    ia::ExtWarpContext ctx{};
    ctx.plane = job.geom.plane;
    ctx.sub_x = job.geom.sub_x;
    ctx.sub_y = job.geom.sub_y;
    ctx.block_w = w;
    ctx.block_h = h;
    ctx.mi_col = job.geom.mi_col;
    ctx.mi_row = job.geom.mi_row;
    ctx.bw4 = job.geom.bw4;
    ctx.bh4 = job.geom.bh4;
    ctx.mi_cols = job.geom.mi_cols;
    ctx.mi_rows = job.geom.mi_rows;
    ctx.scaled = ia::is_scaled_ref(job.geom.ref_w, job.geom.ref_h, job.geom.frame_w,
                                   job.geom.frame_h);
    ctx.ref_w = job.geom.ref_w;
    ctx.ref_h = job.geom.ref_h;
    ctx.frame_w = job.geom.frame_w;
    ctx.frame_h = job.geom.frame_h;
    ctx.inter_round1 = inter_round1;
    ctx.dst_x = job.geom.dst_x;
    ctx.dst_y = job.geom.dst_y;
    ctx.clip_output = clip_output;

    for (int i4 = 0; i4 < (h >> 2); ++i4) {
      for (int j4 = 0; j4 < (w >> 2); ++j4) {
        ia::ExtWarpSection sec{};
        if (!ws_ext_prepare(job.params, ref.max_x, ref.max_y, ctx, job.geom.rect.x,
                            job.geom.rect.y, i4, j4, &sec)) {
          continue;
        }
        __syncthreads();
        const int entries = sec.rows * ia::kExtWarpCols;
        for (int t = tid; t < entries; t += nthr) {
          intermediate[t] = ws_ext_intermediate_value(ref, sec, t);
        }
        __syncthreads();
        for (int t = tid; t < 16; t += nthr) {
          const int k_local = t / 4;
          const int l_local = t % 4;
          const int k = sec.scaled ? k_local : k_local - 2;
          const int l = sec.scaled ? l_local : l_local - 2;
          const int local_y = sec.scaled ? i4 * 4 + k : i4 * 4 + k + 2;
          const int local_x = sec.scaled ? j4 * 4 + l : j4 * 4 + l + 2;
          if (local_y < 0 || local_y >= h || local_x < 0 || local_x >= w) {
            continue;
          }
          job.dst[static_cast<std::ptrdiff_t>(job.geom.dst_y + local_y) * job.dst_stride +
                  job.geom.dst_x + local_x] =
              ws_ext_store_value(sec, k, l, intermediate, inter_round1, clip_output,
                                 bit_depth);
        }
        ++r.sections;
      }
    }
  }

  if (tid == 0 && result != nullptr) {
    *result = r;
  }
}

// ---------------------------------------------------------------------------
// §7.12.2.3/.4 corner points from the mode-info grid.
// The encoder grid is `const WarpMi*`; device code cannot call the host-only
// WarpGrid methods, so the accessors are repeated here.
// ---------------------------------------------------------------------------

AV2ENC_WS_HD inline bool ws_grid_inside(const inter::warp::WarpGrid& grid, int row, int col) {
  return grid.mi != nullptr && row >= 0 && col >= 0 && row < grid.mi_rows &&
         col < grid.mi_cols;
}

AV2ENC_WS_HD inline const inter::warp::WarpMi& ws_grid_at(
    const inter::warp::WarpGrid& grid, int row, int col) {
  return grid.mi[static_cast<std::size_t>(row) * static_cast<std::size_t>(grid.mi_cols) +
                 static_cast<std::size_t>(col)];
}

AV2ENC_WS_HD inline std::int64_t ws_clamp_i64(std::int64_t value) {
  if (value > 2147483647LL) return 2147483647LL;
  if (value < -2147483648LL) return -2147483648LL;
  return value;
}

AV2ENC_WS_HD inline int ws_floor_log2(int value) {
  int n = 0;
  while (value > 1) {
    value >>= 1;
    ++n;
  }
  return n;
}

// §7.12.2.4 helper, matching warp_stack.cpp's get_warp_motion_vector_xy_pos().
AV2ENC_WS_HD inline inter::mc::Mv ws_warp_motion_vector_xy_pos(
    const ia::WarpParams& params, int pos_row, int pos_col, int mi_row, int mi_col, int bw4,
    int bh4, int mi_rows, int mi_cols) {
  const int y = pos_row * inter::warp::kMiSize;
  const int x = pos_col * inter::warp::kMiSize;
  const std::int64_t xc = std::int64_t{params.p[2]} * x +
                          std::int64_t{params.p[3]} * y + params.p[0] -
                          (std::int64_t{x} << ia::kWarpedModelPrecBits);
  const std::int64_t yc = std::int64_t{params.p[4]} * x +
                          std::int64_t{params.p[5]} * y + params.p[1] -
                          (std::int64_t{y} << ia::kWarpedModelPrecBits);
  int mv_y = static_cast<int>(
      ws_clamp_i64(ia::round2_signed64(yc, ia::kWarpedModelPrecBits - 3)));
  int mv_x = static_cast<int>(
      ws_clamp_i64(ia::round2_signed64(xc, ia::kWarpedModelPrecBits - 3)));
  mv_y = ia::clip3(ia::kMvLow + 1, ia::kMvUpp - 1, mv_y);
  mv_x = ia::clip3(ia::kMvLow + 1, ia::kMvUpp - 1, mv_x);
  mv_y = ia::clamp_mv_row(mv_y, mi_row, bh4, mi_rows);
  mv_x = ia::clamp_mv_col(mv_x, mi_col, bw4, mi_cols);
  return inter::mc::Mv{mv_y, mv_x};
}

AV2ENC_WS_HD inline bool ws_corner_process(const inter::warp::WarpGrid& grid, int sb_h4,
                                            int mi_row, int mi_col, int bw4, int bh4,
                                            std::int8_t ref_frame0, int delta_row,
                                            int delta_col, int adjust_col,
                                            inter::warp::CornerResult* out) {
  if (out == nullptr || grid.mi == nullptr) {
    return false;
  }
  const int is_sb_border = (mi_row & (sb_h4 - 1)) == 0 ? 1 : 0;
  const int mv_row = mi_row + delta_row;
  const int mv_col = mi_col + delta_col;
  delta_col += adjust_col;
  int mv_col2;
  if (delta_row < 0 && is_sb_border) {
    mv_col2 = (mi_col - (mi_col & 1)) + (delta_col - (delta_col & 1));
  } else {
    mv_col2 = mi_col + delta_col;
  }
  if (is_sb_border == 1 && delta_col == 0 && bw4 <= 2) {
    return false;
  }
  if (!ws_grid_inside(grid, mv_row, mv_col2)) {
    return false;
  }

  for (int ref = 0; ref <= 1; ++ref) {
    const inter::warp::WarpMi& n = ws_grid_at(grid, mv_row, mv_col2);
    if (!n.written || !n.is_inter) {
      continue;
    }
    if (n.ref[ref] != ref_frame0) {
      continue;
    }
    const int idx = out->corners_found;
    out->corner_pts[idx][0] = (mv_row + 1) * inter::warp::kMiSize;
    out->corner_pts[idx][1] = (mv_col + 1) * inter::warp::kMiSize;
    if (n.motion_mode >= inter::warp::kMotionLocalWarp) {
      if (ref > 0) {
        return false;
      }
      const inter::mc::Mv mv =
          ws_warp_motion_vector_xy_pos(n.warp[ref], mv_row + 1, mv_col + 1, mi_row, mi_col,
                                       bw4, bh4, grid.mi_rows, grid.mi_cols);
      out->corner_mvs[idx][0] = mv.y;
      out->corner_mvs[idx][1] = mv.x;
    } else {
      out->corner_mvs[idx][0] = n.sub_mv[ref][0];
      out->corner_mvs[idx][1] = n.sub_mv[ref][1];
    }
    ++out->corners_found;
    return true;
  }
  return false;
}

// §7.12.2.3. Returns true when a reduced warp model was built (the CPU builder
// then calls insert_warp_candidate(corner.wmmat, stack)).
AV2ENC_WS_HD inline bool ws_generate_points_from_corners(
    const inter::warp::WarpGrid& grid, int sb_h4, int mi_row, int mi_col, int bw4, int bh4,
    std::int8_t ref_frame0, int iter, inter::warp::CornerResult* out) {
  if (out == nullptr) {
    return false;
  }
  *out = inter::warp::CornerResult{};
  if (grid.mi == nullptr || bw4 <= 0 || bh4 <= 0) {
    return false;
  }
  ws_corner_process(grid, sb_h4, mi_row, mi_col, bw4, bh4, ref_frame0, -1, -1, iter, out);
  ws_corner_process(grid, sb_h4, mi_row, mi_col, bw4, bh4, ref_frame0, -1, bw4 - 1, iter, out);
  ws_corner_process(grid, sb_h4, mi_row, mi_col, bw4, bh4, ref_frame0, bh4 - 1, -1, 0, out);
  if (out->corners_found != 3) {
    out->all_mvs_same = false;
    return false;
  }

  out->all_mvs_same = true;
  for (int n = 0; n < out->corners_found; ++n) {
    for (int c = 0; c < 2; ++c) {
      const std::int64_t value =
          (std::int64_t{out->corner_pts[n][c]} << ia::kWarpedModelPrecBits) +
          (std::int64_t{out->corner_mvs[n][c]} << inter::warp::kGmTransOnlyPrecDiff);
      out->ref_pts[n][c] = static_cast<int>(ws_clamp_i64(value));
      if (out->corner_mvs[n][c] != out->corner_mvs[0][c]) {
        out->all_mvs_same = false;
      }
    }
  }
  if (out->all_mvs_same) {
    return false;
  }
  for (int n = 0; n < out->corners_found; ++n) {
    for (int c = 0; c < 2; ++c) {
      if (out->ref_pts[n][c] < 0) {
        out->negative_ref_pts = true;
        return false;
      }
    }
  }

  const int width_log2 = ws_floor_log2(bw4 * inter::warp::kMiSize);
  const int height_log2 = ws_floor_log2(bh4 * inter::warp::kMiSize);
  const int y0 = out->corner_pts[0][0];
  const int x0 = out->corner_pts[0][1];

  ia::WarpParams wmmat{};
  wmmat.p[0] = 0;
  wmmat.p[1] = 0;
  wmmat.p[2] = (out->ref_pts[1][1] - out->ref_pts[0][1]) >> width_log2;
  wmmat.p[4] = (out->ref_pts[1][0] - out->ref_pts[0][0]) >> width_log2;
  wmmat.p[3] = (out->ref_pts[2][1] - out->ref_pts[0][1]) >> height_log2;
  wmmat.p[5] = (out->ref_pts[2][0] - out->ref_pts[0][0]) >> height_log2;

  const std::int64_t wmmat0 = std::int64_t{out->ref_pts[0][1]} -
                              std::int64_t{wmmat.p[2]} * x0 -
                              std::int64_t{wmmat.p[3]} * y0;
  const std::int64_t wmmat1 = std::int64_t{out->ref_pts[0][0]} -
                              std::int64_t{wmmat.p[4]} * x0 -
                              std::int64_t{wmmat.p[5]} * y0;

  out->wmmat = ia::reduce_warp_model(wmmat);
  out->wmmat.p[0] = ia::clip3(
      -ia::kWarpedModelTransClamp,
      ia::kWarpedModelTransClamp - (1 << ia::kWarpParamReduceBits),
      static_cast<int>(ws_clamp_i64(wmmat0)));
  out->wmmat.p[1] = ia::clip3(
      -ia::kWarpedModelTransClamp,
      ia::kWarpedModelTransClamp - (1 << ia::kWarpParamReduceBits),
      static_cast<int>(ws_clamp_i64(wmmat1)));
  return true;
}

// ---------------------------------------------------------------------------
// §7.12.3 find warp samples.
// ---------------------------------------------------------------------------

AV2ENC_WS_HD inline bool ws_above_sample_stored(const inter::warp::WarpSampleParams& params,
                                                 int delta_col) {
  if (!ws_grid_inside(params.grid, params.mi_row - 1, params.mi_col + delta_col)) {
    return false;
  }
  const int is_sb_border = (params.mi_row & (params.sb_h4 - 1)) == 0 ? 1 : 0;
  if (!is_sb_border) {
    return true;
  }
  if (((params.mi_col + delta_col) % 2) == 0) {
    return true;
  }
  const inter::warp::WarpMi& n =
      ws_grid_at(params.grid, params.mi_row - 1, params.mi_col + delta_col);
  const int src_w4 = n.w4 > 1 ? n.w4 : 1;
  if (src_w4 == 1) {
    return false;
  }
  return params.mi_col + delta_col + 1 < params.mi_cols;
}

AV2ENC_WS_HD inline void ws_add_warp_sample(const inter::warp::WarpSampleParams& params,
                                             int delta_row, int delta_col,
                                             inter::warp::WarpSampleSet* out) {
  if (out == nullptr || out->num_samples >= inter::warp::kLeastSquaresSamplesMax) {
    return;
  }
  const int mv_row = params.mi_row + delta_row;
  const int mv_col = params.mi_col + delta_col;
  if (!ws_grid_inside(params.grid, mv_row, mv_col)) {
    return;
  }
  const inter::warp::WarpMi& n = ws_grid_at(params.grid, mv_row, mv_col);
  if (!n.written) {
    return;
  }
  const std::int8_t target = params.ref_frame[params.ref];
  for (int list = 0; list < 2; ++list) {
    if (n.ref[list] != target) {
      continue;
    }
    const int cand_w4 = n.w4 > 1 ? n.w4 : 1;
    const int cand_h4 = n.h4 > 1 ? n.h4 : 1;
    const int cand_row = n.row_base;
    const int cand_col = n.col_base;
    const int mid_y = cand_row * inter::warp::kMiSize + cand_h4 * 2 - 1;
    const int mid_x = cand_col * inter::warp::kMiSize + cand_w4 * 2 - 1;
    int* cand = out->cand[out->num_samples];
    cand[0] = mid_y * 8;
    cand[1] = mid_x * 8;
    cand[2] = mid_y * 8 + n.mv[list][0];
    cand[3] = mid_x * 8 + n.mv[list][1];
    ++out->num_samples;
    if (out->num_samples >= inter::warp::kLeastSquaresSamplesMax) {
      return;
    }
  }
}

AV2ENC_WS_HD inline bool ws_find_warp_samples(const inter::warp::WarpSampleParams& params,
                                              inter::warp::WarpSampleSet* out) {
  if (out == nullptr || params.grid.mi == nullptr || params.w4 <= 0 || params.h4 <= 0 ||
      params.ref < 0 || params.ref > 1) {
    return false;
  }
  *out = inter::warp::WarpSampleSet{};
  int do_top_left = 1;
  int do_top_right = 1;

  if (params.avail_u) {
    const int col_offset =
        ws_grid_at(params.grid, params.mi_row - 1, params.mi_col).col_base - params.mi_col;
    if (col_offset < 0) {
      do_top_left = 0;
    }
    int i = col_offset;
    const int limit = params.w4 < params.mi_cols - params.mi_col
                          ? params.w4
                          : params.mi_cols - params.mi_col;
    while (i < limit) {
      const inter::warp::WarpMi& n =
          ws_grid_at(params.grid, params.mi_row - 1, params.mi_col + i);
      const int src_w = n.w4 > 1 ? n.w4 : 1;
      if (ws_above_sample_stored(params, i)) {
        ws_add_warp_sample(params, -1, i, out);
      }
      i += src_w;
    }
    do_top_right = (i == params.w4) && (i < params.mi_cols - params.mi_col);
  }
  if (params.avail_l) {
    const int row_offset =
        ws_grid_at(params.grid, params.mi_row, params.mi_col - 1).row_base - params.mi_row;
    if (row_offset < 0) {
      do_top_left = 0;
    }
    int i = row_offset;
    const int limit = params.h4 < params.mi_rows - params.mi_row
                          ? params.h4
                          : params.mi_rows - params.mi_row;
    while (i < limit) {
      const inter::warp::WarpMi& n =
          ws_grid_at(params.grid, params.mi_row + i, params.mi_col - 1);
      const int src_h = n.h4 > 1 ? n.h4 : 1;
      ws_add_warp_sample(params, i, -1, out);
      i += src_h;
    }
  }
  if (do_top_left && ws_above_sample_stored(params, -1)) {
    ws_add_warp_sample(params, -1, -1, out);
  }
  if (do_top_right && params.w4 <= 16 && ws_above_sample_stored(params, params.w4)) {
    ws_add_warp_sample(params, -1, params.w4, out);
  }
  return out->num_samples > 0;
}

// ---------------------------------------------------------------------------
// §7.13.3.23 least-squares model derivation.
// This is the 64-bit-determinant form used by warp_stack.cpp's
// estimate_warp_from_samples(), not the int-narrowed adv::warp_estimate().
// ---------------------------------------------------------------------------

AV2ENC_WS_HD inline int ws_ls_product(int a, int b) { return ((a * b) >> 2) + (a + b); }

AV2ENC_WS_HD inline int ws_floor_log2_64(std::int64_t value) {
  int n = 0;
  while (value > 1) {
    value >>= 1;
    ++n;
  }
  return n;
}

struct WsDiv64 {
  int shift = 0;
  std::int64_t factor = 0;
};

AV2ENC_WS_HD inline WsDiv64 ws_resolve_divisor_64(std::int64_t d) {
  const std::int64_t magnitude = d < 0 ? -d : d;
  const int n = ws_floor_log2_64(magnitude);
  const std::int64_t e = magnitude - (std::int64_t{1} << n);
  const int f = (n > ia::kDivLutBits)
                    ? static_cast<int>(ia::round2_signed64(e, n - ia::kDivLutBits))
                    : static_cast<int>(e << (ia::kDivLutBits - n));
  WsDiv64 out;
  out.shift = n + ia::kDivLutPrecBits;
  out.factor = d < 0 ? -ia::div_lut_entry(f) : ia::div_lut_entry(f);
  return out;
}

AV2ENC_WS_HD inline ia::WarpParams ws_estimate_warp_from_samples(
    const inter::warp::WarpSampleSet& samples, int mid_x, int mid_y,
    const int block_mv[2]) {
  const std::int64_t suy = std::int64_t{mid_y} * 8;
  const std::int64_t sux = std::int64_t{mid_x} * 8;
  const std::int64_t duy = suy + block_mv[0];
  const std::int64_t dux = sux + block_mv[1];

  std::int64_t a00 = 0;
  std::int64_t a01 = 0;
  std::int64_t a11 = 0;
  std::int64_t bx0 = 0;
  std::int64_t bx1 = 0;
  std::int64_t by0 = 0;
  std::int64_t by1 = 0;
  for (int i = 0; i < samples.num_samples; ++i) {
    const int sy = samples.cand[i][0] - static_cast<int>(suy);
    const int sx = samples.cand[i][1] - static_cast<int>(sux);
    const int dy = samples.cand[i][2] - static_cast<int>(duy);
    const int dx = samples.cand[i][3] - static_cast<int>(dux);
    const int adx = sx - dx < 0 ? dx - sx : sx - dx;
    const int ady = sy - dy < 0 ? dy - sy : sy - dy;
    if (adx < inter::warp::kLsMvMax && ady < inter::warp::kLsMvMax) {
      a00 += ws_ls_product(sx, sx) + 8;
      a01 += ws_ls_product(sx, sy) + 4;
      a11 += ws_ls_product(sy, sy) + 8;
      bx0 += ws_ls_product(sx, dx) + 8;
      bx1 += ws_ls_product(sy, dx) + 4;
      by0 += ws_ls_product(sx, dy) + 4;
      by1 += ws_ls_product(sy, dy) + 8;
    }
  }

  ia::WarpParams params{};
  const std::int64_t det = a00 * a11 - a01 * a01;
  if (det == 0) {
    params.p[2] = 1 << ia::kWarpedModelPrecBits;
    params.p[3] = 0;
    params.p[4] = 0;
    params.p[5] = 1 << ia::kWarpedModelPrecBits;
    ia::get_warp_translation(params, mid_x, mid_y, block_mv);
    return params;
  }

  WsDiv64 ds = ws_resolve_divisor_64(det);
  int div_shift = ds.shift - ia::kWarpedModelPrecBits;
  std::int64_t div_factor = ds.factor;
  if (div_shift < 0) {
    div_factor <<= -div_shift;
    div_shift = 0;
  }

  auto diag = [&](std::int64_t v) -> int {
    const std::int64_t rounded = ia::round2_signed64(v * div_factor, div_shift);
    return static_cast<int>(rounded > 2147483647LL
                                ? 2147483647LL
                                : (rounded < -2147483648LL ? -2147483648LL : rounded));
  };
  params.p[2] = diag(a11 * bx0 - a01 * bx1);
  params.p[3] = diag(-a01 * bx0 + a00 * bx1);
  params.p[4] = diag(a11 * by0 - a01 * by1);
  params.p[5] = diag(-a01 * by0 + a00 * by1);
  params = ia::reduce_warp_model(params);
  ia::get_warp_translation(params, mid_x, mid_y, block_mv);
  return params;
}

