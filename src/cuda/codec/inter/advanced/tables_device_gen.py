#!/usr/bin/env python3
"""Generate `tables_device.cuh` from the CPU advanced-inter spec tables.

nvcc cannot odr-use a namespace-scope host `constexpr` array from device code
("identifier is undefined in device code").  The shared helpers in
`codec/inter/advanced/{advanced,warp}_common.h` index the CPU tables directly,
so the CUDA advanced-inter component mirrors every table with `__device__`
storage under `__CUDA_ARCH__` and host storage otherwise, then macro-redirects
the identifiers in `advanced.cu`.

Run from this directory:

    python3 tables_device_gen.py
"""

from __future__ import annotations

import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[4]
TABLES = REPO / "src" / "codec" / "inter" / "advanced" / "tables"
FILES = ("wedge_tables.h", "warp_filters.h")
OUT = HERE / "tables_device.cuh"

NAMESPACE_OPEN = "namespace av2enc::inter::adv::tables {"
NAMESPACE_CLOSE = "}  // namespace av2enc::inter::adv::tables"


def namespace_body(path: pathlib.Path) -> str:
    text = path.read_text()
    start = text.index(NAMESPACE_OPEN) + len(NAMESPACE_OPEN)
    end = text.index(NAMESPACE_CLOSE)
    return text[start:end]


def declarations(body: str):
    """Return (arrays, scalars) as (name, kind) pairs."""
    arrays = []
    scalars = []
    for m in re.finditer(
        r"inline constexpr\s+([A-Za-z_][A-Za-z0-9_:<> ]*?)\s+"
        r"([A-Za-z_][A-Za-z0-9_]*)\s*(\[[^=]*?\])\s*=",
        body,
    ):
        arrays.append(m.group(2))
    for m in re.finditer(
        r"inline constexpr\s+(?:int|std::int8_t|std::int16_t)\s+"
        r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*[^;]+;",
        body,
    ):
        name = m.group(1)
        if name not in arrays:
            scalars.append(name)
    return arrays, scalars


def main() -> None:
    bodies = {}
    arrays: list[str] = []
    scalars: list[str] = []
    for filename in FILES:
        body = namespace_body(TABLES / filename)
        bodies[filename] = body
        a, s = declarations(body)
        arrays += a
        scalars += s

    arrays = sorted(set(arrays))
    scalars = sorted(set(scalars))
    rename = {n: n + "Dev" for n in arrays + scalars}
    pattern = re.compile(r"\b(" + "|".join(map(re.escape, rename)) + r")\b")

    def convert(body: str) -> str:
        body = body.replace("inline constexpr", "AV2ENC_ADV_DEV_TABLE")
        return pattern.sub(lambda m: rename[m.group(1)], body)

    lines: list[str] = []
    lines.append("// GENERATED by tables_device_gen.py; do not hand-edit.")
    lines.append("//")
    lines.append("// Device-storage copies of the AV2 v1.0.0 advanced-inter spec tables")
    lines.append("// (wedge / inter-intra and §9.5 warp filters).  The nvcc device pass sees")
    lines.append("// `__device__ constexpr` storage; every host pass sees `inline constexpr`.")
    lines.append("// A host-only static_assert compares every entry against the CPU tables so")
    lines.append("// the copies cannot drift.")
    lines.append("#ifndef AV2ENC_CUDA_INTER_ADVANCED_TABLES_DEVICE_CUH_")
    lines.append("#define AV2ENC_CUDA_INTER_ADVANCED_TABLES_DEVICE_CUH_")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append(
        '#include "../../../../codec/inter/advanced/tables/wedge_tables.h"'
    )
    lines.append(
        '#include "../../../../codec/inter/advanced/tables/warp_filters.h"'
    )
    lines.append("")
    lines.append("#if defined(__CUDACC__) && defined(__CUDA_ARCH__)")
    lines.append("#define AV2ENC_ADV_DEV_TABLE __device__ constexpr")
    lines.append("#else")
    lines.append("#define AV2ENC_ADV_DEV_TABLE inline constexpr")
    lines.append("#endif")
    lines.append("")
    lines.append(NAMESPACE_OPEN)
    lines.append("")
    for filename in FILES:
        lines.append(convert(bodies[filename]).strip("\n"))
        lines.append("")
    lines.append(NAMESPACE_CLOSE)
    lines.append("")
    lines.append("#if !defined(__CUDA_ARCH__)")
    lines.append("namespace av2enc::inter::adv::tables::detail {")
    lines.append("")
    lines.append("template <typename T>")
    lines.append("constexpr bool same_table_entry(const T& a, const T& b) {")
    lines.append("  return a == b;")
    lines.append("}")
    lines.append("")
    lines.append("template <typename T, std::size_t N>")
    lines.append("constexpr bool same_table_entry(const T (&a)[N], const T (&b)[N]) {")
    lines.append("  for (std::size_t i = 0; i < N; ++i) {")
    lines.append("    if (!same_table_entry(a[i], b[i])) return false;")
    lines.append("  }")
    lines.append("  return true;")
    lines.append("}")
    lines.append("")
    lines.append("constexpr bool advanced_tables_match() {")
    for name in arrays:
        lines.append(
            "  if (!same_table_entry(%s, %s)) return false;" % (rename[name], name)
        )
    for name in scalars:
        lines.append("  if (%s != %s) return false;" % (rename[name], name))
    lines.append("  return true;")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace av2enc::inter::adv::tables::detail")
    lines.append(
        "static_assert("
        "av2enc::inter::adv::tables::detail::advanced_tables_match(),"
    )
    lines.append(
        '              "device advanced-inter tables drifted from the CPU tables");'
    )
    lines.append("#endif  // !__CUDA_ARCH__")
    lines.append("")
    lines.append("#endif  // AV2ENC_CUDA_INTER_ADVANCED_TABLES_DEVICE_CUH_")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT, "-", len(arrays), "arrays,", len(scalars), "scalars")


if __name__ == "__main__":
    main()
