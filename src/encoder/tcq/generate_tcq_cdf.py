#!/usr/bin/env python3
"""Generate src/encoder/tcq/tcq_cdf_tables.h from the committed AV2 spec tables.

Source: spec/tables/default_cdf.json (AV2 v1.0.0 §9.3, commit 38f28e7).
The TCQ coefficient base CDFs already live in the generated
`src/encoder/m1/qctx/qctx_cdf_tables.h` (their `tcqState` axis is the explicit
2 in `Default_Coeff_Base_Cdf[COEFF_CDF_Q_CTXS][TX_SIZES][SIG_COEF_CONTEXTS][2]
[5]`).  This header only adds the standalone `Default_Cctx_Type_Cdf` that the
qctx slice does not carry.

Do not hand-edit the output.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "spec" / "tables" / "default_cdf.json"
OUTPUT = Path(__file__).resolve().parent / "tcq_cdf_tables.h"


def wrap(values: list[int], indent: str) -> str:
    line = indent
    out = []
    for value in values:
        token = f"{value}, "
        if len(line) + len(token) > 78:
            out.append(line.rstrip())
            line = indent
        line += token
    if line.strip():
        out.append(line.rstrip())
    return "\n".join(out)


def main() -> None:
    arrays = json.loads(SOURCE.read_text())["arrays"]
    entry = arrays["Default_Cctx_Type_Cdf"]
    shape = entry["shape"]
    values = entry["data"]
    if shape != [8] or len(values) != 8:
        raise SystemExit(
            f"Default_Cctx_Type_Cdf: expected shape [8], got {shape}"
        )
    text = "\n".join(
        [
            "// Generated by src/encoder/tcq/generate_tcq_cdf.py from",
            "// spec/tables/default_cdf.json (AV2 v1.0.0 §9.3).",
            "// Do not hand-edit.",
            "#pragma once",
            "",
            "#include <cstdint>",
            "",
            "namespace av2enc::tcq::cdf {",
            "",
            "// Default_Cctx_Type_Cdf [CCTX_TYPES + 1] (§9.3).",
            "inline constexpr std::uint16_t kCctxTypeCdf[8] = {",
            wrap(values, "    "),
            "};",
            "",
            "}  // namespace av2enc::tcq::cdf",
            "",
        ]
    )
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
