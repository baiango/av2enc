#!/usr/bin/env python3
"""Generate the M0 scan and inverse-DCT tables.

Sources (both generated from the AV2 v1.0.0 PDF by tools/spec_extract):
  spec/tables/scan.json        §5.20.7.30 diagonal (TX_CLASS_2D) scan
  spec/tables/dct_kernels.json §9.6 Dct_Kernel16 / Dct_Kernel32

Run from the repository root:

    python3 src/encoder/generate_m0_tables.py

Output: src/encoder/m0_tables.h
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SCAN = ROOT / "spec" / "tables" / "scan.json"
DCT = ROOT / "spec" / "tables" / "dct_kernels.json"
OUT = ROOT / "src" / "encoder" / "m0_tables.h"


def fmt_flat(values, per_line=16):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i : i + per_line]) + ",")
    return "\n".join(lines)


def main():
    scans = json.loads(SCAN.read_text())["scans"]
    kernels = json.loads(DCT.read_text())["kernels"]
    lines = [
        "// Generated by src/encoder/generate_m0_tables.py from",
        "// spec/tables/scan.json and spec/tables/dct_kernels.json",
        "// (AV2 v1.0.0 clauses 5.20.7.30 and 9.6). Do not hand-edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace av2enc::m0 {",
        "",
    ]
    for n in (16, 32):
        scan = scans[str(n)]
        lines.append(f"// Diagonal TX_CLASS_2D scan, {n}x{n} (pos = row*{n}+col).")
        lines.append(
            f"inline constexpr std::uint16_t kScan{n}[{n * n}] = {{"
        )
        lines.append(fmt_flat(scan))
        lines.append("};")
        lines.append("")
    for n in (4, 8, 16, 32):
        kernel = kernels[f"Dct_Kernel{n}"]
        assert len(kernel) == n and all(len(row) == n for row in kernel)
        lines.append(f"// Dct_Kernel{n}[j][i]: j = input coefficient, i = output sample.")
        lines.append(
            f"inline constexpr std::int16_t kDct{n}[{n}][{n}] = {{"
        )
        for row in kernel:
            lines.append("    {" + ", ".join(str(v) for v in row) + "},")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace av2enc::m0")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
