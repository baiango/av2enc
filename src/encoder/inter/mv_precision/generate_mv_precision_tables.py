#!/usr/bin/env python3
"""Generate mv_precision_cdf_tables.h from the pinned AV2 §9.3 tables.

The only source is `spec/tables/default_cdf.json`, which is itself generated
from the pinned `spec/AV2_Spec_v1.0.0.pdf` by `tools/spec_extract`.  Nothing in
this file is hand-typed.

    python3 generate_mv_precision_tables.py            # rewrite the header
    python3 generate_mv_precision_tables.py --check    # CI/check mode

The component owns only the CDFs that the absent MV-precision tools need:
AMVD, joint-MVD, per-block precision, and the switchable interpolation filter.
The shell tables are included because a flex-precision block codes its MVD with
a precision-dependent shell alphabet; M2 only shipped the 1/8-pel rows.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
SOURCE = ROOT / "spec" / "tables" / "default_cdf.json"
OUTPUT = HERE / "mv_precision_cdf_tables.h"

# name in §9.3 -> (C++ identifier, comment)
TABLES = [
    ("Default_Use_Amvd_Cdf", "kUseAmvdCdf",
     "AMVD on/off: [YMode-index][ctx][2]"),
    ("Default_Mv_Joint_Adaptive_Cdf", "kMvJointAdaptiveCdf",
     "AMVD mv_joint: [MV_JOINTS]"),
    ("Default_Amvd_Indices_Cdf", "kAmvdIndicesCdf",
     "AMVD magnitude index: [component][MAX_AMVD_INDEX]"),
    ("Default_Jmvd_Scale_Mode_Cdf", "kJmvdScaleModeCdf",
     "jmvd_scale_mode when use_amvd == 0: [JOINT_NEWMV_SCALE_FACTOR_CNT]"),
    ("Default_Jmvd_Adaptive_Scale_Mode_Cdf", "kJmvdAdaptiveScaleModeCdf",
     "jmvd_scale_mode when use_amvd == 1: [JOINT_AMVD_SCALE_FACTOR_CNT]"),
    ("Default_Use_Most_Probable_Precision_Cdf", "kUseMostProbablePrecisionCdf",
     "per-block precision: [ctx][2]"),
    ("Default_Pb_Mv_Precision_Cdf", "kPbMvPrecisionCdf",
     "pb_mv_precision: [ctx][FrameMvPrecision - MV_PRECISION_HALF_PEL][3]"),
    ("Default_Interp_Filter_Cdf", "kInterpFilterCdf",
     "switchable interp_filter: [INTERP_FILTER_CONTEXTS][3]"),
    ("Default_Joint_Shell_Set_Cdf", "kJointShellSetCdf",
     "shell_set: [MV_CONTEXTS]"),
    ("Default_Joint_Shell_Last_Two_Classes_Cdf", "kJointShellLastTwoClassesCdf",
     "joint_shell_last_two_classes: [MV_CONTEXTS]"),
    ("Default_Shell_Offset_Low_Class_Cdf", "kShellOffsetLowClassCdf",
     "shell_offset_low_class: [MV_CONTEXTS][2]"),
    ("Default_Shell_Offset_Class2_Cdf", "kShellOffsetClass2Cdf",
     "shell_offset_class2: [MV_CONTEXTS]"),
    ("Default_Shell_Offset_Other_Class_Cdf", "kShellOffsetOtherClassCdf",
     "shell_offset_other_class: [MV_CONTEXTS][16]"),
    ("Default_Col_Mv_Greater_Cdf", "kColMvGreaterCdf",
     "col_mv_greater: [MV_CONTEXTS][2]"),
    ("Default_Col_Mv_Index_Cdf", "kColMvIndexCdf",
     "col_mv_index: [MV_CONTEXTS][4]"),
]

# §5.20.7.20: shell_class CDF depends on MvPrecision p and shell_set q.
# p == MV_PRECISION_TWO_PEL (2) is unreachable and has no table.
SHELL_PRECISIONS = (0, 1, 3, 4, 5, 6)
for p in SHELL_PRECISIONS:
    TABLES.append(
        (f"Default_Joint_Shell{p}_Class0_Cdf", f"kJointShell{p}Class0Cdf",
         f"shell_class, MvPrecision={p}, shell_set=0: [MV_CONTEXTS]"))
    TABLES.append(
        (f"Default_Joint_Shell{p}_Class1_Cdf", f"kJointShell{p}Class1Cdf",
         f"shell_class, MvPrecision={p}, shell_set=1: [MV_CONTEXTS]"))


def reshape(flat, shape):
    if not shape:
        return flat
    if len(shape) == 1:
        assert len(flat) == shape[0], (shape, len(flat))
        return flat
    step = len(flat) // shape[0]
    return [reshape(flat[i * step:(i + 1) * step], shape[1:])
            for i in range(shape[0])]


def cpp_array(name, shape, data):
    def emit(value, depth):
        indent = "    " * (depth + 1)
        if isinstance(value, list):
            if not value:
                return "{}"
            inner = ",\n".join(indent + emit(v, depth + 1) for v in value)
            return "{\n" + inner + ",\n" + "    " * depth + "}"
        return str(value)

    dims = "".join(f"[{d}]" for d in shape)
    return (f"inline constexpr unsigned short {name}{dims} = "
            f"{emit(data, 0)};\n")


def build() -> str:
    doc = json.loads(SOURCE.read_text())
    arrays = doc["arrays"]
    out = []
    out.append("// Generated by generate_mv_precision_tables.py. Do not hand-edit.\n")
    out.append("// Source: spec/tables/default_cdf.json, AV2 v1.0.0 §9.3.\n")
    out.append("#pragma once\n\n#include <cstdint>\n\n")
    out.append("namespace av2enc::inter::mvprec::cdf {\n\n")
    for source, ident, comment in TABLES:
        if source not in arrays:
            raise SystemExit(f"missing §9.3 table: {source}")
        entry = arrays[source]
        flat = entry["data"]
        shape = entry["shape"]
        if len(flat) != prod(shape):
            raise SystemExit(
                f"{source}: flattened length {len(flat)} != {shape}")
        out.append(f"// {comment}\n")
        out.append(cpp_array(ident, shape, reshape(flat, shape)))
        out.append("\n")
    out.append("}  // namespace av2enc::inter::mvprec::cdf\n")
    return "".join(out)


def prod(shape):
    p = 1
    for d in shape:
        p *= d
    return p


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"{OUTPUT.name} is stale; regenerate it", file=sys.stderr)
            return 1
        print(f"{OUTPUT.name}: up to date")
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
