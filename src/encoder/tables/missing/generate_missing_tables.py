def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: pathlib.Path) -> str:
    return sha256_bytes(path.read_bytes())


def fail(message: str) -> NoReturn:
    raise SystemExit(f"missing_tables: {message}")


def import_specpdf():
    sys.path.insert(0, str(REPO_ROOT / "tools" / "spec_extract"))
    try:
        import specpdf  # type: ignore
    except ImportError as exc:  # pragma: no cover
        raise SystemExit(
            "tools/spec_extract/specpdf.py is required (pip install pypdf)"
        ) from exc
    return specpdf


def extents(shape: Iterable[int]) -> str:
    return "".join(f"[{d}]" for d in shape)


def product(shape: Iterable[int]) -> int:
    out = 1
    for d in shape:
        out *= d
    return out


def flatten(obj) -> list:
    if isinstance(obj, list):
        out = []
        for item in obj:
            out.extend(flatten(item))
        return out
    return [obj]


def canonical_payload(spec: TableSpec, flat: list) -> object:
    if spec.kind == "tx_type_enum":
        # Pin both the printed names and the numeric mapping.  A change to
        # constants.json therefore shows up as a hash mismatch.
        return {"names": flat, "values": [tx_type_value(n) for n in flat]}
    return flat


def tx_type_value(name: str) -> int:
    constants = spec_constants()
    if name not in constants:
        fail(f"Mode_To_Txfm entry {name!r} is not a constant in constants.json")
    value = constants[name]
    if not isinstance(value, int):
        fail(f"Mode_To_Txfm entry {name!r} is not an integer constant")
    return value


@lru_cache(maxsize=1)
def spec_constants() -> dict:
    return json.loads(CONSTANTS_JSON.read_text(encoding="utf-8"))


def extract_all() -> dict[str, list]:
    """Return name -> flat values (names for Mode_To_Txfm)."""
    if sha256_file(SPEC_PDF) != SPEC_PDF_SHA256:
        fail(
            f"{SPEC_PDF} sha256 {sha256_file(SPEC_PDF)} != pinned "
            f"{SPEC_PDF_SHA256}"
        )

    specpdf = import_specpdf()
    text = specpdf.pdf_text(SPEC_PDF)
    sec92 = specpdf.section(text, *SECTION_92)
    sec93 = specpdf.section(text, *SECTION_93)

    # The tile tables print the token `reserved`.  Rewriting it to -1 before
    # parsing is equivalent to accepting that literal, and keeps the generic
    # initializer parser unchanged.
    sec92_reserved = re.sub(r"\breserved\b", str(RESERVED), sec92)

    out: dict[str, list] = {}
    for spec in SPECS:
        sec = sec92_reserved if spec.section == "9.2" else sec93
        arr = specpdf.find_array(sec, spec.name)
        if arr is None:
            fail(f"{spec.name}: not found in §{spec.section}")
        if tuple(arr.shape) != spec.shape:
            fail(
                f"{spec.name}: PDF extents {extents(arr.shape)} != expected "
                f"{extents(spec.shape)}"
            )
        flat = list(arr.values)
        if len(flat) != product(spec.shape):
            fail(
                f"{spec.name}: {len(flat)} values != {product(spec.shape)} "
                f"for {extents(spec.shape)}"
            )
        if spec.kind == "tx_type_enum":
            for item in flat:
                tx_type_value(item)
        elif spec.kind == "reserved_int":
            for item in flat:
                if not isinstance(item, int):
                    fail(f"{spec.name}: non-integer value {item!r}")
                if item == RESERVED:
                    continue
                if item <= 0:
                    fail(f"{spec.name}: unexpected non-positive value {item}")
        else:
            for item in flat:
                if not isinstance(item, int):
                    fail(f"{spec.name}: non-integer value {item!r}")
        out[spec.name] = flat
    return out


def values_digest(spec: TableSpec, flat: list) -> str:
    payload = canonical_payload(spec, flat)
    data = json.dumps(payload, separators=(",", ":"), sort_keys=True).encode()
    return sha256_bytes(data)


def verify_pins(extracted: dict[str, list]) -> None:
    for spec in SPECS:
        digest = values_digest(spec, extracted[spec.name])
        if not spec.sha256:
            fail(
                f"{spec.name}: no value digest pinned; run --print-hashes and "
                f"put {digest} in SPECS"
            )
        if digest != spec.sha256:
            fail(
                f"{spec.name}: value digest {digest} != pinned {spec.sha256}"
            )


