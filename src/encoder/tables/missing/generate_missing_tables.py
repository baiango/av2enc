#!/usr/bin/env python3
"""Materialize the §9.2 tables (and one §9.3 CDF) that spec/tables/ omits.

The pinned AV2 v1.0.0 PDF prints every table in this set as a literal C
initializer.  This generator reads those initializers directly from
``spec/AV2_Spec_v1.0.0.pdf`` and emits the C++ headers in this directory.

It is deliberately independent of ``spec/tables/*.json``: those artifacts do
not contain these tables at all.  ``Gaussian_Sequence`` and the other tables
that already have hand-written local copies are cross-checked against those
copies, and a disagreement aborts the run instead of silently picking the PDF.

Fail-closed provenance
----------------------
* the PDF SHA-256 is pinned and must match;
* every table's inferred extents must equal the expected extents;
* every table's canonical value digest must equal the pinned digest;
* ``--check`` also requires the generated bytes to be current.

Usage
-----
    python3 src/encoder/tables/missing/generate_missing_tables.py
    python3 src/encoder/tables/missing/generate_missing_tables.py --check
    python3 src/encoder/tables/missing/generate_missing_tables.py --print-hashes

Requires Python 3.9+ and ``pypdf`` (the same dependency as
``tools/spec_extract``).
"""

