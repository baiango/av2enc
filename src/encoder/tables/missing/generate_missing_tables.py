def parse_cpp_array(path: pathlib.Path, symbol: str) -> list[int]:
    text = path.read_text(encoding="utf-8")
    m = re.search(
        r"\b" + re.escape(symbol) + r"\s*(?:\[[^\]]*\]\s*)+=\s*\{", text
    )
    if not m:
        raise ValueError(f"{path}: array {symbol} not found")
    start = text.index("{", m.start())
    depth = 0
    end = None
    for i in range(start, len(text)):
        ch = text[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                end = i
                break
    if end is None:
        raise ValueError(f"{path}: unbalanced braces for {symbol}")
    return [int(x) for x in re.findall(r"-?\d+", text[start : end + 1])]


def parse_cpp_macro(path: pathlib.Path, macro: str) -> list[int]:
    text = path.read_text(encoding="utf-8")
    idx = text.index(macro)
    lines = text[idx:].splitlines()
    body: list[str] = []
    for line_no, line in enumerate(lines):
        if line_no > 0:
            body.append(line)
        if not line.rstrip().endswith("\\"):
            break
    return [int(x) for x in re.findall(r"-?\d+", "\n".join(body))]


def parse_palette_multiplier_expression(path: pathlib.Path) -> list[int]:
    text = path.read_text(encoding="utf-8")
    m = re.search(
        r"scores\[0\]\s*\+\s*(\d+)\s*\*\s*scores\[1\]\s*\+\s*"
        r"(\d+)\s*\*\s*scores\[2\]",
        text,
    )
    if not m:
        raise ValueError(f"{path}: palette hash multiplier expression not found")
    return [1, int(m.group(1)), int(m.group(2))]


def report_mismatch(table: str, source: str, expected: list, actual: list) -> None:
    if len(expected) != len(actual):
        fail(
            f"CROSS-CHECK DISAGREEMENT {table} vs {source}: "
            f"length {len(expected)} != {len(actual)}"
        )
    diffs = [(i, e, a) for i, (e, a) in enumerate(zip(expected, actual)) if e != a]
    if diffs:
        preview = ", ".join(
            f"[{i}] pdf={e} local={a}" for i, e, a in diffs[:8]
        )
        fail(
            f"CROSS-CHECK DISAGREEMENT {table} vs {source}: "
            f"{len(diffs)} differing entries ({preview})"
        )


def run_cross_checks(extracted: dict[str, list]) -> None:
    for check in CROSS_CHECKS:
        path = REPO_ROOT / check.path
        if not path.is_file():
            fail(
                f"CROSS-CHECK MISSING {check.table}: {check.path} no longer "
                "exists; update CROSS_CHECKS or restore the local copy"
            )
        try:
            if check.kind == "macro":
                local = parse_cpp_macro(path, check.symbol)
            elif check.kind == "json_cdf":
                arrays = json.loads(path.read_text(encoding="utf-8"))["arrays"]
                if check.symbol not in arrays:
                    raise ValueError(
                        f"{path}: {check.symbol} not present in arrays"
                    )
                local = flatten(arrays[check.symbol]["data"])
            else:
                local = parse_cpp_array(path, check.symbol)
        except (ValueError, KeyError) as exc:
            fail(f"CROSS-CHECK ERROR {check.table}: {exc}")
        pdf = [int(v) for v in extracted[check.table]]
        report_mismatch(check.table, f"{check.path}:{check.symbol}", pdf, local)
        print(
            f"cross-check: ok {check.table} == {check.path}:{check.symbol} "
            f"({len(local)} values)"
        )

    # Palette_Color_Hash_Multipliers is inlined as an expression in
    # palette_core.h rather than a named array.
    path = REPO_ROOT / "src/encoder/palette/palette_core.h"
    if not path.is_file():
        fail(
            "CROSS-CHECK MISSING Palette_Color_Hash_Multipliers: "
            "src/encoder/palette/palette_core.h no longer exists"
        )
    try:
        local = parse_palette_multiplier_expression(path)
    except ValueError as exc:
        fail(f"CROSS-CHECK ERROR Palette_Color_Hash_Multipliers: {exc}")
    pdf = [int(v) for v in extracted["Palette_Color_Hash_Multipliers"]]
    report_mismatch(
        "Palette_Color_Hash_Multipliers",
        f"{path}:scores[0]+2*scores[1]+2*scores[2]",
        pdf,
        local,
    )
    print(
        "cross-check: ok Palette_Color_Hash_Multipliers == "
        f"{path}:palette_color_context expression ({len(local)} values)"
    )


