def fmt_flat(values: list[int], indent: int = 2, per_line: int = 12) -> list[str]:
    pad = " " * indent
    lines = []
    for i in range(0, len(values), per_line):
        lines.append(pad + ", ".join(str(v) for v in values[i : i + per_line]) + ",")
    return lines


def fmt_rows(rows: list[list[int]], indent: int = 2, per_line: int = 12) -> list[str]:
    pad = " " * indent
    inner = " " * (indent + 2)
    lines = []
    for row in rows:
        if len(row) <= per_line:
            lines.append(pad + "{" + ", ".join(str(v) for v in row) + "},")
            continue
        lines.append(pad + "{")
        for i in range(0, len(row), per_line):
            lines.append(
                inner
                + ", ".join(str(v) for v in row[i : i + per_line])
                + ","
            )
        lines.append(pad + "},")
    return lines


def reshape(flat: list[int], shape: tuple[int, ...]) -> list:
    if len(shape) == 1:
        return flat
    step = product(shape[1:])
    return [
        reshape(flat[i * step : (i + 1) * step], shape[1:])
        for i in range(shape[0])
    ]


def header_preamble(title: str) -> list[str]:
    preamble = [f"// {title}"]
    preamble += comment_lines(
        f"Generated by {GENERATOR} from spec/AV2_Spec_v1.0.0.pdf."
    )
    preamble += [f"// Source SHA-256: {SPEC_PDF_SHA256}."]
    preamble += comment_lines(
        f"{SPEC_VERSION}.  §9.2 conversion tables / §9.3 default CDFs. "
        "Do not hand-edit."
    )
    preamble += [
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::tables::missing {",
        "",
    ]
    return preamble


def comment_lines(text: str) -> list[str]:
    wrapped = textwrap.wrap(
        text, width=78, initial_indent="// ", subsequent_indent="// "
    )
    return wrapped or ["//"]


def emit_table(spec: TableSpec, flat: list[int], mode_names: list[str]) -> list[str]:
    dims = extents(spec.shape)
    lines = [
        f"// {spec.clause} {spec.name}{dims}",
    ]
    lines += comment_lines(spec.note)
    if len(spec.shape) == 1:
        lines.append(
            f"inline constexpr {spec.ctype} {spec.cpp_name}{dims} = {{"
        )
        lines.extend(fmt_flat(flat))
        lines.append("};")
    else:
        rows = reshape(flat, spec.shape)
        assert isinstance(rows[0], list)
        lines.append(
            f"inline constexpr {spec.ctype} {spec.cpp_name}{dims} = {{"
        )
        lines.extend(fmt_rows(rows))
        lines.append("};")
    if spec.kind == "tx_type_enum":
        lines.extend(
            [
                "",
                "// TX_TYPE names exactly as printed in the specification.",
                f"inline constexpr const char* {spec.cpp_name}Names{dims} = {{",
            ]
        )
        for i in range(0, len(mode_names), 8):
            chunk = mode_names[i : i + 8]
            lines.append("    " + ", ".join(f'"{n}"' for n in chunk) + ",")
        lines.append("};")
    lines.append("")
    return lines


def build_group_header(header: str, specs: list[TableSpec], extracted: dict) -> str:
    lines = header_preamble(f"{header}: recovered spec tables")
    if any(spec.kind == "reserved_int" for spec in specs):
        lines.extend(
            [
                "// The PDF prints `reserved` for these entries.  -1 cannot be",
                "// mistaken for a scaling factor; consumers must reject it.",
                f"inline constexpr std::int8_t kReservedTileScalingFactor = "
                f"{RESERVED};",
                "",
            ]
        )
    for spec in specs:
        flat = extracted[spec.name]
        mode_names = [str(v) for v in flat] if spec.kind == "tx_type_enum" else []
        if spec.kind == "tx_type_enum":
            flat = [tx_type_value(n) for n in flat]
        lines.extend(emit_table(spec, flat, mode_names))
    lines.append("}  // namespace av2enc::tables::missing")
    lines.append("")
    return "\n".join(lines)


def build_provenance_header() -> str:
    lines = [
        "// Provenance for the recovered §9.2 tables and one §9.3 CDF.",
    ]
    lines += comment_lines(f"Generated by {GENERATOR}.  Do not hand-edit.")
    lines += [
        "#pragma once",
        "",
        "namespace av2enc::tables::missing {",
        "",
        f'inline constexpr char kSpecPdfSha256[] = "{SPEC_PDF_SHA256}";',
        f'inline constexpr char kSpecVersion[] = "{SPEC_VERSION}";',
        f'inline constexpr char kGeneratorPath[] = "{GENERATOR}";',
        "",
        "struct MissingTableProvenance {",
        "  const char* spec_name;",
        "  const char* clause;",
        "  const char* extents;",
        "  const char* value_sha256;",
        "};",
        "",
        "// value_sha256 is the SHA-256 of the canonical JSON value list used by",
        "// generate_missing_tables.py.  It pins the PDF extraction independently",
        "// of the generated header bytes.",
        "inline constexpr MissingTableProvenance kMissingTableProvenance[] = {",
    ]
    for spec in SPECS:
        clause = spec.clause.replace("§", "")
        lines.append(
            f'    {{"{spec.name}", "{clause}", "{extents(spec.shape)}", '
            f'"{spec.sha256}"}},'
        )
    lines += [
        "};",
        "",
        f"inline constexpr int kMissingTableCount = "
        f"{len(SPECS)};",
        "",
        "}  // namespace av2enc::tables::missing",
        "",
    ]
    return "\n".join(lines)


def build_umbrella_header(headers: list[str]) -> str:
    lines = [
        "// Umbrella include for the recovered §9.2 / §9.3 tables.",
        f"// Generated by {GENERATOR}.  Do not hand-edit.",
        "#pragma once",
        "",
    ]
    for header in headers:
        lines.append(f'#include "encoder/tables/missing/{header}"')
    lines.append("")
    return "\n".join(lines)


def outputs(extracted: dict[str, list]) -> dict[pathlib.Path, str]:
    headers: dict[str, list[TableSpec]] = {}
    for spec in SPECS:
        headers.setdefault(spec.header, []).append(spec)

    produced: dict[pathlib.Path, str] = {}
    for header, specs in headers.items():
        produced[HERE / header] = build_group_header(header, specs, extracted)
    produced[HERE / "missing_tables_provenance.h"] = build_provenance_header()
    produced[HERE / "missing_tables.h"] = build_umbrella_header(list(headers))
    return produced


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify PDF/value pins and that generated headers are current",
    )
    parser.add_argument(
        "--print-hashes",
        action="store_true",
        help="print the canonical value digest for each table",
    )
    args = parser.parse_args(argv)

    extracted = extract_all()
    run_cross_checks(extracted)
    if args.print_hashes:
        for spec in SPECS:
            print(
                f"{values_digest(spec, extracted[spec.name])}  "
                f"{spec.name} {extents(spec.shape)}"
            )
        return 0

    verify_pins(extracted)

    produced = outputs(extracted)
    if args.check:
        stale = False
        for path, text in produced.items():
            if not path.is_file():
                print(f"MISSING {path.relative_to(REPO_ROOT)}", file=sys.stderr)
                stale = True
            elif path.read_text(encoding="utf-8") != text:
                print(f"STALE   {path.relative_to(REPO_ROOT)}", file=sys.stderr)
                stale = True
            else:
                print(f"ok      {path.name}")
        return 2 if stale else 0

    for path, text in produced.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
