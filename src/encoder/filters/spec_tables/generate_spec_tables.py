def outputs() -> dict[pathlib.Path, str]:
    return {
        HERE / "spec_tables_provenance.h": build_provenance_header(),
        HERE / "gdf_tables.h": build_gdf_header(),
        HERE / "pc_wiener_tables.h": build_pc_wiener_header(),
        HERE / "film_grain_tables.h": build_film_grain_header(),
    }


def ensure_raw() -> None:
    """Fetch a missing or modified attachment, verifying the pinned hash.

    The verbatim spec attachments are not redistributed with this repository.
    Only the derived headers are committed; the source bytes are re-fetched
    from the official location and must match the SHA-256 in ``TABLES``.
    """
    RAW.mkdir(parents=True, exist_ok=True)
    for filename, (expected, *_rest) in TABLES.items():
        path = RAW / filename
        if path.is_file() and sha256(path) == expected:
            continue
        url = f"{ATTACHMENT_BASE}/{filename}"
        try:
            with urllib.request.urlopen(url, timeout=60) as response:
                data = response.read()
        except Exception as exc:  # noqa: BLE001 - report the exact remedy
            raise SystemExit(
                f"missing raw attachment {filename} and download failed "
                f"({exc}).\nFetch {url} into {RAW} and re-run."
            ) from exc
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            raise SystemExit(
                f"{filename}: downloaded sha256 {actual} != pinned {expected}"
            )
        path.write_bytes(data)


def verify_raw_hashes() -> None:
    for filename, (expected, *_rest) in TABLES.items():
        path = RAW / filename
        if not path.is_file():
            raise SystemExit(f"missing raw attachment: {path}")
        actual = sha256(path)
        if actual != expected:
            raise SystemExit(f"{filename}: sha256 {actual} != pinned {expected}")
        spec_name, declared, values, _text = load_table(filename)
        expected_dims = TABLES[filename][3]
        if declared != expected_dims:
            raise SystemExit(f"{filename}: declared {declared} != {expected_dims}")
        total = 1
        for d in expected_dims:
            total *= d
        if len(values) != total:
            raise SystemExit(f"{filename}: {len(values)} values != {total}")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify raw hashes and generated bytes")
    ap.add_argument("--print-hashes", action="store_true", help="print raw attachment hashes")
    args = ap.parse_args(argv)

    ensure_raw()
    verify_raw_hashes()

    if args.print_hashes:
        for filename, (digest, *_rest) in TABLES.items():
            print(f"{digest}  {filename}")

    produced = outputs()
    if args.check:
        failed = False
        for path, text in produced.items():
            if not path.is_file():
                print(f"MISSING {path}", file=sys.stderr)
                failed = True
            elif path.read_text(encoding="utf-8") != text:
                print(f"STALE   {path}", file=sys.stderr)
                failed = True
            else:
                print(f"ok      {path.name}")
        return 2 if failed else 0

    for path, text in produced.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
