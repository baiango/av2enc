DECL_RE = re.compile(r"^\s*([A-Za-z_]\w*)\s*((?:\[\s*[^\]]+\s*\])+)\s*=", re.S)
DIM_RE = re.compile(r"\[\s*([^\]]+?)\s*\]")


def sha256(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse_declared_dims(text: str) -> tuple[str, list[int]]:
    m = DECL_RE.search(text)
    if not m:
        raise SystemExit("could not parse array declaration")
    name = m.group(1)
    dims: list[int] = []
    for token in DIM_RE.findall(m.group(2)):
        if token.isdigit():
            dims.append(int(token))
        elif token in SPEC_CONSTANTS:
            dims.append(SPEC_CONSTANTS[token])
        else:
            raise SystemExit(f"{name}: unknown extent {token!r}")
    return name, dims


def parse_values(text: str) -> list[int]:
    body = text.split("=", 1)[1]
    return [int(x) for x in re.findall(r"-?\d+", body)]


def load_table(filename: str):
    """Return (spec name, resolved dims, flat values, raw text)."""
    path = RAW / filename
    text = path.read_text(encoding="utf-8")
    spec_name, declared = parse_declared_dims(text)
    values = parse_values(text)
    return spec_name, declared, values, text


def reshape(values: list[int], dims: list[int]) -> object:
    expected = 1
    for d in dims:
        expected *= d
    if len(values) != expected:
        raise SystemExit(f"expected {expected} values for {dims}, got {len(values)}")
    if len(dims) == 1:
        return values
    step = 1
    for d in dims[1:]:
        step *= d
    return [reshape(values[i * step : (i + 1) * step], dims[1:]) for i in range(dims[0])]


def cpp_shape(dims: Iterable[int]) -> str:
    return "".join(f"[{d}]" for d in dims)


def emit_flat(values: list[int], indent: int, per_line: int = 16) -> list[str]:
    """Emit comma-separated numbers, wrapped, with a trailing comma."""
    pad = " " * indent
    chunks = [values[i : i + per_line] for i in range(0, len(values), per_line)]
    lines = [pad + ", ".join(str(v) for v in chunk) + "," for chunk in chunks]
    return lines


def emit_values(values: list[int], indent: int, per_line: int = 16) -> list[str]:
    """Emit one braced row (a leaf of the nested initializer)."""
    pad = " " * indent
    chunks = [values[i : i + per_line] for i in range(0, len(values), per_line)]
    if len(chunks) == 1:
        return [pad + "{" + ", ".join(str(v) for v in chunks[0]) + "},"]
    lines = [pad + "{"]
    for chunk in chunks:
        lines.append(pad + "  " + ", ".join(str(v) for v in chunk) + ",")
    lines.append(pad + "},")
    return lines


def emit_array(
    name: str, ctype: str, dims: list[int], data: object, clause: str
) -> list[str]:
    lines = [
        f"// {clause}",
        f"// Extents: {', '.join(str(d) for d in dims)} (flat data from the attachment).",
        f"inline constexpr {ctype} {name}{cpp_shape(dims)} = {{",
    ]

    def rec(node: object, depth: int) -> None:
        indent = 2 * depth
        if isinstance(node, list) and node and isinstance(node[0], list):
            pad = " " * indent
            lines.append(pad + "{")
            for child in node:
                rec(child, depth + 1)
            lines.append(pad + "},")
        else:
            lines.extend(emit_values(node, indent))

    if len(dims) == 1:
        lines.extend(emit_flat(data, 2))
    else:
        # The declaration already opened the outermost brace.
        for child in data:
            rec(child, 1)
    lines.append("};")
    return lines


def build_provenance_header() -> str:
    lines = [
        "// Generated by generate_spec_tables.py.  Do not hand-edit.",
        f"// {SPEC_VERSION}.",
        f"// Attachment mirror: {ATTACHMENT_REPO} @ {ATTACHMENT_COMMIT} (retrieved {RETRIEVED}).",
        "#pragma once",
        "",
        "namespace av2enc::filters::spec_tables {",
        "",
        f'inline constexpr char kSpecVersion[] = "{SPEC_VERSION}";',
        f'inline constexpr char kAttachmentRepo[] = "{ATTACHMENT_REPO}";',
        f'inline constexpr char kAttachmentCommit[] = "{ATTACHMENT_COMMIT}";',
        f'inline constexpr char kAttachmentRetrieved[] = "{RETRIEVED}";',
        "",
        "struct TableProvenance {",
        "  const char* spec_name;",
        "  const char* filename;",
        "  const char* sha256;",
        "};",
        "",
        "// Byte-exact SHA-256 of each verbatim attachment in raw/.",
        "inline constexpr TableProvenance kTableProvenance[] = {",
    ]
    for filename, (digest, _ident, _ctype, _dims, _clause) in TABLES.items():
        spec_name = load_table(filename)[0]
        lines.append(f'    {{"{spec_name}", "{filename}", "{digest}"}},')
    lines += [
        "};",
        "",
        "}  // namespace av2enc::filters::spec_tables",
        "",
    ]
    return "\n".join(lines)


