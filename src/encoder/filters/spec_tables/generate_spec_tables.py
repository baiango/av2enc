def build_pc_wiener_header() -> str:
    quant = json.loads(QUANT_JSON.read_text())
    ac = quant["Ac_Qlookup"]
    if len(ac) != 25:
        raise SystemExit("Ac_Qlookup length changed")

    # qlookup(q) per §7.14.2 for q = 0..MaxQ_bits (351), reconstructed from
    # Ac_Qlookup, then checked against the printed 0..255 slice.
    qlookup = [ac[q] if q < 25 else ac[((q - 1) % 24) + 1] << ((q - 1) // 24) for q in range(352)]
    if qlookup[:256] != quant["qlookup_q0_255"]:
        raise SystemExit("qlookup reconstruction disagrees with quant.json")

    lines = [
        "// Generated by generate_spec_tables.py.  Do not hand-edit.",
        f"// {SPEC_VERSION}.  Source: {ATTACHMENT_BASE}/*.h",
        f"// Mirror: {ATTACHMENT_REPO} @ {ATTACHMENT_COMMIT}",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::filters::spec_tables {",
        "",
        "constexpr int kPcWienerFilterSets = 4;   // get_filter_set_index()",
        "constexpr int kPcWienerFiltersPerSet = 64;",
        "constexpr int kPcWienerCoeffs = 13;      // 25 taps -> i >> 1",
        "constexpr int kPcWienerLutClasses = 256;",
        "constexpr int kPcWienerSubClasses = 8;   // Pc_Wiener_Sub_Classify2 axis",
        "",
    ]
    for filename, (_digest, ident, ctype, dims, clause) in TABLES.items():
        if not filename.startswith("pc_wiener_"):
            continue
        _name, declared, values, _text = load_table(filename)
        if declared != dims:
            raise SystemExit(f"{filename}: declared {declared} != expected {dims}")
        lines.extend(emit_array(ident, ctype, dims, reshape(values, dims), clause))
        lines.append("")

    lines += [
        "// §7.14.2 Ac_Qlookup[25] and qlookup(q) for q = 0..351 (MaxQ_bits).",
        "// Regenerated from spec/tables/quant.json; the 0..255 slice is verified",
        "// against the printed qlookup in the generator.",
        "inline constexpr std::int32_t kAcQlookup[25] = {",
    ]
    lines.extend(emit_flat(ac, 2))
    lines += [
        "};",
        "",
        "inline constexpr std::int32_t kQlookup[352] = {",
    ]
    lines.extend(emit_flat(qlookup, 2))
    lines += [
        "};",
        "",
        "}  // namespace av2enc::filters::spec_tables",
        "",
    ]
    return "\n".join(lines)


