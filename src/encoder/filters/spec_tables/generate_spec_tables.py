#!/usr/bin/env python3
"""Generate the loop-restoration / film-grain normative tables.

Source of truth
---------------
AV2 v1.0.0 (2026-05-28, spec commit ``38f28e7``) prints these tables in the
pinned PDF, but section 9.8 / 9.9 prose only points at header files.  The PDF
blocks (pages 921-1087) are cross-checked number-for-number against the
attachments by ``verify_pdf_tables.py``.  The prose says only::

    Gdf_Alpha is defined in the gdf_alpha.h header file.
    ...
    Gaussian_Sequence is defined in the gaussian_sequence.h header file.

The official attachments are published with the specification at

    https://av2.aomedia.org/v1.0.0/attachments/<name>

and mirrored in the AOMediaCodec/av2-spec repository under ``v1.0.0``
(commit ``42d091fe9f8ea4b526800d073b3e4c4da132967e``).  The verbatim files
are fetched on demand into ``raw/`` (not redistributed with this repo) and
verified against the SHA-256 values pinned in ``TABLES`` before parsing.

Values are never typed by hand.  This script parses the initializer bodies,
validates the declared extents against the spec constants, and emits the C++
headers.  ``--check`` re-runs the whole pipeline and fails if a raw hash or a
generated byte differs.

Usage
-----
    python3 src/encoder/filters/spec_tables/generate_spec_tables.py
    python3 src/encoder/filters/spec_tables/generate_spec_tables.py --check
    python3 src/encoder/filters/spec_tables/generate_spec_tables.py --print-hashes

Requires Python 3.9+ (standard library only).
"""

