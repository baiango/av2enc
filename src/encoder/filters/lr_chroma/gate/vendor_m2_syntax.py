#!/usr/bin/env python3
"""Vendor the M2 tile writer with one chroma-LR hook (gate use only).

The chroma loop-restoration gate needs one call to `read_lr()` immediately
before `read_partition()` in the M2 tile writer (§5.20.10.4).  The M2 core is
owned by another workstream and must not be edited, so this script makes an
exact copy of `src/encoder/m2/m2_syntax.cpp` in the build directory and injects
that one call.

The transform is anchored on exact source text and on the source SHA-256.  If
the M2 writer changes, this fails loudly instead of silently producing a
different stream.

Usage:
    python3 vendor_m2_syntax.py --out <build-dir>
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[4]
SOURCE = ROOT / "src" / "encoder" / "m2" / "m2_syntax.cpp"
EXPECTED_SHA256 = (
    "fe401c60f5d9555a98b51f612eb40d823327b1a03db2c5a73aee62ea9bbbd879"
)

HEADER = """\
// Generated by vendor_m2_syntax.py.  Do not edit.
#pragma once

#include <cstddef>
#include <cstdint>
#include <span>
#include <string>
#include <vector>

#include "encoder/filters/lr_chroma/chroma_lr.h"
#include "encoder/m2/m2_syntax.h"

namespace av2enc::lr_chroma::gate {

// Identical to av2enc::m2::syntax::assemble_m2_frame(), except that
// `lr_state`/`lr_decision` drive the §5.20.10.4 read_lr() call before each
// superblock's read_partition().  Pass nullptr for both for a baseline
// (no-LR) tile.
bool assemble_m2_frame_lr(
    const av2enc::m2::syntax::FramePlan& plan,
    std::span<const av2enc::m2::syntax::BlockSyntax> blocks,
    std::span<const std::int32_t> levels, const av2enc::m2::M2Config& config,
    fs::LrState* lr_state, const ChromaDecision* lr_decision,
    std::vector<std::uint8_t>& tile_payload, std::string& error,
    std::size_t* tile_bytes);

}  // namespace av2enc::lr_chroma::gate
"""


def replace_once(text: str, old: str, new: str, what: str) -> str:
    if text.count(old) != 1:
        raise SystemExit(
            f"vendor_m2_syntax: anchor for {what} occurs {text.count(old)} "
            "times; refusing to patch"
        )
    return text.replace(old, new, 1)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    out_dir = pathlib.Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    raw = SOURCE.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(
            "vendor_m2_syntax: m2_syntax.cpp changed\n"
            f"  expected {EXPECTED_SHA256}\n  actual   {digest}\n"
            "Update the hook and the pin together."
        )
    text = raw.decode("utf-8")

    text = replace_once(
        text,
        '#include "encoder/m2/m2_syntax.h"\n',
        '#include "encoder/m2/m2_syntax.h"\n\n'
        '#include "encoder/filters/lr_chroma/chroma_lr.h"\n',
        "include",
    )
    text = replace_once(
        text,
        "namespace av2enc::m2::syntax {\n",
        "namespace av2enc::lr_chroma::gate {\n"
        "\n"
        "using namespace av2enc::m2;\n"
        "using namespace av2enc::m2::syntax;\n"
        "int gate_plan_sb_cols(const FramePlan& plan);\n"
        "int gate_plan_sb_rows(const FramePlan& plan);\n"
        "void build_scan(int w, int h, std::span<std::uint16_t> scan);\n"
        "bool gate_assemble_m2_frame(\n"
        "    const FramePlan& plan, std::span<const BlockSyntax> blocks,\n"
        "    std::span<const std::int32_t> levels, const M2Config& config,\n"
        "    std::vector<std::uint8_t>& tile_payload, std::string& error,\n"
        "    std::size_t* tile_bytes);\n"
        "\n"
        "namespace {\n"
        "// Gate-only hook state.  The M2 tile writer is single-threaded.\n"
        "fs::LrState* g_lr_state = nullptr;\n"
        "const ChromaDecision* g_lr_decision = nullptr;\n"
        "}  // namespace\n",
        "namespace open",
    )
    text = replace_once(
        text,
        "    const int sb_cols = plan_.sb_cols();\n"
        "    const int sb_rows = plan_.sb_rows();\n",
        "    const int sb_cols = gate_plan_sb_cols(plan_);\n"
        "    const int sb_rows = gate_plan_sb_rows(plan_);\n",
        "FramePlan use",
    )
    text = replace_once(
        text,
        """      if (node.mi_col == 0) {
        // New superblock row: the left partition context restarts.  Mirrors
        // `if (sb.mi_col == 0) clear_left_context()` in m1_still.
        clear_left_context();
      }
      std::size_t next = 0;
""",
        """      if (node.mi_col == 0) {
        // New superblock row: the left partition context restarts.  Mirrors
        // `if (sb.mi_col == 0) clear_left_context()` in m1_still.
        clear_left_context();
      }
      // §5.20.10.4 read_lr(): once per superblock, BEFORE read_partition().
      if (g_lr_state != nullptr && g_lr_decision != nullptr) {
        if (!chroma_write_read_lr(enc_, *g_lr_state, node.mi_row, node.mi_col,
                                  sb_mi, sb_mi, 0, 0, *g_lr_decision, &error)) {
          return false;
        }
      }
      std::size_t next = 0;
""",
        "read_lr hook",
    )
    text = replace_once(
        text,
        """int FramePlan::sb_cols() const {
  FrameGeometry geometry;
  geometry.width = width;
  geometry.height = height;
  geometry.sb_size = sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_cols(geometry) + sb_mi - 1) / sb_mi;
}

int FramePlan::sb_rows() const {
  FrameGeometry geometry;
  geometry.width = width;
  geometry.height = height;
  geometry.sb_size = sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_rows(geometry) + sb_mi - 1) / sb_mi;
}

int FramePlan::superblock_count() const { return sb_cols() * sb_rows(); }
""",
        """int gate_plan_sb_cols(const FramePlan& plan) {
  FrameGeometry geometry;
  geometry.width = plan.width;
  geometry.height = plan.height;
  geometry.sb_size = plan.sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_cols(geometry) + sb_mi - 1) / sb_mi;
}

int gate_plan_sb_rows(const FramePlan& plan) {
  FrameGeometry geometry;
  geometry.width = plan.width;
  geometry.height = plan.height;
  geometry.sb_size = plan.sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_rows(geometry) + sb_mi - 1) / sb_mi;
}
""",
        "FramePlan definitions",
    )
    text = replace_once(
        text,
        "bool assemble_m2_frame(const FramePlan& plan,\n"
        "                             std::span<const BlockSyntax> blocks,\n"
        "                             std::span<const std::int32_t> levels,\n"
        "                             const M2Config& config,\n"
        "                             std::vector<std::uint8_t>& tile_payload,\n"
        "                             std::string& error, std::size_t* tile_bytes) {\n",
        "bool gate_assemble_m2_frame(const FramePlan& plan,\n"
        "                             std::span<const BlockSyntax> blocks,\n"
        "                             std::span<const std::int32_t> levels,\n"
        "                             const M2Config& config,\n"
        "                             std::vector<std::uint8_t>& tile_payload,\n"
        "                             std::string& error, std::size_t* tile_bytes) {\n",
        "internal assemble rename",
    )
    text = replace_once(
        text,
        "}  // namespace av2enc::m2::syntax\n",
        """bool assemble_m2_frame_lr(
    const FramePlan& plan, std::span<const BlockSyntax> blocks,
    std::span<const std::int32_t> levels, const M2Config& config,
    fs::LrState* lr_state, const ChromaDecision* lr_decision,
    std::vector<std::uint8_t>& tile_payload, std::string& error,
    std::size_t* tile_bytes) {
  g_lr_state = lr_state;
  g_lr_decision = lr_decision;
  const bool ok =
      gate_assemble_m2_frame(plan, blocks, levels, config, tile_payload, error,
                             tile_bytes);
  g_lr_state = nullptr;
  g_lr_decision = nullptr;
  return ok;
}

}  // namespace av2enc::lr_chroma::gate
""",
        "namespace close",
    )

    (out_dir / "m2_syntax_lr.cpp").write_text(text)
    (out_dir / "m2_syntax_lr.h").write_text(HEADER)
    print(f"wrote {out_dir / 'm2_syntax_lr.cpp'} ({len(text.splitlines())} lines)")
    print(f"wrote {out_dir / 'm2_syntax_lr.h'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
