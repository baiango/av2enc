#!/usr/bin/env python3
"""Generate the transform-variant kernel tables for `src/encoder/tx_variants/`.

Sources (normative AV2 v1.0.0 only):

  * ``spec/AV2_Spec_v1.0.0.pdf`` §9.6 — Dct_Kernel4/8/16/32,
    Adst_Kernel4/8/16 and Fdst_Kernel4/8/16.  The HTML edition only names
    header attachments, so the PDF is the source of the numbers (same reason
    as ``tools/spec_extract/_tables``).
  * ``spec/tables/block_tables.json`` §9.2 — Tx_Width, Tx_Height,
    Tx_Width_Log2, Tx_Height_Log2, Adjusted_Tx_Size and Transform_Shift.

Outputs (both checked in, do not hand-edit):

  * ``tx_tables.h``      host ``inline constexpr`` tables (C++17/20)
  * ``tx_tables_dev.cuh`` ``__device__ const`` copies for the CUDA kernels

The CUDA copies exist because a namespace-scope ``constexpr`` array cannot be
indexed at runtime from device code; both files are emitted from the same
parsed data so they cannot drift.

Usage:
  python3 src/encoder/tx_variants/generate_tx_tables.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / "tools" / "spec_extract"))

from specpdf import find_array, pdf_text  # noqa: E402

BLOCK_TABLES = REPO / "spec" / "tables" / "block_tables.json"

DCT_SIZES = (4, 8, 16, 32)
ADST_SIZES = (4, 8, 16)
FDST_SIZES = (4, 8, 16)


def c_array(name: str, rows: list[list[int]]) -> list[str]:
    n = len(rows)
    out = [f"inline constexpr std::int16_t {name}[{n}][{n}] = {{"]
    for row in rows:
        assert len(row) == n
        out.append("    {" + ", ".join(f"{v:4d}" for v in row) + "},")
    out.append("};")
    return out


def dev_array(name: str, rows: list[list[int]]) -> list[str]:
    n = len(rows)
    out = [f"__device__ const std::int16_t {name}[{n}][{n}] = {{"]
    for row in rows:
        assert len(row) == n
        out.append("    {" + ", ".join(f"{v:4d}" for v in row) + "},")
    out.append("};")
    return out


def main() -> None:
    text = pdf_text()
    kernels: dict[str, list[list[int]]] = {}
    for n in DCT_SIZES:
        arr = find_array(text, f"Dct_Kernel{n}")
        if arr is None or arr.shape != [n, n]:
            raise SystemExit(f"missing/invalid Dct_Kernel{n}: {arr}")
        kernels[f"Dct_Kernel{n}"] = arr.data
    for n in ADST_SIZES:
        arr = find_array(text, f"Adst_Kernel{n}")
        if arr is None or arr.shape != [n, n]:
            raise SystemExit(f"missing/invalid Adst_Kernel{n}: {arr}")
        kernels[f"Adst_Kernel{n}"] = arr.data
    for n in FDST_SIZES:
        arr = find_array(text, f"Fdst_Kernel{n}")
        if arr is None or arr.shape != [n, n]:
            raise SystemExit(f"missing/invalid Fdst_Kernel{n}: {arr}")
        kernels[f"Fdst_Kernel{n}"] = arr.data

    # §9.6 spot checks already used by the DCT reference plus ADST/FDST anchors.
    checks = {
        "Dct_Kernel4": (0, 1, 64),
        "Dct_Kernel32": (1, 0, 90),
        "Adst_Kernel4": (0, 0, 18),
        "Adst_Kernel8": (0, 0, 11),
        "Adst_Kernel16": (0, 0, 8),
        "Fdst_Kernel4": (0, 0, 89),
        "Fdst_Kernel8": (0, 0, 89),
        "Fdst_Kernel16": (0, 0, 89),
    }
    for name, (r, c, want) in checks.items():
        got = kernels[name][r][c]
        if got != want:
            raise SystemExit(f"{name}[{r}][{c}] = {got}, expected {want}")

    block = json.loads(BLOCK_TABLES.read_text())
    enum = block["enum_tx_size"]["data"]
    assert len(enum) == 25
    w = block["Tx_Width"]["data"]
    h = block["Tx_Height"]["data"]
    log2w = block["Tx_Width_Log2"]["data"]
    log2h = block["Tx_Height_Log2"]["data"]
    adj = block["Adjusted_Tx_Size"]["data"]
    shifts = block["Transform_Shift"]["data"]
    for name, arr in (
        ("Tx_Width", w),
        ("Tx_Height", h),
        ("Tx_Width_Log2", log2w),
        ("Tx_Height_Log2", log2h),
        ("Adjusted_Tx_Size", adj),
        ("Transform_Shift", shifts),
    ):
        assert len(arr) == 25, (name, len(arr))

    header = [
        "// Generated by src/encoder/tx_variants/generate_tx_tables.py from",
        "// spec/AV2_Spec_v1.0.0.pdf clause 9.6 and spec/tables/block_tables.json",
        "// clause 9.2. Do not edit by hand.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace av2enc::txv {",
        "",
        "// 1D kernel tables, K[coeff][sample], scale 64*sqrt(n) (see §9.6).",
    ]
    for n in DCT_SIZES:
        header += c_array(f"kDct{n}", kernels[f"Dct_Kernel{n}"])
        header.append("")
    for n in ADST_SIZES:
        header += c_array(f"kAdst{n}", kernels[f"Adst_Kernel{n}"])
        header.append("")
    for n in FDST_SIZES:
        header += c_array(f"kFdst{n}", kernels[f"Fdst_Kernel{n}"])
        header.append("")

    header += [
        "// §9.2 transform-size geometry, indexed by the TX_* enum (0..24).",
        "struct TxSizeInfo {",
        "  std::int16_t width;",
        "  std::int16_t height;",
        "  std::int16_t adj_width;",
        "  std::int16_t adj_height;",
        "  std::int8_t log2_w;",
        "  std::int8_t log2_h;",
        "  std::int8_t row_shift;",
        "  std::int8_t col_shift;",
        "};",
        "",
        "inline constexpr TxSizeInfo kTxSizes[25] = {",
    ]
    for i in range(25):
        aw, ah = w[adj[i]], h[adj[i]]
        header.append(
            f"    /*{enum[i]:>10}*/ {{{w[i]:3d}, {h[i]:3d}, {aw:3d}, {ah:3d}, "
            f"{log2w[i]:2d}, {log2h[i]:2d}, {shifts[i][0]:2d}, {shifts[i][1]:2d}}},"
        )
    header += [
        "};",
        "",
        "// §7.15.4.1 get_identity_scale(log2Sz).",
        "inline constexpr int kIdentityScale[7] = {0, 0, 128, 181, 256, 362, 362};",
        "",
        "inline constexpr int identity_scale(int log2_sz) {",
        "  return log2_sz >= 2 && log2_sz <= 6 ? kIdentityScale[log2_sz] : 362;",
        "}",
        "",
        "}  // namespace av2enc::txv",
        "",
    ]
    (HERE / "tx_tables.h").write_text("\n".join(header))

    dev = [
        "// Generated by src/encoder/tx_variants/generate_tx_tables.py. Do not edit.",
        "// Device copies of tx_tables.h; included only from CUDA translation units.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace av2enc::txv::dev {",
        "",
    ]
    for n in DCT_SIZES:
        dev += dev_array(f"kDct{n}", kernels[f"Dct_Kernel{n}"])
        dev.append("")
    for n in ADST_SIZES:
        dev += dev_array(f"kAdst{n}", kernels[f"Adst_Kernel{n}"])
        dev.append("")
    for n in FDST_SIZES:
        dev += dev_array(f"kFdst{n}", kernels[f"Fdst_Kernel{n}"])
        dev.append("")

    dev += [
        "struct TxSizeInfoDev {",
        "  std::int16_t width, height, adj_width, adj_height;",
        "  std::int8_t log2_w, log2_h, row_shift, col_shift;",
        "};",
        "",
        "__device__ const TxSizeInfoDev kTxSizesDev[25] = {",
    ]
    for i in range(25):
        aw, ah = w[adj[i]], h[adj[i]]
        dev.append(
            f"    {{{w[i]:3d}, {h[i]:3d}, {aw:3d}, {ah:3d}, {log2w[i]:2d}, "
            f"{log2h[i]:2d}, {shifts[i][0]:2d}, {shifts[i][1]:2d}}},"
        )
    dev += [
        "};",
        "",
        "__device__ const int kIdentityScaleDev[7] = {0, 0, 128, 181, 256, 362, 362};",
        "",
        "}  // namespace av2enc::txv::dev",
        "",
    ]
    (HERE / "tx_tables_dev.cuh").write_text("\n".join(dev))

    total = sum(len(v) * len(v[0]) for v in kernels.values())
    print(f"wrote tx_tables.h and tx_tables_dev.cuh ({len(kernels)} kernels, {total} entries)")


if __name__ == "__main__":
    main()
