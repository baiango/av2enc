#!/usr/bin/env python3
"""Generate the M0 tile CDF tables from spec/tables/default_cdf.json.

The AV2 default CDF arrays are normative tables (§9.3) and must never be
hand-typed.  This script slices the leading COEFF_CDF_Q_CTXS dimension for
base_q_idx = 90 (qctx 0) and emits a typed C++ header.

Run from the repository root:

    python3 src/encoder/generate_m0_cdf.py

Output: src/encoder/m0_cdf_tables.h
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "spec" / "tables" / "default_cdf.json"
OUT = ROOT / "src" / "encoder" / "m0_cdf_tables.h"

# name in JSON -> (C++ identifier, qctx-sliced?)
ARRAYS = [
    ("Default_Do_Split_Cdf", "kDoSplitCdf", False),
    ("Default_Do_Square_Split_Cdf", "kDoSquareSplitCdf", False),
    ("Default_Rect_Type_Cdf", "kRectTypeCdf", False),
    ("Default_Y_Mode_Set_Cdf", "kYModeSetCdf", False),
    ("Default_Y_Mode_Index_Cdf", "kYModeIndexCdf", False),
    ("Default_Uv_Mode_Cfl_Not_Allowed_Cdf", "kUvModeCflNotAllowedCdf", False),
    ("Default_Txb_Skip_Cdf", "kTxbSkipCdf", True),
    ("Default_V_Txb_Skip_Cdf", "kVTxbSkipCdf", True),
    ("Default_Eob_Pt_256_Cdf", "kEobPt256Cdf", True),
    ("Default_Eob_Pt_1024_Cdf", "kEobPt1024Cdf", True),
    ("Default_Eob_Extra_Cdf", "kEobExtraCdf", True),
    ("Default_Coeff_Base_Cdf", "kCoeffBaseCdf", True),
    ("Default_Coeff_Base_Lf_Cdf", "kCoeffBaseLfCdf", True),
    ("Default_Coeff_Base_Eob_Cdf", "kCoeffBaseEobCdf", True),
    ("Default_Coeff_Base_Lf_Eob_Cdf", "kCoeffBaseLfEobCdf", True),
    ("Default_Coeff_Br_Cdf", "kCoeffBrCdf", True),
    ("Default_Coeff_Br_Lf_Cdf", "kCoeffBrLfCdf", True),
    ("Default_Coeff_Base_Uv_Cdf", "kCoeffBaseUvCdf", True),
    ("Default_Coeff_Base_Lf_Uv_Cdf", "kCoeffBaseLfUvCdf", True),
    ("Default_Coeff_Base_Eob_Uv_Cdf", "kCoeffBaseEobUvCdf", True),
    ("Default_Coeff_Base_Lf_Eob_Uv_Cdf", "kCoeffBaseLfEobUvCdf", True),
    ("Default_Coeff_Br_Uv_Cdf", "kCoeffBrUvCdf", True),
    ("Default_Dc_Sign_Cdf", "kDcSignCdf", True),
    ("Default_Intra_Tx_Type_Set1_Cdf", "kIntraTxTypeSet1Cdf", False),
]


def reshape(flat, dims):
    if len(dims) == 1:
        return flat
    step = len(flat) // dims[0]
    return [reshape(flat[i * step : (i + 1) * step], dims[1:]) for i in range(dims[0])]


def format_array(values, indent):
    if isinstance(values, int):
        return str(values)
    if values and isinstance(values[0], int):
        return "{ " + ", ".join(str(v) for v in values) + " }"
    inner = ",\n".join(
        " " * (indent + 2) + format_array(v, indent + 2) for v in values
    )
    return "{\n" + inner + "\n" + " " * indent + "}"


def main():
    data = json.loads(SRC.read_text())["arrays"]
    lines = [
        "// Generated by src/encoder/generate_m0_cdf.py from",
        "// spec/tables/default_cdf.json (AV2 v1.0.0 clause 9.3).",
        "// Do not hand-edit. base_q_idx = 90 selects COEFF_CDF_Q_CTXS slice 0.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace av2enc::m0 {",
        "",
    ]
    for json_name, cpp_name, sliced in ARRAYS:
        entry = data[json_name]
        dims = list(entry["shape"])
        flat = list(entry["data"])
        if sliced:
            assert dims[0] == 4, (json_name, dims)
            dims = dims[1:]
            step = len(flat) // 4
            flat = flat[:step]
        values = reshape(flat, dims)
        dims_cpp = "".join(f"[{d}]" for d in dims)
        lines.append(f"// {json_name} {entry['shape']}")
        lines.append(
            f"inline constexpr std::uint16_t {cpp_name}{dims_cpp} = "
            + format_array(values, 0)
            + ";"
        )
        lines.append("")
    lines.append("}  // namespace av2enc::m0")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
