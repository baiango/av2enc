#!/usr/bin/env python3
"""Generate format_tables.h from the AV2 v1.0.0 spec table dump.

The block-size / chroma-residual mapping is normative (spec §5.20.7.26,
`Subsampled_Size` in §9.2).  Hand-typing it is error-prone, so the component
keeps a generator like the rest of the repo's table code.

Usage:
    ./generate_format_tables.py            # rewrite format_tables.h
    ./generate_format_tables.py --check    # exit 1 if the file is stale

The input defaults to `<repo>/spec/tables/block_tables.json`.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

# Number of AV2 block sizes (BLOCK_4X4 .. BLOCK_64X8, Table 6.22).
EXPECTED_BLOCK_SIZES = 29
INVALID = 255


def repo_root() -> pathlib.Path:
    # .../src/encoder/format/generate_format_tables.py -> repo root
    return pathlib.Path(__file__).resolve().parents[3]


def load_tables(path: pathlib.Path) -> tuple[list[str], list[int], list[int], list[list[list[int]]]]:
    data = json.loads(path.read_text())

    names = data["enum_block_size"]["data"]
    wide = data["Num_4x4_Blocks_Wide"]["data"]
    high = data["Num_4x4_Blocks_High"]["data"]
    subsampled = data["Subsampled_Size"]["data"]

    if len(names) != EXPECTED_BLOCK_SIZES:
        raise SystemExit(f"expected {EXPECTED_BLOCK_SIZES} block sizes, got {len(names)}")
    if len(wide) != EXPECTED_BLOCK_SIZES or len(high) != EXPECTED_BLOCK_SIZES:
        raise SystemExit("Num_4x4_Blocks_Wide/High length mismatch")
    if len(subsampled) != EXPECTED_BLOCK_SIZES:
        raise SystemExit("Subsampled_Size length mismatch")

    widths = [int(v) * 4 for v in wide]
    heights = [int(v) * 4 for v in high]

    for idx, (w, h) in enumerate(zip(widths, heights)):
        if w <= 0 or h <= 0:
            raise SystemExit(f"non-positive block dimension at index {idx}: {w}x{h}")

    for idx, entry in enumerate(subsampled):
        if len(entry) != 2 or any(len(row) != 2 for row in entry):
            raise SystemExit(f"Subsampled_Size[{idx}] is not [2][2]")

    return list(names), widths, heights, subsampled


def render(names: list[str], widths: list[int], heights: list[int],
           subsampled: list[list[list[int]]]) -> str:
    out: list[str] = []
    out.append("// Generated by src/encoder/format/generate_format_tables.py.")
    out.append("// Source: spec/tables/block_tables.json (AV2 v1.0.0, §9.2).")
    out.append("// Do not edit by hand; rerun the generator instead.")
    out.append("#pragma once")
    out.append("")
    out.append("namespace av2enc::fmt {")
    out.append("")
    out.append(f"inline constexpr int kBlockSizeCount = {EXPECTED_BLOCK_SIZES};")
    out.append(f"inline constexpr int kInvalidBlockIndex = {INVALID};")
    out.append("")
    out.append("inline constexpr const char* kBlockSizeNames[kBlockSizeCount] = {")
    out.append("    " + ", ".join(f'"{name}"' for name in names) + ",")
    out.append("};")
    out.append("")
    out.append("inline constexpr int kBlockWidth[kBlockSizeCount] = {")
    out.append("    " + ", ".join(str(v) for v in widths) + ",")
    out.append("};")
    out.append("")
    out.append("inline constexpr int kBlockHeight[kBlockSizeCount] = {")
    out.append("    " + ", ".join(str(v) for v in heights) + ",")
    out.append("};")
    out.append("")
    out.append("// Subsampled_Size[block][subsampling_x][subsampling_y].")
    out.append("// kInvalidBlockIndex means the chroma residual size is not allowed.")
    out.append("inline constexpr int kSubsampledSize[kBlockSizeCount][2][2] = {")
    for row in subsampled:
        (a, b), (c, d) = row
        out.append("        {{" + str(a) + ", " + str(b) + "}, {" + str(c) + ", " + str(d) + "}},")
    out.append("    };")
    out.append("")
    out.append("}  // namespace av2enc::fmt")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=pathlib.Path,
                        default=repo_root() / "spec" / "tables" / "block_tables.json")
    parser.add_argument("--output", type=pathlib.Path,
                        default=pathlib.Path(__file__).resolve().parent / "format_tables.h")
    parser.add_argument("--check", action="store_true",
                        help="verify the output file is up to date without writing it")
    args = parser.parse_args()

    if not args.input.is_file():
        print(f"missing input table dump: {args.input}", file=sys.stderr)
        return 2

    names, widths, heights, subsampled = load_tables(args.input)
    text = render(names, widths, heights, subsampled)

    if args.check:
        try:
            current = args.output.read_text()
        except FileNotFoundError:
            print(f"missing generated file: {args.output}", file=sys.stderr)
            return 1
        if current != text:
            print(f"stale generated file: {args.output}", file=sys.stderr)
            return 1
        print(f"{args.output} is up to date")
        return 0

    args.output.write_text(text)
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
