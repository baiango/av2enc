#!/usr/bin/env python3
"""Generate scc_cdf.h from the committed AV2 v1.0.0 default-CDF extract.

The palette and intra-block-copy CDFs are *not* in `src/encoder/m0_cdf_tables.h`
(M0 never codes those tools).  They do exist in `spec/tables/default_cdf.json`,
which is generated from the normative PDF by `tools/spec_extract/`.  This script
only re-shapes those values into the array declarations the screen-content
modules use; no numbers are typed by hand.

Usage:  python3 src/encoder/palette/gen_scc_cdf.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "spec" / "tables" / "default_cdf.json"
OUT = Path(__file__).resolve().parent / "scc_cdf.h"

# name -> (C++ declaration, comment)
ARRAYS = [
    ("Default_Palette_Y_Mode_Cdf", "kPaletteYModeCdf", "[3]"),
    ("Default_Palette_Y_Size_Cdf", "kPaletteYSizeCdf", "[8]"),
    ("Default_Identity_Row_Y_Cdf", "kIdentityRowYCdf", "[4][4]"),
    ("Default_Intrabc_Cdf", "kIntrabcCdf", "[3][3]"),
    ("Default_Intrabc_Mode_Cdf", "kIntrabcModeCdf", "[3]"),
    # read_skip() is reachable for IBC blocks (intra frames only signal
    # skip_flag when use_intrabc == 1).  The palette path never uses it.
    ("Default_Skip_Cdf", "kSkipCdf", "[6][3]"),
]
for size in range(2, 9):
    ARRAYS.append(
        (
            f"Default_Palette_Size_{size}_Y_Color_Cdf",
            f"kPaletteSize{size}YColorCdf",
            f"[5][{size + 1}]",
        )
    )


def format_values(values, indent):
    out = []
    line = " " * indent
    for i, v in enumerate(values):
        token = f"{v},"
        if len(line) + len(token) + 1 > 88:
            out.append(line.rstrip())
            line = " " * indent
        line += token + " "
    out.append(line.rstrip())
    return "\n".join(out)


def main() -> int:
    data = json.loads(SRC.read_text())["arrays"]
    lines = [
        "// Generated by src/encoder/palette/gen_scc_cdf.py.",
        "// Source: AV2 v1.0.0 §9.3 default CDFs, via spec/tables/default_cdf.json",
        "// (commit 38f28e7). Do not hand-edit.",
        "//",
        "// Only the screen-content tool CDFs live here: palette (§5.20.8.1/.4) and",
        "// intra block copy (§5.20.5.4). Every array is the inverse-CDF form used by",
        "// av2enc::av2::Encoder: cdf[N] is the adaptation counter and cdf[0..N-1]",
        "// are the cumulative probabilities.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::scc {",
        "",
    ]
    for spec_name, cpp_name, dims in ARRAYS:
        entry = data[spec_name]
        values = entry["data"]
        shape = entry["shape"]
        # Flattened initializer is valid C++ for nested arrays; keep one row per
        # line when the last dimension is small enough to stay readable.
        lines.append(f"// {spec_name}{dims}  (§9.3)")
        lines.append(
            f"inline constexpr std::uint16_t {cpp_name}{dims} = {{"
        )
        if len(shape) == 2:
            row = shape[1]
            for r in range(shape[0]):
                chunk = values[r * row : (r + 1) * row]
                lines.append("    {" + format_values(chunk, 0).lstrip() + "},")
        else:
            lines.append("    " + format_values(values, 0))
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace av2enc::scc")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(ARRAYS)} arrays)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
