#!/usr/bin/env python3
"""Generate ext_tables_generated.h for the AV2 extended-partition reference.

Source of truth (never hand-typed):

  * spec/tables/block_tables.json   -- §9.2 Partition_Subsize, H_Partition_Midsize,
                                       Partition_Size_Adjust[_Rect_Type]
  * spec/tables/default_cdf.json    -- §9.3 Default_* partition CDFs

Usage:
    python3 src/encoder/partition_ext/generate_ext_tables.py
    python3 src/encoder/partition_ext/generate_ext_tables.py --check

The generated header is committed so the standalone build has no Python
dependency.  Re-run this script whenever the spec caches are regenerated; the
test binary fails if the checked-in header disagrees with the JSON.
"""

from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent.parent
BLOCK_JSON = REPO / "spec" / "tables" / "block_tables.json"
CDF_JSON = REPO / "spec" / "tables" / "default_cdf.json"
OUT = HERE / "ext_tables_generated.h"

PARTITION_NAMES = [
    "PARTITION_NONE",
    "PARTITION_HORZ",
    "PARTITION_VERT",
    "PARTITION_HORZ_3",
    "PARTITION_VERT_3",
    "PARTITION_HORZ_4A",
    "PARTITION_HORZ_4B",
    "PARTITION_VERT_4A",
    "PARTITION_VERT_4B",
    "PARTITION_SPLIT",
]

CDF_ARRAYS = [
    ("kDoSplitCdf", "Default_Do_Split_Cdf", 2, 64, 3),
    ("kDoSquareSplitCdf", "Default_Do_Square_Split_Cdf", 2, 8, 3),
    ("kRectTypeCdf", "Default_Rect_Type_Cdf", 2, 64, 3),
    ("kDoExtPartitionCdf", "Default_Do_Ext_Partition_Cdf", 2, 64, 3),
    ("kDoUneven4wayPartitionCdf", "Default_Do_Uneven_4way_Partition_Cdf", 2, 64, 3),
]


def fmt_int_table(name: str, ctype: str, values, per_line: int = 16) -> str:
    lines = []
    for i in range(0, len(values), per_line):
        chunk = ", ".join(str(v) for v in values[i : i + per_line])
        lines.append("    " + chunk + ",")
    body = "\n".join(lines)
    return f"inline constexpr {ctype} {name}[{len(values)}] = {{\n{body}\n}};\n"


def fmt_2d(name: str, ctype: str, rows, cols) -> str:
    out = [f"inline constexpr {ctype} {name}[{rows}][{cols}] = {{"]
    for row in rows:
        out.append("    {" + ", ".join(str(v) for v in row) + "},")
    out.append("};")
    return "\n".join(out) + "\n"


def fmt_cdf(name: str, values, d0: int, d1: int, d2: int) -> str:
    assert len(values) == d0 * d1 * d2, (name, len(values))
    out = [f"inline constexpr std::uint16_t {name}[{d0}][{d1}][{d2}] = {{"]
    cursor = 0
    for _ in range(d0):
        out.append("  {")
        for _ in range(d1):
            triple = values[cursor : cursor + 3]
            cursor += 3
            out.append("      {" + ", ".join(str(v) for v in triple) + "},")
        out.append("  },")
    out.append("};")
    return "\n".join(out) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    blocks = json.loads(BLOCK_JSON.read_text())
    cdfs = json.loads(CDF_JSON.read_text())["arrays"]

    subsize = blocks["Partition_Subsize"]["data"]
    midsize = blocks["H_Partition_Midsize"]["data"]
    adjust = blocks["Partition_Size_Adjust"]["data"]
    adjust_rect = blocks["Partition_Size_Adjust_Rect_Type"]["data"]
    assert blocks["Partition_Subsize"]["shape"] == [10, 29]
    assert len(subsize) == 10 and all(len(row) == 29 for row in subsize)

    parts = [
        "// Generated by generate_ext_tables.py -- do not edit by hand.",
        "//",
        "// Sources: spec/tables/block_tables.json (clause 9.2) and",
        "//          spec/tables/default_cdf.json  (clause 9.3).",
        "//",
        "// The CDF arrays are the *default* §9.3 tables.  A tile must use an",
        "// independent mutable copy; `init_default_cdfs()` does that.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::partition_ext {",
        "",
        "inline constexpr int kExtBlockSizeCount = 29;",
        "inline constexpr std::uint8_t kExtInvalidBlock = 255;",
        "",
        "// Partition_Subsize[partition][bSize], partition index is the §6.19.3",
        "// PartitionType enum value (0=NONE .. 9=SPLIT).",
        "// 255 == BLOCK_INVALID.",
    ]
    for p, name in enumerate(PARTITION_NAMES):
        parts.append(f"// row {p} = {name}")
    parts.append("inline constexpr std::uint8_t kPartitionSubsize[10][29] = {")
    for row in subsize:
        parts.append("    {" + ", ".join(str(v) for v in row) + "},")
    parts.append("};\n")

    parts.append(
        "// H_Partition_Midsize[bSize] (§9.2): half-width x half-height block used\n"
        "// by the middle pair of PARTITION_HORZ_3 / PARTITION_VERT_3."
    )
    parts.append(fmt_int_table("kHPartitionMidsize", "std::uint8_t", midsize))
    parts.append(
        "// Partition_Size_Adjust[bSize] (§9.2): do_split / do_ext_partition context\n"
        "// scale."
    )
    parts.append(fmt_int_table("kPartitionSizeAdjust", "std::uint8_t", adjust))
    parts.append(
        "// Partition_Size_Adjust_Rect_Type[bSize] (§9.2): rect_type context scale."
    )
    parts.append(
        fmt_int_table("kPartitionSizeAdjustRectType", "std::uint8_t", adjust_rect)
    )

    for cname, jname, d0, d1, d2 in CDF_ARRAYS:
        values = cdfs[jname]["data"]
        parts.append(f"// {jname} (§9.3), copied verbatim.")
        parts.append(fmt_cdf(cname, values, d0, d1, d2))

    parts.append("}  // namespace av2enc::partition_ext")
    parts.append("")

    text = "\n".join(parts)
    if check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"OUT OF DATE: {OUT}", file=sys.stderr)
            return 1
        print(f"up to date: {OUT}")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
