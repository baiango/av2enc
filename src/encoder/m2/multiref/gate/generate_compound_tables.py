#!/usr/bin/env python3
"""Generate the compound CDF header for the multi-reference gate.

Only the §9.3 arrays the gate's compound tile writer can select are emitted.
Partition / is_inter / skip / drl tables are re-used from the M0 and M2
headers, exactly as the M2 writer does.

Usage:
  python3 src/encoder/m2/multiref/gate/generate_compound_tables.py \
    > src/encoder/m2/multiref/gate/compound_cdf_tables.h
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
SOURCE = ROOT / "spec" / "tables" / "default_cdf.json"

ARRAYS = [
    ("kCompModeCdf", "Default_Comp_Mode_Cdf"),
    ("kCompRef0Cdf", "Default_Comp_Ref0_Cdf"),
    ("kCompRef1Cdf", "Default_Comp_Ref1_Cdf"),
    ("kIsJointCdf", "Default_Is_Joint_Cdf"),
    ("kCompoundModeNonJointCdf", "Default_Compound_Mode_Non_Joint_Cdf"),
    ("kCompoundModeSameRefsCdf", "Default_Compound_Mode_Same_Refs_Cdf"),
    ("kCompGroupIdxCdf", "Default_Comp_Group_Idx_Cdf"),
    ("kCompoundTypeCdf", "Default_Compound_Type_Cdf"),
    ("kWedgeQuadCdf", "Default_Wedge_Quad_Cdf"),
    ("kWedgeAngleCdf", "Default_Wedge_Angle_Cdf"),
    ("kWedgeDist1Cdf", "Default_Wedge_Dist1_Cdf"),
    ("kWedgeDist2Cdf", "Default_Wedge_Dist2_Cdf"),
    ("kCwpIdxCdf", "Default_Cwp_Idx_Cdf"),
]


def flatten(data):
    if isinstance(data, list):
        out = []
        for item in data:
            out.extend(flatten(item))
        return out
    return [data]


def dims(shape):
    return "".join(f"[{n}]" for n in shape)


def main() -> None:
    payload = json.loads(SOURCE.read_text())
    arrays = payload["arrays"]
    print("// Generated by src/encoder/m2/multiref/gate/generate_compound_tables.py.")
    print("// Source: AV2 v1.0.0 §9.3 default CDFs (commit 38f28e7).")
    print("// Do not hand-edit.")
    print("#pragma once")
    print()
    print("namespace av2enc::m2::multiref::gate {")
    print()
    for symbol, name in ARRAYS:
        entry = arrays[name]
        shape = entry["shape"]
        values = flatten(entry["data"])
        expected = 1
        for n in shape:
            expected *= n
        if len(values) != expected:
            raise SystemExit(
                f"{name}: got {len(values)} values, shape {shape} needs {expected}"
            )
        print(f"// {name} {shape}")
        print(f"inline constexpr unsigned short {symbol}{dims(shape)} = {{")
        line = "   "
        for value in values:
            piece = f" {value},"
            if len(line) + len(piece) > 78:
                print(line)
                line = "   "
            line += piece
        if line.strip():
            print(line)
        print("};")
        print()
    print("}  // namespace av2enc::m2::multiref::gate")
    print()


if __name__ == "__main__":
    main()
