#!/usr/bin/env python3
"""Vendor the M2 tile writer with one CCSO hook (gate use only).

The temporal-CCSO gate needs the §5.20.10.2 `read_ccso()` call immediately
before `read_partition()` at each superblock origin.  The M2 core is owned by
another workstream and must not be edited, so this script copies
`src/pipeline/video/video_syntax.cpp` into the build directory and injects that one
call, exactly like `filters/lr_chroma/gate/vendor_video_syntax.py` does for
`read_lr()`.

The transform is anchored on exact source text and on the source SHA-256.  If
the M2 writer changes, this fails loudly instead of silently producing a
different stream.

Usage:
    python3 vendor_video_syntax.py --out <build-dir>
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[4]
SOURCE = ROOT / "src" / "encoder" / "m2" / "video_syntax.cpp"
EXPECTED_SHA256 = (
    "fe401c60f5d9555a98b51f612eb40d823327b1a03db2c5a73aee62ea9bbbd879"
)

HEADER = """\
// Generated by vendor_video_syntax.py.  Do not edit.
#pragma once

#include <cstddef>
#include <cstdint>
#include <span>
#include <string>
#include <vector>

#include "codec/filters/ccso/ccso_reuse.h"
#include "pipeline/video/video_syntax.h"

namespace av2enc::ccso_reuse::gate {

// Identical to av2enc::video::syntax::assemble_video_frame(), except that `state`
// drives the §5.20.10.2 ccso_blk S() symbols before each superblock's
// read_partition().  Pass nullptr for a baseline (CCSO-off) tile.
bool assemble_video_frame_ccso(
    const av2enc::video::syntax::FramePlan& plan,
    std::span<const av2enc::video::syntax::BlockSyntax> blocks,
    std::span<const std::int32_t> levels, const av2enc::video::VideoConfig& config,
    av2enc::ccso_reuse::TileState* state,
    std::vector<std::uint8_t>& tile_payload, std::string& error,
    std::size_t* tile_bytes);

}  // namespace av2enc::ccso_reuse::gate
"""


def replace_once(text: str, old: str, new: str, what: str) -> str:
    if text.count(old) != 1:
        raise SystemExit(
            f"vendor_video_syntax: anchor for {what} occurs {text.count(old)} "
            "times; refusing to patch"
        )
    return text.replace(old, new, 1)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    out_dir = pathlib.Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    raw = SOURCE.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(
            "vendor_video_syntax: video_syntax.cpp changed\n"
            f"  expected {EXPECTED_SHA256}\n  actual   {digest}\n"
            "Update the hook and the pin together."
        )
    text = raw.decode("utf-8")

    text = replace_once(
        text,
        '#include "pipeline/video/video_syntax.h"\n',
        '#include "pipeline/video/video_syntax.h"\n\n'
        '#include "codec/filters/ccso/ccso_reuse.h"\n',
        "include",
    )
    text = replace_once(
        text,
        "namespace av2enc::video::syntax {\n",
        "namespace av2enc::ccso_reuse::gate {\n"
        "\n"
        "using namespace av2enc::video;\n"
        "using namespace av2enc::video::syntax;\n"
        "int gate_plan_sb_cols(const FramePlan& plan);\n"
        "int gate_plan_sb_rows(const FramePlan& plan);\n"
        "void build_scan(int w, int h, std::span<std::uint16_t> scan);\n"
        "bool gate_assemble_video_frame(\n"
        "    const FramePlan& plan, std::span<const BlockSyntax> blocks,\n"
        "    std::span<const std::int32_t> levels, const VideoConfig& config,\n"
        "    std::vector<std::uint8_t>& tile_payload, std::string& error,\n"
        "    std::size_t* tile_bytes);\n"
        "\n"
        "namespace {\n"
        "// Gate-only hook state.  The M2 tile writer is single-threaded.\n"
        "av2enc::ccso_reuse::TileState* g_ccso_state = nullptr;\n"
        "}  // namespace\n",
        "namespace open",
    )
    text = replace_once(
        text,
        "    const int sb_cols = plan_.sb_cols();\n"
        "    const int sb_rows = plan_.sb_rows();\n",
        "    const int sb_cols = gate_plan_sb_cols(plan_);\n"
        "    const int sb_rows = gate_plan_sb_rows(plan_);\n",
        "FramePlan use",
    )
    # §5.20.10.2 read_ccso() is called from mode_info(), after the skip /
    # segmentation fields and before the mode fields.  In the M2 writer those
    # points are the start of write_inter_mode_info() (is_inter == 1) and the
    # start of write_intra_leaf() (keyframe and is_inter == 0).
    text = replace_once(
        text,
        "  bool write_inter_mode_info(const BlockSyntax& node, "
        "std::string& error) {\n"
        "    if (node.inter_mode > kInterNewMv) {\n",
        "  bool write_inter_mode_info(const BlockSyntax& node, "
        "std::string& error) {\n"
        "    // §5.20.10.2 read_ccso() at the CCSO unit origin.\n"
        "    if (g_ccso_state != nullptr &&\n"
        "        !g_ccso_state->write_block(enc_, node.mi_row, node.mi_col,\n"
        "                                   &error)) {\n"
        "      return false;\n"
        "    }\n"
        "    if (node.inter_mode > kInterNewMv) {\n",
        "inter read_ccso hook",
    )
    text = replace_once(
        text,
        "  bool write_intra_leaf(const BlockSyntax& node, int w, int h, int cw, "
        "int ch,\n"
        "                        std::string& error) {\n"
        "    // Validate the declared transform sizes against TX_MODE_LARGEST "
        "geometry\n",
        "  bool write_intra_leaf(const BlockSyntax& node, int w, int h, int cw, "
        "int ch,\n"
        "                        std::string& error) {\n"
        "    // §5.20.10.2 read_ccso() at the CCSO unit origin.\n"
        "    if (g_ccso_state != nullptr &&\n"
        "        !g_ccso_state->write_block(enc_, node.mi_row, node.mi_col,\n"
        "                                   &error)) {\n"
        "      return false;\n"
        "    }\n"
        "    // Validate the declared transform sizes against TX_MODE_LARGEST "
        "geometry\n",
        "intra read_ccso hook",
    )
    text = replace_once(
        text,
        """int FramePlan::sb_cols() const {
  FrameGeometry geometry;
  geometry.width = width;
  geometry.height = height;
  geometry.sb_size = sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_cols(geometry) + sb_mi - 1) / sb_mi;
}

int FramePlan::sb_rows() const {
  FrameGeometry geometry;
  geometry.width = width;
  geometry.height = height;
  geometry.sb_size = sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_rows(geometry) + sb_mi - 1) / sb_mi;
}

int FramePlan::superblock_count() const { return sb_cols() * sb_rows(); }
""",
        """int gate_plan_sb_cols(const FramePlan& plan) {
  FrameGeometry geometry;
  geometry.width = plan.width;
  geometry.height = plan.height;
  geometry.sb_size = plan.sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_cols(geometry) + sb_mi - 1) / sb_mi;
}

int gate_plan_sb_rows(const FramePlan& plan) {
  FrameGeometry geometry;
  geometry.width = plan.width;
  geometry.height = plan.height;
  geometry.sb_size = plan.sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_rows(geometry) + sb_mi - 1) / sb_mi;
}
""",
        "FramePlan definitions",
    )
    text = replace_once(
        text,
        "bool assemble_video_frame(const FramePlan& plan,\n"
        "                             std::span<const BlockSyntax> blocks,\n"
        "                             std::span<const std::int32_t> levels,\n"
        "                             const VideoConfig& config,\n"
        "                             std::vector<std::uint8_t>& tile_payload,\n"
        "                             std::string& error, std::size_t* tile_bytes) {\n",
        "bool gate_assemble_video_frame(const FramePlan& plan,\n"
        "                             std::span<const BlockSyntax> blocks,\n"
        "                             std::span<const std::int32_t> levels,\n"
        "                             const VideoConfig& config,\n"
        "                             std::vector<std::uint8_t>& tile_payload,\n"
        "                             std::string& error, std::size_t* tile_bytes) {\n",
        "internal assemble rename",
    )
    text = replace_once(
        text,
        "}  // namespace av2enc::video::syntax\n",
        """bool assemble_video_frame_ccso(
    const FramePlan& plan, std::span<const BlockSyntax> blocks,
    std::span<const std::int32_t> levels, const VideoConfig& config,
    av2enc::ccso_reuse::TileState* state,
    std::vector<std::uint8_t>& tile_payload, std::string& error,
    std::size_t* tile_bytes) {
  g_ccso_state = state;
  const bool ok =
      gate_assemble_video_frame(plan, blocks, levels, config, tile_payload,
                             error, tile_bytes);
  g_ccso_state = nullptr;
  return ok;
}

}  // namespace av2enc::ccso_reuse::gate
""",
        "namespace close",
    )

    (out_dir / "video_syntax_ccso.cpp").write_text(text)
    (out_dir / "video_syntax_ccso.h").write_text(HEADER)
    print(f"wrote {out_dir / 'video_syntax_ccso.cpp'} ({len(text.splitlines())} lines)")
    print(f"wrote {out_dir / 'video_syntax_ccso.h'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
