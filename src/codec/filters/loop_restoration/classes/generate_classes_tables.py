#!/usr/bin/env python3
"""Generate the hand-free tables used by the Wiener encoder search.

    python3 src/codec/filters/loop_restoration/classes/generate_classes_tables.py

Inputs (both are committed, generated artefacts of the pinned spec):

  spec/tables/default_cdf.json  ->  wiener_cdfs.h
      Default_Use_Wiener_Ns_Cdf, Default_Wiener_Ns_Length_Cdf,
      Default_Wiener_Ns_Uv_Sym_Cdf, Default_Wiener_Ns_Base_Cdf,
      Default_Use_Pc_Wiener_Cdf, Default_Flex_Restoration_Type_Cdf.
      Clauses §9.3 / §8.3.  Never hand-typed.

  spec/tables/quant.json        ->  wiener_qlookup.h
      qlookup(q) for q = 0..255 and Ac_Qlookup[0] (used by
      get_q(qindex, 0), §7.14.2).  Indirectly needed by
      get_qval_given_tskip() in §7.20.4.

What this script deliberately does *not* generate: Pc_Wiener_Sub_Classify2,
Pc_Wiener_Lut_To_Class, Pc_Wiener_Sub_Classify and Pc_Wiener_Filters.  §9.8
only says they are "defined in the ... header file"; those attachments are not
part of the specification text or of spec/tables/.  The encoder API takes them
from the caller and refuses multi-class frame filters without them.
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
TABLES = ROOT / "spec" / "tables"

BANNER = """// Generated by generate_classes_tables.py from {src}.  Do not edit.
// Normative reference: AV2 Bitstream & Decoding Process Specification
// v1.0.0 (commit 38f28e7).
"""


def read_json(name: str) -> dict:
    with (TABLES / name).open() as f:
        return json.load(f)


def write_cdfs() -> None:
    arrays = read_json("default_cdf.json")["arrays"]
    wanted = [
        ("Default_Use_Wiener_Ns_Cdf", "kUseWienerNsCdf", "std::uint16_t"),
        ("Default_Use_Pc_Wiener_Cdf", "kUsePcWienerCdf", "std::uint16_t"),
        ("Default_Wiener_Ns_Length_Cdf", "kWienerNsLengthCdf", "std::uint16_t"),
        ("Default_Wiener_Ns_Uv_Sym_Cdf", "kWienerNsUvSymCdf", "std::uint16_t"),
        ("Default_Wiener_Ns_Base_Cdf", "kWienerNsBaseCdf", "std::uint16_t"),
        ("Default_Flex_Restoration_Type_Cdf", "kFlexRestorationTypeCdf",
         "std::uint16_t"),
    ]

    out = [
        BANNER.format(src="spec/tables/default_cdf.json"),
        "",
        "#ifndef AV2ENC_ENCODER_FILTERS_RESTORATION_CLASSES_WIENER_CDFS_H_",
        "#define AV2ENC_ENCODER_FILTERS_RESTORATION_CLASSES_WIENER_CDFS_H_",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::restoration::classes {",
        "",
    ]

    for spec_name, c_name, ctype in wanted:
        entry = arrays[spec_name]
        shape = entry["shape"]
        data = entry["data"]
        if len(shape) == 1:
            dims = f"[{shape[0]}]"
        elif len(shape) == 2:
            dims = f"[{shape[0]}][{shape[1]}]"
        elif len(shape) == 3:
            dims = f"[{shape[0]}][{shape[1]}][{shape[2]}]"
        else:  # pragma: no cover - the spec has no wider restoration CDF
            raise SystemExit(f"unexpected CDF rank for {spec_name}")
        out.append(f"// {spec_name}, §9.3.")
        out.append(f"inline constexpr {ctype} {c_name}{dims} = {{")
        if len(shape) == 1:
            out.append("    " + ", ".join(str(v) for v in data) + ",")
        elif len(shape) == 2:
            for i in range(shape[0]):
                row = data[i * shape[1]:(i + 1) * shape[1]]
                out.append("    {" + ", ".join(str(v) for v in row) + "},")
        else:
            for i in range(shape[0]):
                out.append("    {")
                for j in range(shape[1]):
                    base = (i * shape[1] + j) * shape[2]
                    row = data[base:base + shape[2]]
                    out.append("        {" + ", ".join(str(v) for v in row) +
                               "},")
                out.append("    },")
        out.append("};")
        out.append("")

    out += [
        "}  // namespace av2enc::restoration::classes",
        "",
        "#endif  // AV2ENC_ENCODER_FILTERS_RESTORATION_CLASSES_WIENER_CDFS_H_",
        "",
    ]
    (HERE / "wiener_cdfs.h").write_text("\n".join(out))


def write_qlookup() -> None:
    quant = read_json("quant.json")
    lookup = quant["qlookup_q0_255"]
    ac = quant["Ac_Qlookup"]
    if len(lookup) != 256 or len(ac) != 25:
        raise SystemExit("unexpected quant.json shape")

    out = [
        BANNER.format(src="spec/tables/quant.json"),
        "",
        "#ifndef AV2ENC_ENCODER_FILTERS_RESTORATION_CLASSES_WIENER_QLOOKUP_H_",
        "#define AV2ENC_ENCODER_FILTERS_RESTORATION_CLASSES_WIENER_QLOOKUP_H_",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::restoration::classes {",
        "",
        "// §7.14.2 Ac_Qlookup[25] and qlookup(q) for 8-bit (q = 0..255).",
        "inline constexpr std::int32_t kAcQlookup[25] = {",
    ]
    for i in range(0, 25, 8):
        out.append("    " + ", ".join(str(v) for v in ac[i:i + 8]) + ",")
    out += [
        "};",
        "",
        "// §7.14.2 get_q(qindex, 0) for 8-bit (MaxQ = 255).",
        "inline constexpr std::int32_t kQlookupQ0To255[256] = {",
    ]
    for i in range(0, 256, 8):
        out.append("    " + ", ".join(str(v) for v in lookup[i:i + 8]) + ",")
    out += [
        "};",
        "",
        "}  // namespace av2enc::restoration::classes",
        "",
        "#endif  // AV2ENC_ENCODER_FILTERS_RESTORATION_CLASSES_WIENER_QLOOKUP_H_",
        "",
    ]
    (HERE / "wiener_qlookup.h").write_text("\n".join(out))


def main() -> None:
    write_cdfs()
    write_qlookup()
    print("wrote wiener_cdfs.h, wiener_qlookup.h")


if __name__ == "__main__":
    main()
