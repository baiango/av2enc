#!/usr/bin/env python3
"""Vendor the M2 tile writer with one PC-Wiener LR hook (gate use only).

The PC-Wiener loop-restoration gate needs one call to `read_lr()` immediately
before `read_partition()` in the M2 tile writer (§5.20.10.4).  The M2 core is
owned by another workstream and must not be edited, so this script makes an
exact copy of `src/pipeline/video/video_syntax.cpp` in the build directory and injects
that one call.

The transform is anchored on exact source text and on the source SHA-256.  If
the M2 writer changes, this fails loudly instead of silently producing a
different stream.

Usage:
    python3 vendor_video_syntax.py --out <build-dir>
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[4]
SOURCE = ROOT / "src" / "encoder" / "m2" / "video_syntax.cpp"
EXPECTED_SHA256 = (
    "fe401c60f5d9555a98b51f612eb40d823327b1a03db2c5a73aee62ea9bbbd879"
)

HEADER = """\
// Generated by vendor_video_syntax_pc.py.  Do not edit.
#pragma once

#include <cstddef>
#include <cstdint>
#include <span>
#include <string>
#include <vector>

#include "codec/filters/pc_wiener/pc_wiener_stream.h"
#include "pipeline/video/video_syntax.h"

namespace av2enc::filters::pc_wiener_stream::gate {

namespace pcw = av2enc::filters::pc_wiener_stream;

// Identical to av2enc::video::syntax::assemble_video_frame(), except that
// `lr_state`/`lr_units` drive the §5.20.10.4 read_lr() call before each
// superblock's read_partition().  Pass nullptr for both for a baseline
// (no-LR) tile.
bool assemble_video_frame_pcw(
    const av2enc::video::syntax::FramePlan& plan,
    std::span<const av2enc::video::syntax::BlockSyntax> blocks,
    std::span<const std::int32_t> levels, const av2enc::video::VideoConfig& config,
    pcw::TileState* lr_state,
    const std::vector<pcw::UnitDecision>* lr_units,
    std::vector<std::uint8_t>& tile_payload, std::string& error,
    std::size_t* tile_bytes);

}  // namespace av2enc::filters::pc_wiener_stream::gate
"""


def replace_once(text: str, old: str, new: str, what: str) -> str:
    if text.count(old) != 1:
        raise SystemExit(
            f"vendor_video_syntax: anchor for {what} occurs {text.count(old)} "
            "times; refusing to patch"
        )
    return text.replace(old, new, 1)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    out_dir = pathlib.Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    raw = SOURCE.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(
            "vendor_video_syntax: video_syntax.cpp changed\n"
            f"  expected {EXPECTED_SHA256}\n  actual   {digest}\n"
            "Update the hook and the pin together."
        )
    text = raw.decode("utf-8")

    text = replace_once(
        text,
        '#include "pipeline/video/video_syntax.h"\n',
        '#include "pipeline/video/video_syntax.h"\n\n'
        '#include "codec/filters/pc_wiener/pc_wiener_stream.h"\n',
        "include",
    )
    text = replace_once(
        text,
        "namespace av2enc::video::syntax {\n",
        "namespace av2enc::filters::pc_wiener_stream::gate {\n"
        "\n"
        "using namespace av2enc::video;\n"
        "using namespace av2enc::video::syntax;\n"
        "int gate_plan_sb_cols(const FramePlan& plan);\n"
        "int gate_plan_sb_rows(const FramePlan& plan);\n"
        "void build_scan(int w, int h, std::span<std::uint16_t> scan);\n"
        "bool gate_assemble_video_frame(\n"
        "    const FramePlan& plan, std::span<const BlockSyntax> blocks,\n"
        "    std::span<const std::int32_t> levels, const VideoConfig& config,\n"
        "    std::vector<std::uint8_t>& tile_payload, std::string& error,\n"
        "    std::size_t* tile_bytes);\n"
        "\n"
        "namespace pcw = av2enc::filters::pc_wiener_stream;\n"
        "namespace {\n"
        "// Gate-only hook state.  The M2 tile writer is single-threaded.\n"
        "pcw::TileState* g_lr_state = nullptr;\n"
        "const std::vector<pcw::UnitDecision>* g_lr_units = nullptr;\n"
        "}  // namespace\n",
        "namespace open",
    )
    text = replace_once(
        text,
        "    const int sb_cols = plan_.sb_cols();\n"
        "    const int sb_rows = plan_.sb_rows();\n",
        "    const int sb_cols = gate_plan_sb_cols(plan_);\n"
        "    const int sb_rows = gate_plan_sb_rows(plan_);\n",
        "FramePlan use",
    )
    text = replace_once(
        text,
        """      if (node.mi_col == 0) {
        // New superblock row: the left partition context restarts.  Mirrors
        // `if (sb.mi_col == 0) clear_left_context()` in still_encoder.
        clear_left_context();
      }
      std::size_t next = 0;
""",
        """      if (node.mi_col == 0) {
        // New superblock row: the left partition context restarts.  Mirrors
        // `if (sb.mi_col == 0) clear_left_context()` in still_encoder.
        clear_left_context();
      }
      // §5.20.10.4 read_lr(): once per superblock, BEFORE read_partition().
      if (g_lr_state != nullptr && g_lr_units != nullptr) {
        std::vector<pcw::UnitDecision> decisions;
        for (int plane = 0; plane < 3; ++plane) {
          pcw::UnitRange range;
          if (!pcw::UnitRangeFor(*g_lr_state, plane, node.mi_row, node.mi_col,
                                 sb_mi, sb_mi, 0, 0, &range, &error)) {
            return false;
          }
          for (int r = range.row_begin; r < range.row_end; ++r) {
            for (int c = range.col_begin; c < range.col_end; ++c) {
              const int cols = g_lr_state->unit_cols[plane];
              decisions.push_back((*g_lr_units)[static_cast<std::size_t>(r) *
                                                    cols +
                                                c]);
            }
          }
        }
        if (!pcw::WriteBlock(enc_, *g_lr_state, node.mi_row, node.mi_col, sb_mi,
                             sb_mi, 0, 0, decisions, &error)) {
          return false;
        }
      }
      std::size_t next = 0;
""",
        "read_lr hook",
    )
    text = replace_once(
        text,
        """int FramePlan::sb_cols() const {
  FrameGeometry geometry;
  geometry.width = width;
  geometry.height = height;
  geometry.sb_size = sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_cols(geometry) + sb_mi - 1) / sb_mi;
}

int FramePlan::sb_rows() const {
  FrameGeometry geometry;
  geometry.width = width;
  geometry.height = height;
  geometry.sb_size = sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_rows(geometry) + sb_mi - 1) / sb_mi;
}

int FramePlan::superblock_count() const { return sb_cols() * sb_rows(); }
""",
        """int gate_plan_sb_cols(const FramePlan& plan) {
  FrameGeometry geometry;
  geometry.width = plan.width;
  geometry.height = plan.height;
  geometry.sb_size = plan.sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_cols(geometry) + sb_mi - 1) / sb_mi;
}

int gate_plan_sb_rows(const FramePlan& plan) {
  FrameGeometry geometry;
  geometry.width = plan.width;
  geometry.height = plan.height;
  geometry.sb_size = plan.sb_size;
  const int sb_mi = partition::sb_size_mi(geometry);
  return (partition::mi_rows(geometry) + sb_mi - 1) / sb_mi;
}
""",
        "FramePlan definitions",
    )
    text = replace_once(
        text,
        "bool assemble_video_frame(const FramePlan& plan,\n"
        "                             std::span<const BlockSyntax> blocks,\n"
        "                             std::span<const std::int32_t> levels,\n"
        "                             const VideoConfig& config,\n"
        "                             std::vector<std::uint8_t>& tile_payload,\n"
        "                             std::string& error, std::size_t* tile_bytes) {\n",
        "bool gate_assemble_video_frame(const FramePlan& plan,\n"
        "                             std::span<const BlockSyntax> blocks,\n"
        "                             std::span<const std::int32_t> levels,\n"
        "                             const VideoConfig& config,\n"
        "                             std::vector<std::uint8_t>& tile_payload,\n"
        "                             std::string& error, std::size_t* tile_bytes) {\n",
        "internal assemble rename",
    )
    text = replace_once(
        text,
        "}  // namespace av2enc::video::syntax\n",
        """bool assemble_video_frame_pcw(
    const FramePlan& plan, std::span<const BlockSyntax> blocks,
    std::span<const std::int32_t> levels, const VideoConfig& config,
    pcw::TileState* lr_state,
    const std::vector<pcw::UnitDecision>* lr_units,
    std::vector<std::uint8_t>& tile_payload, std::string& error,
    std::size_t* tile_bytes) {
  g_lr_state = lr_state;
  g_lr_units = lr_units;
  const bool ok =
      gate_assemble_video_frame(plan, blocks, levels, config, tile_payload, error,
                             tile_bytes);
  g_lr_state = nullptr;
  g_lr_units = nullptr;
  return ok;
}

}  // namespace av2enc::filters::pc_wiener_stream::gate
""",
        "namespace close",
    )

    (out_dir / "video_syntax_pcw.cpp").write_text(text)
    (out_dir / "video_syntax_pcw.h").write_text(HEADER)
    print(f"wrote {out_dir / 'video_syntax_pcw.cpp'} ({len(text.splitlines())} lines)")
    print(f"wrote {out_dir / 'video_syntax_pcw.h'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
