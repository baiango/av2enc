#!/usr/bin/env python3
"""Generate mc_subpel_tables.h from the pinned AV2 specification PDF.

The AV2 spec only carries the normative Subpel_Filters table in the PDF
(§7.13.3.18, table on pages 488-490 of the v1.0.0 PDF).  Hand-typing 768
coefficients is error-prone, so this script extracts them and emits a header.

    python3 gen_subpel_tables.py [--pdf ../../../../spec/AV2_Spec_v1.0.0.pdf]
    python3 gen_subpel_tables.py --check    # verify the checked-in header

The script refuses to write unless it finds exactly 6*16*8 values, each phase
sums to 128, and the eight-tap table matches the AV1/AV2 regular phase 0 entry.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
DEFAULT_PDF = HERE.parents[3] / "spec" / "AV2_Spec_v1.0.0.pdf"
OUT = HERE / "mc_subpel_tables.h"

EXPECTED_VALUES = 6 * 16 * 8


def extract(pdf_path: pathlib.Path) -> list[list[list[int]]]:
    try:
        import fitz  # PyMuPDF
    except ImportError as exc:  # pragma: no cover - environment dependent
        raise SystemExit("PyMuPDF is required: pip install pymupdf") from exc

    doc = fitz.open(pdf_path)
    text = ""
    for page in range(486, 492):  # PDF pages 487-492, 0-based indices
        text += doc[page].get_text()
        text += "\n"

    if "Subpel_Filters[ 6 ][ 16 ][ 8 ] = {" not in text:
        raise SystemExit("Subpel_Filters table not found in the PDF")

    # The PDF text order interleaves the table tail with following prose, so
    # match the 8-coefficient rows directly instead of slicing the body.
    rows = re.findall(
        r"\{\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*"
        r"(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*\}",
        text,
    )
    vals = [[int(x) for x in row] for row in rows]
    if len(vals) != EXPECTED_VALUES // 8:
        raise SystemExit(
            f"expected {EXPECTED_VALUES // 8} filter-phase rows, got {len(vals)}"
        )

    table: list[list[list[int]]] = []
    k = 0
    for _ in range(6):
        filt = []
        for _ in range(16):
            phase = vals[k]
            k += 1
            if sum(phase) != 128:
                raise SystemExit(f"phase does not sum to 128: {phase}")
            filt.append(phase)
        table.append(filt)
    return table


def render(table: list[list[list[int]]]) -> str:
    lines = []
    lines.append("// Generated by gen_subpel_tables.py — do not edit by hand.")
    lines.append("//")
    lines.append("// AV2 v1.0.0 §7.13.3.18 Subpel_Filters[6][16][8].")
    lines.append("// Source: spec/AV2_Spec_v1.0.0.pdf (2026-05-28, commit 38f28e7).")
    lines.append("//")
    lines.append("// Filter indices: 0 EIGHTTAP, 1 EIGHTTAP_SMOOTH, 2 EIGHTTAP_SHARP,")
    lines.append("// 3 BILINEAR, 4 four-tap EIGHTTAP, 5 four-tap EIGHTTAP_SMOOTH.")
    lines.append("// Indices 4/5 are only used when w <= 4 (horizontal pass) or")
    lines.append("// h <= 4 (vertical pass); their zero-padded entries let the same")
    lines.append("// eight-tap loop implement both.")
    lines.append("#ifndef AV2ENC_ENCODER_INTER_MC_MC_SUBPEL_TABLES_H_")
    lines.append("#define AV2ENC_ENCODER_INTER_MC_MC_SUBPEL_TABLES_H_")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("// Host and device compilation passes need different storage classes for")
    lines.append("// a namespace-scope constexpr table (same pattern as deblock_core.h).")
    lines.append("#if defined(__CUDA_ARCH__)")
    lines.append("#define AV2ENC_MC_SUBPEL_TABLE __device__ constexpr")
    lines.append("#else")
    lines.append("#define AV2ENC_MC_SUBPEL_TABLE inline constexpr")
    lines.append("#endif")
    lines.append("")
    lines.append("namespace av2enc::inter::mc {")
    lines.append("")
    lines.append("inline constexpr int kSubpelFilterTypes = 6;")
    lines.append("inline constexpr int kSubpelPhases = 16;")
    lines.append("inline constexpr int kSubpelTaps = 8;")
    lines.append("")
    lines.append("AV2ENC_MC_SUBPEL_TABLE std::int16_t")
    lines.append("    kSubpelFilters[kSubpelFilterTypes][kSubpelPhases][kSubpelTaps] = {")
    names = [
        "EIGHTTAP",
        "EIGHTTAP_SMOOTH",
        "EIGHTTAP_SHARP",
        "BILINEAR",
        "FOURTAP",
        "FOURTAP_SMOOTH",
    ]
    for fi, filt in enumerate(table):
        lines.append(f"  {{  // {fi}: {names[fi]}")
        for phase in filt:
            vals = ", ".join(f"{v:4d}" for v in phase)
            lines.append("      {" + vals + "},")
        lines.append("  },")
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace av2enc::inter::mc")
    lines.append("")
    lines.append("#undef AV2ENC_MC_SUBPEL_TABLE")
    lines.append("")
    lines.append("#endif  // AV2ENC_ENCODER_INTER_MC_MC_SUBPEL_TABLES_H_")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pdf", type=pathlib.Path, default=DEFAULT_PDF)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    table = extract(args.pdf)
    rendered = render(table)

    if args.check:
        if not OUT.exists() or OUT.read_text() != rendered:
            print(f"{OUT} is out of date; rerun without --check", file=sys.stderr)
            return 1
        print(f"{OUT} matches the spec table")
        return 0

    OUT.write_text(rendered)
    print(f"wrote {OUT} ({EXPECTED_VALUES} coefficients)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
