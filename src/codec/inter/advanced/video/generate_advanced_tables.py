#!/usr/bin/env python3
"""Generate advanced_cdf_tables.h from the normative spec tables.

Source: spec/tables/default_cdf.json (AV2 v1.0.0 §9.3, commit 38f28e7) and
spec/tables/block_tables.json (§9.2).  This mirrors the M2 generator style:
the generated header is committed so normal builds do not need the PDF.

Usage:
    python3 src/codec/inter/advanced/video/generate_advanced_tables.py
    python3 src/codec/inter/advanced/video/generate_advanced_tables.py --check
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[3]
DEFAULT_CDF = ROOT / "spec" / "tables" / "default_cdf.json"
BLOCK_TABLES = ROOT / "spec" / "tables" / "block_tables.json"
OUT = HERE / "advanced_cdf_tables.h"

# (C++ identifier, spec name, rows, columns).  shape [R, C] in the JSON means
# R rows of C entries.  A shape of [C] is one row of C entries.
ARRAYS = [
    ("kIsWarpCdf", "Default_Is_Warp_Cdf", 5, 3),
    ("kWarpMvCdf", "Default_Warp_Mv_Cdf", 1, 3),
    ("kWarpIdxCdf", "Default_Warp_Idx_Cdf", 3, 3),
    ("kWarpWithMvdCdf", "Default_Warp_With_Mvd_Cdf", 1, 3),
    ("kWarpPrecisionCdf", "Default_Warp_Precision_Cdf", 29, 3),
    ("kWarpDeltaParamLowCdf", "Default_Warp_Delta_Param_Low_Cdf", 2, 9),
    ("kWarpDeltaParamHighCdf", "Default_Warp_Delta_Param_High_Cdf", 2, 9),
    ("kWarpDeltaParamSignCdf", "Default_Warp_Delta_Param_Sign_Cdf", 1, 3),
    ("kInterIntraCdf", "Default_Inter_Intra_Cdf", 4, 3),
    ("kWarpInterIntraCdf", "Default_Warp_Inter_Intra_Cdf", 4, 3),
    ("kInterIntraModeCdf", "Default_Inter_Intra_Mode_Cdf", 4, 5),
    ("kWedgeInterIntraCdf", "Default_Wedge_Inter_Intra_Cdf", 1, 3),
    ("kWedgeQuadCdf", "Default_Wedge_Quad_Cdf", 1, 5),
    ("kWedgeAngleCdf", "Default_Wedge_Angle_Cdf", 4, 6),
    ("kWedgeDist1Cdf", "Default_Wedge_Dist1_Cdf", 1, 5),
    ("kWedgeDist2Cdf", "Default_Wedge_Dist2_Cdf", 1, 4),
    ("kUseBawpCdf", "Default_Use_Bawp_Cdf", 1, 3),
    ("kUseBawpChromaCdf", "Default_Use_Bawp_Chroma_Cdf", 1, 3),
    ("kExplicitBawpCdf", "Default_Explicit_Bawp_Cdf", 3, 3),
    ("kExplicitBawpScaleCdf", "Default_Explicit_Bawp_Scale_Cdf", 1, 3),
    ("kUseLocalWarpCdf", "Default_Use_Local_Warp_Cdf", 4, 3),
    ("kUseExtendWarpCdf", "Default_Use_Extend_Warp_Cdf", 3, 3),
]


def _dimensions(data: dict, rows: int, cols: int) -> list[list[int]]:
    values = data["data"]
    if rows == 1:
        if len(values) != cols:
            raise SystemExit(f"shape mismatch: expected {cols}, got {len(values)}")
        return [values]
    if len(values) != rows * cols:
        raise SystemExit(f"shape mismatch: expected {rows * cols}, got {len(values)}")
    return [values[r * cols : (r + 1) * cols] for r in range(rows)]


def _emit_array(name: str, rows: list[list[int]], rows_decl: int, cols: int) -> str:
    lines = [f"// {rows_decl} x {cols}" if rows_decl > 1 else f"// {cols} entries"]
    if rows_decl == 1:
        body = ", ".join(str(v) for v in rows[0])
        lines.append(f"inline constexpr unsigned short {name}[{cols}] = {{")
        lines.append(f"    {body},")
        lines.append("};")
    else:
        lines.append(
            f"inline constexpr unsigned short {name}[{rows_decl}][{cols}] = {{"
        )
        for row in rows:
            body = ", ".join(str(v) for v in row)
            lines.append(f"    {{{body}}},")
        lines.append("};")
    return "\n".join(lines)


def build() -> str:
    cdf = json.loads(DEFAULT_CDF.read_text())
    arrays = cdf["arrays"]
    blocks = json.loads(BLOCK_TABLES.read_text())["Size_Group"]
    if blocks["shape"] != [29]:
        raise SystemExit("Size_Group shape changed")

    chunks = [
        "// Generated by src/codec/inter/advanced/video/generate_advanced_tables.py.",
        "// Source: AV2 v1.0.0 §9.2/§9.3 (commit 38f28e7).",
        "// Do not hand-edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::video::adv::cdf {",
        "",
        "// §9.2 Size_Group[BLOCK_SIZES]: intra/inter context bucket per MiSize.",
        "inline constexpr std::int8_t kSizeGroup[29] = {",
        "    " + ", ".join(str(v) for v in blocks["data"]),
        "};",
        "",
    ]

    for name, spec_name, rows, cols in ARRAYS:
        if spec_name not in arrays:
            raise SystemExit(f"missing {spec_name}")
        data = arrays[spec_name]
        expected = [rows, cols] if rows > 1 else [cols]
        if data["shape"] != expected:
            raise SystemExit(
                f"{spec_name}: shape {data['shape']} != expected {expected}"
            )
        chunks.append(_emit_array(name, _dimensions(data, rows, cols), rows, cols))
        chunks.append("")

    chunks.append("}  // namespace av2enc::video::adv::cdf")
    chunks.append("")
    return "\n".join(chunks)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; rerun without --check", file=sys.stderr)
            return 1
        print(f"{OUT}: up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
