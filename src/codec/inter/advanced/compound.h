#ifndef AV2ENC_INTER_ADVANCED_COMPOUND_H_
#define AV2ENC_INTER_ADVANCED_COMPOUND_H_

// CPU reference and encoder-side search for AV2 v1.0.0 compound prediction and
// inter-intra (§7.13.3.14, §7.13.3.27–.30).
//
// This component does not run motion compensation. The caller supplies the two
// compound predictions (`Preds[0]`, `Preds[1]`, 1/16 sample precision) from
// src/encoder/inter/mc/, plus the source block for the encoder-side decision.
//
// Usage sketch:
//
//   adv::CompoundJob job;                 // see compound_common.h
//   job.plane = 0; job.rect = {x, y, w, h}; job.bsize = bsize;
//   job.p0 = preds[0]; job.p1 = preds[1];
//   job.type = adv::CompoundType::kWedge;
//   job.wedge_index = 12; job.wedge_sign = 1;
//   job.dst = recon; job.dst_stride = stride;
//   adv::apply_compound(job);             // writes the blended luma
//
//   adv::CompoundSearchInput in{...};
//   auto best = adv::search_compound(in); // SSE-only; RDO owns lambda
//
// The search is an encoder decision only. The returned syntax values are what
// a future entropy pass must code: comp_group_idx, compound_type, wedge_index
// (via WedgeIndexToAngle/Dist), wedge_sign, mask_type, cwp_idx.

#include <cstdint>
#include <optional>

#include "compound_common.h"

namespace av2enc::inter::adv {

// Materialises the §7.13.3.27 mask for one block into `out`
// (`out[i * stride + j]`, values 0..64).
void build_wedge_mask(int bsize, int wedge_sign, int wedge_index, std::uint8_t* out, int stride);

// §7.13.3.27 inverse of Wedge_Angle_Dist_2_Index: (wedge_angle, wedge_dist) ->
// WedgeIndex, or -1 when the pair is not signallable. Encoder-side helper that
// pairs with the `read_wedge_mode()` syntax.
int wedge_index_from_angle_dist(int wedge_angle, int wedge_dist);

// True when `read_wedge_mode()` can signal this wedge index.
bool wedge_index_signalable(int wedge_index);

// Applies a fully specified job. Returns false for a structurally invalid job
// (null planes, block outside the destination plane, illegal type/size) without
// touching memory.
bool apply_compound(const CompoundJob& job);

struct CompoundSearchInput {
  int bsize = tables::kBlock64x64;
  int bit_depth = 8;
  BlockRect rect{};

  // Luma compound predictions at 1/16 sample precision, `p*_stride` in samples.
  const std::int16_t* p0 = nullptr;
  int p0_stride = 0;
  const std::int16_t* p1 = nullptr;
  int p1_stride = 0;

  // Source luma block for the SSE decision.
  const std::uint8_t* source = nullptr;
  int source_stride = 0;

  // Scratch destination used to form candidate predictions.
  std::uint8_t* scratch = nullptr;
  int scratch_stride = 0;

  bool enable_average = true;
  bool enable_cwp = true;
  bool enable_wedge = true;
  bool enable_diffwtd = true;
  bool enable_imp_mask = true;

  // Candidate CWP weights. The signallable set is
  // `Cwp_Weighting_Factor[is_same_side()][idx]` (§5.20.7.6), which the caller
  // knows; the default is the opposite-side row. `cwp_count == 0` searches only
  // CWP_EQUAL.
  int cwp_candidates[7] = {8, 12, 4, 10, 6, -4, 20};
  int cwp_count = 5;

  // Inputs for the implicit mask blend (§7.13.3.14). `imp_mask_eligible` mirrors
  // the full condition; search only tries it when the caller says it holds.
  bool imp_mask_eligible = false;
  int ref_start_x[2] = {0, 0};
  int ref_start_y[2] = {0, 0};
  int mi_cols = 0;
  int mi_rows = 0;

  // Restrict the wedge search to one sign (the encoder can derive the sign from
  // the residual sign, but both are legal). -1 = search both.
  int wedge_sign = -1;
};

struct CompoundDecision {
  CompoundType type = CompoundType::kAverage;
  int cwp_weight = kCwpEqual;
  int wedge_index = 0;
  int wedge_sign = 0;
  int mask_type = 0;
  bool use_imp_mask = false;
  std::int64_t sse = 0;
};

// Exhaustive SSE search over the enabled compound types. `scratch` must be at
// least `rect.w x rect.h`. Returns std::nullopt for invalid input.
std::optional<CompoundDecision> search_compound(const CompoundSearchInput& in);

// ---------------------------------------------------------------------------
// Inter-intra
// ---------------------------------------------------------------------------

struct InterIntraSearchInput {
  int bsize = tables::kBlock64x64;
  BlockRect rect{};
  // Intra prediction candidates for the four interintra_mode values, already
  // generated by the intra module on the same geometry. Index with
  // static_cast<int>(InterIntraMode).
  const std::uint8_t* intra[kInterIntraModes] = {nullptr, nullptr, nullptr, nullptr};
  int intra_stride = 0;
  // Inter prediction already written into `scratch` (integer samples) — this is
  // the same buffer the blend overwrites.
  std::uint8_t* scratch = nullptr;
  int scratch_stride = 0;
  const std::uint8_t* source = nullptr;
  int source_stride = 0;
  // An inter prediction copy, needed because the blend consumes the inter
  // prediction in place: the search restores it between candidates.
  const std::uint8_t* inter_pred = nullptr;
  int inter_pred_stride = 0;

  bool enable_wedge_interintra = true;
  int wedge_sign = 0;  // read_interintra_mode() forces wedge_sign = 0
};

struct InterIntraDecision {
  InterIntraMode mode = InterIntraMode::kDc;
  bool wedge_interintra = false;
  int wedge_index = 0;
  std::int64_t sse = 0;
};

// Searches II_DC/V/H/SMOOTH with and without a wedge mask. Requires
// `bsize_has_wedge(bsize)` for the wedge variants. Returns std::nullopt for
// invalid input.
std::optional<InterIntraDecision> search_inter_intra(const InterIntraSearchInput& in);

// Applies one inter-intra candidate to `scratch` (used by the search and by
// apply_compound()). `inter_pred` is copied into scratch first.
bool apply_inter_intra(const InterIntraSearchInput& in, InterIntraMode mode, bool wedge_interintra,
                       int wedge_index);

// ---------------------------------------------------------------------------
// Small helpers shared by the search and the tests.
// ---------------------------------------------------------------------------

// Sum of squared error between two w x h blocks at (a_x,a_y) and (b_x,b_y).
std::int64_t block_sse(const std::uint8_t* a, int a_stride, int a_x, int a_y, const std::uint8_t* b,
                       int b_stride, int b_x, int b_y, int w, int h);

}  // namespace av2enc::inter::adv

#endif  // AV2ENC_INTER_ADVANCED_COMPOUND_H_
