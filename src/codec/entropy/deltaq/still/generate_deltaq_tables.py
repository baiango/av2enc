#!/usr/bin/env python3
"""Generate the delta-Q / segmentation CDF header from the AV2 spec tables.

Numeric source: ``spec/tables/default_cdf.json`` (AV2 v1.0.0 clause 9.3),
which is itself extracted from the pinned spec PDF by ``tools/spec_extract``.
Nothing here is hand-typed.

Two groups are emitted:

``namespace av2enc::deltaq::cdf``
    The non-coefficient CDFs used by ``segmentation_params()`` and
    ``read_delta_qindex()`` / ``read_segment_id()``:
    ``Default_Delta_Q_Cdf``, ``Default_Segment_Id_Cdf``,
    ``Default_Segment_Id_Ext_Cdf``, ``Default_Seg_Id_Ext_Flag_Cdf`` and
    ``Default_Segment_Id_Predicted_Cdf``.

``namespace av2enc::deltaq::coeff``
    Every coefficient CDF from ``init_coeff_cdfs()`` (clause 6.17.2) that the
    M1/M2 syntax paths use, with the leading ``COEFF_CDF_Q_CTXS = 4`` slice
    dimension preserved.  Clause 6.17.2 selects the slice from the *raw*
    ``base_q_idx`` -- never from a segmentation or delta-Q effective qindex.

Run from the repository root::

    python3 src/codec/entropy/deltaq/still/generate_deltaq_tables.py
    python3 src/codec/entropy/deltaq/still/generate_deltaq_tables.py --check

``--check`` regenerates into memory and fails if the checked-in header differs.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[5]
JSON_PATH = ROOT / "spec" / "tables" / "default_cdf.json"
OUT_PATH = pathlib.Path(__file__).resolve().parent / "deltaq_cdf_tables.h"

# (JSON name, C++ identifier).  All arrays below carry the leading qctx slice.
COEFF_ARRAYS = [
    ("Default_Txb_Skip_Cdf", "TxbSkipCdf"),
    ("Default_V_Txb_Skip_Cdf", "VTxbSkipCdf"),
    ("Default_Eob_Pt_16_Cdf", "EobPt16Cdf"),
    ("Default_Eob_Pt_32_Cdf", "EobPt32Cdf"),
    ("Default_Eob_Pt_64_Cdf", "EobPt64Cdf"),
    ("Default_Eob_Pt_128_Cdf", "EobPt128Cdf"),
    ("Default_Eob_Pt_256_Cdf", "EobPt256Cdf"),
    ("Default_Eob_Pt_512_Cdf", "EobPt512Cdf"),
    ("Default_Eob_Pt_1024_Cdf", "EobPt1024Cdf"),
    ("Default_Eob_Extra_Cdf", "EobExtraCdf"),
    ("Default_Dc_Sign_Cdf", "DcSignCdf"),
    ("Default_Coeff_Base_Cdf", "CoeffBaseCdf"),
    ("Default_Coeff_Base_Lf_Cdf", "CoeffBaseLfCdf"),
    ("Default_Coeff_Base_Eob_Cdf", "CoeffBaseEobCdf"),
    ("Default_Coeff_Base_Lf_Eob_Cdf", "CoeffBaseLfEobCdf"),
    ("Default_Coeff_Br_Cdf", "CoeffBrCdf"),
    ("Default_Coeff_Br_Lf_Cdf", "CoeffBrLfCdf"),
    ("Default_Coeff_Base_Uv_Cdf", "CoeffBaseUvCdf"),
    ("Default_Coeff_Base_Lf_Uv_Cdf", "CoeffBaseLfUvCdf"),
    ("Default_Coeff_Base_Eob_Uv_Cdf", "CoeffBaseEobUvCdf"),
    ("Default_Coeff_Base_Lf_Eob_Uv_Cdf", "CoeffBaseLfEobUvCdf"),
    ("Default_Coeff_Br_Uv_Cdf", "CoeffBrUvCdf"),
]

# (JSON name, C++ identifier).  These are *not* qctx-sliced.
PLAIN_ARRAYS = [
    ("Default_Delta_Q_Cdf", "kDeltaQCdf"),
    ("Default_Segment_Id_Cdf", "kSegmentIdCdf"),
    ("Default_Segment_Id_Ext_Cdf", "kSegmentIdExtCdf"),
    ("Default_Seg_Id_Ext_Flag_Cdf", "kSegIdExtFlagCdf"),
    ("Default_Segment_Id_Predicted_Cdf", "kSegmentIdPredictedCdf"),
]

QCTX = 4


def reshape(flat: list[int], dims: list[int]) -> list:
    if len(dims) == 1:
        return flat
    step = len(flat) // dims[0]
    return [reshape(flat[i * step : (i + 1) * step], dims[1:]) for i in range(dims[0])]


def format_array(values, indent: int) -> str:
    if isinstance(values, int):
        return str(values)
    if values and isinstance(values[0], int):
        return "{ " + ", ".join(str(v) for v in values) + " }"
    inner = ",\n".join(
        " " * (indent + 2) + format_array(v, indent + 2) for v in values
    )
    return "{\n" + inner + "\n" + " " * indent + "}"


def dims_suffix(dims: list[int]) -> str:
    return "".join(f"[{d}]" for d in dims)


def build_header() -> str:
    data = json.loads(JSON_PATH.read_text())["arrays"]
    lines = [
        "// Generated by src/codec/entropy/deltaq/still/generate_deltaq_tables.py from",
        "// spec/tables/default_cdf.json (AV2 v1.0.0 clause 9.3).",
        "// Do not hand-edit.",
        "//",
        "// `deltaq::kCoeffCdfQctxCount` slices come from init_coeff_cdfs()",
        "// (clause 6.17.2), indexed by the *raw* base_q_idx:",
        "//   idx = base_q_idx <= 90 ? 0 : base_q_idx <= 140 ? 1 :",
        "//         base_q_idx <= 190 ? 2 : 3",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace av2enc::deltaq::cdf {",
        "",
    ]

    for json_name, cpp_name in PLAIN_ARRAYS:
        entry = data[json_name]
        dims = list(entry["shape"])
        values = reshape(list(entry["data"]), dims)
        lines.append(f"// {json_name} {dims}")
        lines.append(
            f"inline constexpr std::uint16_t {cpp_name}{dims_suffix(dims)} = "
            + format_array(values, 0)
            + ";"
        )
        lines.append("")

    lines.append("}  // namespace av2enc::deltaq::cdf")
    lines.append("")
    lines.append("namespace av2enc::deltaq::coeff {")
    lines.append("")

    for json_name, cpp_name in COEFF_ARRAYS:
        entry = data[json_name]
        dims = list(entry["shape"])
        if dims[0] != QCTX:
            raise SystemExit(f"{json_name}: expected leading dim {QCTX}, got {dims}")
        values = reshape(list(entry["data"]), dims)
        lines.append(f"// {json_name} {dims}")
        lines.append(
            f"inline constexpr std::uint16_t k{cpp_name}{dims_suffix(dims)} = "
            + format_array(values, 0)
            + ";"
        )
        lines.append("")

    lines.append("}  // namespace av2enc::deltaq::coeff")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the checked-in header instead of writing it",
    )
    args = parser.parse_args()

    text = build_header()
    if args.check:
        if not OUT_PATH.exists():
            print(f"missing generated header: {OUT_PATH}", file=sys.stderr)
            return 1
        current = OUT_PATH.read_text()
        if current != text:
            print(
                f"out of date: {OUT_PATH}\n"
                "run: python3 src/codec/entropy/deltaq/still/generate_deltaq_tables.py",
                file=sys.stderr,
            )
            return 1
        print(f"ok: {OUT_PATH}")
        return 0

    OUT_PATH.write_text(text)
    print(f"wrote {OUT_PATH} ({OUT_PATH.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
