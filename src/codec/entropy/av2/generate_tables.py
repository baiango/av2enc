#!/usr/bin/env python3
"""Generate av2_entropy_tables.h from the normative AV2 v1.0.0 PDF.

Only the published specification is read.  The arrays are extracted from the
PDF (not typed by hand, not copied from an encoder) using the shared
tools/spec_extract/specpdf.py PDF reader.

Usage:
    python3 src/codec/entropy/av2/generate_tables.py

The generated file is checked in so that the C++ module has no Python or PDF
dependency at build time.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SPEC_PDF = REPO / "spec" / "AV2_Spec_v1.0.0.pdf"
SPEC_SHA256 = "e9916f091e4e83446aad6b4601641c5b292e569c144c4163b26a4497573b533f"
OUT = Path(__file__).with_name("av2_entropy_tables.h")

sys.path.insert(0, str(REPO / "tools" / "spec_extract"))
from specpdf import find_array, pdf_text  # noqa: E402


def main() -> None:
    digest = hashlib.sha256(SPEC_PDF.read_bytes()).hexdigest()
    if digest != SPEC_SHA256:
        raise SystemExit(
            f"{SPEC_PDF.name}: sha256 {digest} != pinned {SPEC_SHA256}"
        )

    text = pdf_text(SPEC_PDF)
    prob_inc = find_array(text, "Prob_Inc")
    para = find_array(text, "Para_Adjustment_List")
    if prob_inc is None or prob_inc.shape != [7, 8]:
        raise SystemExit(f"Prob_Inc: unexpected shape {prob_inc}")
    if para is None or para.shape != [125, 3]:
        raise SystemExit(f"Para_Adjustment_List: unexpected shape {para}")

    lines: list[str] = []
    lines.append("// Generated by src/codec/entropy/av2/generate_tables.py.")
    lines.append("// Source: AV2_Spec_v1.0.0.pdf (sha256 " + SPEC_SHA256 + "),")
    lines.append("//         section 9.2 Conversion tables (Prob_Inc and Para_Adjustment_List).")
    lines.append("// Do not hand-edit.  Re-run the generator instead.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace av2enc::av2 {")
    lines.append("")
    # nvcc compiles the header twice: the host pass sees host constexpr
    # tables, the device pass sees __constant__ tables.  This keeps the coder
    # state machine header usable from a .cu without a separate table file.
    lines.append("#if defined(__CUDA_ARCH__)")
    lines.append("#define AV2_ENTROPY_TABLE static __device__ __constant__")
    lines.append("#else")
    lines.append("#define AV2_ENTROPY_TABLE inline constexpr")
    lines.append("#endif")
    lines.append("")
    lines.append("inline constexpr int kNumParaCombinations = 125;")
    lines.append("inline constexpr int kNumParaIntervals = 3;")
    lines.append("")
    lines.append("// AV2 v1.0.0 section 9.2: Prob_Inc[7][8].")
    lines.append("AV2_ENTROPY_TABLE uint8_t kProbInc[7][8] = {")
    for row in prob_inc.data:
        lines.append("    {" + ", ".join(str(v) for v in row) + "},")
    lines.append("};")
    lines.append("")
    lines.append("// AV2 v1.0.0 section 9.2: Para_Adjustment_List[125][3].")
    lines.append("AV2_ENTROPY_TABLE int8_t kParaAdjustmentList[125][3] = {")
    for row in para.data:
        lines.append("    {" + ", ".join(str(v) for v in row) + "},")
    lines.append("};")
    lines.append("")
    lines.append("#undef AV2_ENTROPY_TABLE")
    lines.append("")
    lines.append("}  // namespace av2enc::av2")
    lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(prob_inc.values)} + {len(para.values)} values)")


if __name__ == "__main__":
    main()
