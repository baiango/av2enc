#!/usr/bin/env python3
"""Generate lossless-specific default CDF tables from spec/tables/default_cdf.json.

The coefficient CDFs are already generated by
src/codec/entropy/qctx/generate_qctx_tables.py and are reused from
qctx_cdf_tables.h.  This script only emits the CDF arrays that are unique to
the lossless / DPCM / FSC syntax paths:

  Default_Fsc_Mode_Cdf            [FSC_MODE_CONTEXTS][FSC_BSIZE_CONTEXTS][3]
  Default_Use_Dpcm_Y_Cdf          [3]
  Default_Dpcm_Mode_Y_Cdf         [3]
  Default_Use_Dpcm_UV_Cdf         [3]
  Default_Dpcm_Mode_UV_Cdf        [3]
  Default_Lossless_Tx_Size_Cdf    [BLOCK_SIZE_GROUPS][2][3]

The tables are copied from the v1.0.0 PDF extraction; no numeric value is
invented here.  Run from this directory:

    python3 generate_cdf_tables.py

The output is checked in as lossless_cdf_tables.h.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SOURCE = ROOT / "spec" / "tables" / "default_cdf.json"
OUTPUT = Path(__file__).resolve().parent / "lossless_cdf_tables.h"


def flatten(value):
    if isinstance(value, list):
        for item in value:
            yield from flatten(item)
    else:
        yield int(value)


def shape(value):
    dims = []
    while isinstance(value, list):
        dims.append(len(value))
        value = value[0]
    return dims


def emit(name, value, dims):
    data = list(flatten(value))
    expected = 1
    for dim in dims:
        expected *= dim
    assert len(data) == expected, (name, len(data), expected)
    suffix = "".join(f"[{dim}]" for dim in dims)

    def render(offset, shape, depth):
        if len(shape) == 1:
            chunk = data[offset:offset + shape[0]]
            return "{" + ", ".join(str(v) for v in chunk) + "}"
        stride = 1
        for d in shape[1:]:
            stride *= d
        items = [render(offset + i * stride, shape[1:], depth + 1)
                 for i in range(shape[0])]
        pad = "  " * depth
        body = (",\n" + pad + "  ").join(items)
        return "{\n" + pad + "  " + body + "\n" + pad + "}"

    return (f"inline constexpr std::uint16_t {name}{suffix} = "
            + render(0, dims, 0) + ";")

def get(arrays, name):
    entry = arrays[name]
    if isinstance(entry, dict):
        return entry["data"], entry["shape"]
    return entry, shape(entry)


def main():
    doc = json.loads(SOURCE.read_text())
    arrays = doc["arrays"]
    parts = [
        "// Generated by generate_cdf_tables.py from spec/tables/default_cdf.json.",
        "// AV2 v1.0.0 §9.3.  Do not hand-edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::lossless {",
        "",
        emit("kFscModeCdf", *get(arrays, "Default_Fsc_Mode_Cdf")),
        "",
        emit("kUseDpcmYCdf", *get(arrays, "Default_Use_Dpcm_Y_Cdf")),
        "",
        emit("kDpcmModeYCdf", *get(arrays, "Default_Dpcm_Mode_Y_Cdf")),
        "",
        emit("kUseDpcmUvCdf", *get(arrays, "Default_Use_Dpcm_UV_Cdf")),
        "",
        emit("kDpcmModeUvCdf", *get(arrays, "Default_Dpcm_Mode_UV_Cdf")),
        "",
        emit("kLosslessTxSizeCdf", *get(arrays, "Default_Lossless_Tx_Size_Cdf")),
        "",
        "}  // namespace av2enc::lossless",
        "",
    ]
    OUTPUT.write_text("\n".join(parts))
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
