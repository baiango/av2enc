#!/usr/bin/env python3
"""Generate tx_partition_tables.h from the pinned spec tables.

Sources (must not be hand-edited; regenerate from the AV2 v1.0.0 PDF):

  spec/tables/default_cdf.json   §9.3 Default_Tx_*_Cdf
  spec/tables/block_tables.json  §9.2 Max_Tx_Size_Rect, Size_To_Tx_*,
                                 Tx_Width/Height, Adjusted_Tx_Size

The generated header is committed (repo convention: generated tables are
checked in next to their generator).  Run from anywhere:

  python3 src/codec/transform/tx_partition/generate_tx_partition_tables.py

Any mismatch in array shape or value aborts with an error.  The four CDF
arrays were independently read from PDF pages 634-637 and are re-verified here
against the JSON, so a parsing regression in either source is caught.
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[4]
TABLES = ROOT / "spec" / "tables"
OUT = pathlib.Path(__file__).resolve().parent / "tx_partition_tables.h"


def load(name: str) -> dict:
    with (TABLES / name).open() as handle:
        return json.load(handle)


def flatten(data, shape):
    """Validate a nested or flat list against shape and return a flat list."""
    count = 1
    for dim in shape:
        count *= dim
    if len(data) == count:
        return list(data)
    out = []

    def walk(node, depth):
        if depth == len(shape):
            out.append(int(node))
            return
        if not isinstance(node, list) or len(node) != shape[depth]:
            raise SystemExit(
                f"shape mismatch at depth {depth}: expected {shape[depth]}"
            )
        for child in node:
            walk(child, depth + 1)

    walk(data, 0)
    if len(out) != count:
        raise SystemExit(f"flattened {len(out)} values, expected {count}")
    return out


def c_array(name: str, data, shape):
    """Emit a constexpr array with explicit dimensions."""
    flat = flatten(data, shape)
    lines = [f"inline constexpr std::uint16_t {name}"]
    for dim in shape:
        lines.append(f"    [{dim}]")
    lines[-1] += " = {"
    per_row = 10
    body = []
    for i in range(0, len(flat), per_row):
        chunk = ", ".join(f"{v:5d}" for v in flat[i : i + per_row])
        body.append("    " + chunk + ",")
    lines.extend(body)
    lines.append("};")
    return "\n".join(lines)


def i_array(name: str, data, shape, comment=""):
    flat = flatten(data, shape)
    lines = []
    if comment:
        lines.append(f"// {comment}")
    lines.append(f"inline constexpr int {name}[{flat.__len__()}] = {{")
    per_row = 12
    for i in range(0, len(flat), per_row):
        chunk = ", ".join(f"{v:3d}" for v in flat[i : i + per_row])
        lines.append("    " + chunk + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    cdfs = load("default_cdf.json")["arrays"]
    blocks = load("block_tables.json")

    expected = {
        "Default_Tx_Do_Partition_Cdf": [2, 2, 9, 3],
        "Default_Tx_Partition_Type_Cdf": [2, 2, 14, 8],
        "Default_Tx_Partition_Type_Reduced_Cdf": [2, 2, 14, 8],
        "Default_Tx_2or3_Partition_Type_Cdf": [2, 2, 2, 3],
    }
    for name, shape in expected.items():
        if name not in cdfs:
            raise SystemExit(f"missing CDF {name}")
        if list(cdfs[name]["shape"]) != shape:
            raise SystemExit(
                f"{name}: shape {cdfs[name]['shape']} != {shape}"
            )

    # §8.3.1: every CDF row ends with a rate index < 125 and a use count
    # <= 32.  These arrays have 3 or 8 entries, so the last two are rate/count.
    for name in expected:
        flat = flatten(cdfs[name]["data"], expected[name])
        if len(flat) % 3 == 0 and expected[name][-1] == 3:
            stride = 3
        elif expected[name][-1] == 8:
            stride = 8
        else:
            raise SystemExit(f"{name}: unexpected row width")
        for start in range(0, len(flat), stride):
            row = flat[start : start + stride]
            if row[-2] >= 125 or row[-1] > 32:
                raise SystemExit(f"{name}: bad rate/count in row {row}")
            if stride > 3:
                for value in row[:-2]:
                    if value >= 32768:
                        raise SystemExit(f"{name}: CDF boundary out of range")

    parts = [
        "// Generated by generate_tx_partition_tables.py. Do not hand-edit.",
        "// Source: AV2 v1.0.0 spec/tables/default_cdf.json (§9.3) and",
        "// spec/tables/block_tables.json (§9.2).",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::video::txpartition {",
        "",
        "// §9.3 Default_Tx_Do_Partition_Cdf[FSC_MODES][2][TXFM_SPLIT_GROUP][3]",
        c_array(
            "kDefaultTxDoPartitionCdf",
            cdfs["Default_Tx_Do_Partition_Cdf"]["data"],
            expected["Default_Tx_Do_Partition_Cdf"],
        ),
        "",
        "// §9.3 Default_Tx_Partition_Type_Cdf"
        "[FSC_MODES][2][TX_PARTITION_TYPE_NUM_VERT_AND_HORZ]"
        "[TX_PARTITION_TYPE_NUM + 1]",
        c_array(
            "kDefaultTxPartitionTypeCdf",
            cdfs["Default_Tx_Partition_Type_Cdf"]["data"],
            expected["Default_Tx_Partition_Type_Cdf"],
        ),
        "",
        "// §9.3 Default_Tx_Partition_Type_Reduced_Cdf (uniform)",
        c_array(
            "kDefaultTxPartitionTypeReducedCdf",
            cdfs["Default_Tx_Partition_Type_Reduced_Cdf"]["data"],
            expected["Default_Tx_Partition_Type_Reduced_Cdf"],
        ),
        "",
        "// §9.3 Default_Tx_2or3_Partition_Type_Cdf"
        "[FSC_MODES][2][TX_PARTITION_TYPE_NUM_VERT_OR_HORZ - 1][3]",
        c_array(
            "kDefaultTx2or3PartitionTypeCdf",
            cdfs["Default_Tx_2or3_Partition_Type_Cdf"]["data"],
            expected["Default_Tx_2or3_Partition_Type_Cdf"],
        ),
        "",
        i_array(
            "kTxPartitionMaxTxSizeRect",
            blocks["Max_Tx_Size_Rect"]["data"],
            [29],
            "§9.2 Max_Tx_Size_Rect[BLOCK_SIZES]",
        ),
        "",
        i_array(
            "kTxPartitionBlockGroup",
            blocks["Size_To_Tx_Part_Group_Lookup"]["data"],
            [29],
            "§9.2 Size_To_Tx_Part_Group_Lookup[BLOCK_SIZES]",
        ),
        "",
        i_array(
            "kTxPartitionTypeGroupVertAndHorz",
            blocks["Size_To_Tx_Type_Group_Vert_And_Horz"]["data"],
            [29],
            "§9.2 Size_To_Tx_Type_Group_Vert_And_Horz[BLOCK_SIZES] "
            "(255 == BLOCK_INVALID)",
        ),
        "",
        i_array(
            "kTxPartitionTypeGroupVertOrHorz",
            blocks["Size_To_Tx_Type_Group_Vert_Or_Horz"]["data"],
            [29],
            "§9.2 Size_To_Tx_Type_Group_Vert_Or_Horz[BLOCK_SIZES] "
            "(255 == BLOCK_INVALID)",
        ),
        "",
        i_array(
            "kTxPartitionTxWidth",
            blocks["Tx_Width"]["data"],
            [25],
            "§9.2 Tx_Width[TX_SIZES_ALL]",
        ),
        "",
        i_array(
            "kTxPartitionTxHeight",
            blocks["Tx_Height"]["data"],
            [25],
            "§9.2 Tx_Height[TX_SIZES_ALL]",
        ),
        "",
        i_array(
            "kTxPartitionTxWidthLog2",
            blocks["Tx_Width_Log2"]["data"],
            [25],
            "§9.2 Tx_Width_Log2[TX_SIZES_ALL]",
        ),
        "",
        i_array(
            "kTxPartitionTxHeightLog2",
            blocks["Tx_Height_Log2"]["data"],
            [25],
            "§9.2 Tx_Height_Log2[TX_SIZES_ALL]",
        ),
        "",
        i_array(
            "kTxPartitionAdjustedTxSize",
            blocks["Adjusted_Tx_Size"]["data"],
            [25],
            "§9.2 Adjusted_Tx_Size[TX_SIZES_ALL]",
        ),
        "",
        i_array(
            "kTxPartitionBlockWidth",
            blocks["Num_4x4_Blocks_Wide"]["data"],
            [29],
            "§9.2 Num_4x4_Blocks_Wide[BLOCK_SIZES] (in 4x4 units)",
        ),
        "",
        i_array(
            "kTxPartitionBlockHeight",
            blocks["Num_4x4_Blocks_High"]["data"],
            [29],
            "§9.2 Num_4x4_Blocks_High[BLOCK_SIZES] (in 4x4 units)",
        ),
        "",
        "}  // namespace av2enc::video::txpartition",
        "",
    ]
    OUT.write_text("\n".join(parts))

    # Self-check: shapes must be exactly what the C++ arrays declare.
    counts = {name: len(flatten(cdfs[name]["data"], shape))
              for name, shape in expected.items()}
    print(f"wrote {OUT}")
    for name, count in counts.items():
        print(f"  {name}: {count} values")
    return 0


if __name__ == "__main__":
    sys.exit(main())
