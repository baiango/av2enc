#!/usr/bin/env python3
"""Generate video_residual_cdf.h from the extracted §9.3 default CDF tables.

Source of truth: spec/tables/default_cdf.json (produced from the AV2 v1.0.0
spec by tools/spec_extract/build_all.py).  The M2 table generator
(src/pipeline/video/generate_video_tables.py) does not emit the inter transform-type
CDFs because the M2 core does not signal inter TX types yet; this component
does, so it generates its own header.  Same contract as the other generated
tables: do not hand-edit.

Usage: python3 src/codec/transform/inter_residual/tools/generate_residual_cdf.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", ".."))
SOURCE = os.path.join(ROOT, "spec", "tables", "default_cdf.json")
TARGET = os.path.join(HERE, "..", "video_residual_cdf.h")

# (C identifier, spec array name, C shape).  Shapes follow the §9.3 declaration
# dims: [COEFF_CDF_Q_CTXS][ctx][sqrSz or n+1].
ARRAYS = [
    ("kInterTxTypeSet1Cdf", "Default_Inter_Tx_Type_Set1_Cdf", (3, 2, 3)),
    ("kInterTxTypeIndexSet1Cdf", "Default_Inter_Tx_Type_Index_Set1_Cdf", (3, 9)),
    ("kInterTxTypeOffsetSet1Cdf", "Default_Inter_Tx_Type_Offset_Set1_Cdf", (3, 9)),
    ("kInterTxTypeSet2Cdf", "Default_Inter_Tx_Type_Set2_Cdf", (3, 3)),
    ("kInterTxTypeIndexSet2Cdf", "Default_Inter_Tx_Type_Index_Set2_Cdf", (3, 9)),
    ("kInterTxTypeOffsetSet2Cdf", "Default_Inter_Tx_Type_Offset_Set2_Cdf", (3, 5)),
    ("kInterTxTypeSet3Cdf", "Default_Inter_Tx_Type_Set3_Cdf", (3, 4, 3)),
    ("kInterTxTypeSet4Cdf", "Default_Inter_Tx_Type_Set4_Cdf", (3, 4, 5)),
    ("kInterTxTypeLongCdf", "Default_Inter_Tx_Type_Long_Cdf", (3, 4, 5)),
    # §9.3 coefficient tables the M2 core omits: the M1 writer keeps its own
    # (private) copies of the EOB_PT 16/32 tables, and the inter TX-type long
    # sets need the is_long_side_dct flag CDF.
    ("kEobPt16Cdf", "Default_Eob_Pt_16_Cdf", (3, 6), 90),
    ("kEobPt32Cdf", "Default_Eob_Pt_32_Cdf", (3, 7), 90),
    ("kIsLongSideDctCdf", "Default_Is_Long_Side_Dct_Cdf", (2, 3)),
]


def flatten(shape, data):
    count = 1
    for dim in shape:
        count *= dim
    if count != len(data):
        raise SystemExit(f"shape {shape} expects {count} values, got {len(data)}")
    return data


def emit_array(name, shape, data, lines):
    dims = "".join(f"[{d}]" for d in shape)
    lines.append(f"// §9.3 {name} {list(shape)}")
    lines.append(f"inline constexpr unsigned short {name}{dims} = {{")
    row = []
    for value in data:
        row.append(f"{value},")
        if len(row) == 8:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    lines.append("")


def main():
    with open(SOURCE, encoding="utf-8") as handle:
        doc = json.load(handle)
    arrays = doc["arrays"]
    lines = [
        "// Generated by src/codec/transform/inter_residual/tools/generate_residual_cdf.py.",
        "// Source: AV2 v1.0.0 §9.3 default CDFs (commit 38f28e7).",
        "// Do not hand-edit.",
        "#pragma once",
        "",
        "namespace av2enc::video::residual {",
        "",
    ]
    for spec in ARRAYS:
        c_name, spec_name, shape = spec[0], spec[1], spec[2]
        base_q_idx = spec[3] if len(spec) > 3 else None
        entry = arrays.get(spec_name)
        if entry is None:
            raise SystemExit(f"missing {spec_name} in {SOURCE}")
        data = entry["data"]
        if base_q_idx is not None:
            # Slice the COEFF_CDF_Q_CTXS dimension like init_coeff_cdfs():
            # base_q_idx <= 90 selects slice 0.
            qctx = 0 if base_q_idx <= 90 else (1 if base_q_idx <= 140
                    else (2 if base_q_idx <= 190 else 3))
            per_slice = len(data) // entry["shape"][0]
            data = data[qctx * per_slice:(qctx + 1) * per_slice]
        if len(data) != _product(shape):
            raise SystemExit(
                f"{spec_name}: shape {shape} does not match {len(data)} values")
        emit_array(c_name, shape, flatten(shape, data), lines)
    lines.append("}  // namespace av2enc::video::residual")
    lines.append("")
    with open(TARGET, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {os.path.relpath(TARGET, ROOT)}")


def _product(shape):
    result = 1
    for dim in shape:
        result *= dim
    return result


if __name__ == "__main__":
    main()
