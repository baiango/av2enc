#!/usr/bin/env python3
"""Generate src/codec/rate/rdoq/rdoq_cdf_tables.h.

Source: spec/tables/default_cdf.json (AV2 v1.0.0 §9.3 default CDFs, commit
38f28e7).  Only COEFF_CDF_Q_CTXS == 0 is emitted: the M1 encoder pins
base_q_idx = 90 and coefficient CDF slice 0 is normative for q <= 90
(§8.3.1).  Keeping one slice makes the header small and the model unambiguous.

The shapes are the ones the M1 syntax writer consumes (qctx dimension removed),
plus Default_Eob_Pt_16/32 for the 4x4 / 4x8 EOB syntax that the M1 writer does
not emit but the spec defines.

Do not hand-edit the generated header.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "spec" / "tables" / "default_cdf.json"
OUTPUT = Path(__file__).resolve().parent / "rdoq_cdf_tables.h"

# (C++ name, JSON name, dimensions with the leading qctx axis removed)
TABLES = [
    ("kEobPt16Cdf", "Default_Eob_Pt_16_Cdf"),
    ("kEobPt32Cdf", "Default_Eob_Pt_32_Cdf"),
    ("kEobPt64Cdf", "Default_Eob_Pt_64_Cdf"),
    ("kEobPt128Cdf", "Default_Eob_Pt_128_Cdf"),
    ("kEobPt256Cdf", "Default_Eob_Pt_256_Cdf"),
    ("kEobPt512Cdf", "Default_Eob_Pt_512_Cdf"),
    ("kEobPt1024Cdf", "Default_Eob_Pt_1024_Cdf"),
    ("kEobExtraCdf", "Default_Eob_Extra_Cdf"),
    ("kCoeffBaseCdf", "Default_Coeff_Base_Cdf"),
    ("kCoeffBaseLfCdf", "Default_Coeff_Base_Lf_Cdf"),
    ("kCoeffBaseEobCdf", "Default_Coeff_Base_Eob_Cdf"),
    ("kCoeffBaseLfEobCdf", "Default_Coeff_Base_Lf_Eob_Cdf"),
    ("kCoeffBrCdf", "Default_Coeff_Br_Cdf"),
    ("kCoeffBrLfCdf", "Default_Coeff_Br_Lf_Cdf"),
    ("kCoeffBaseUvCdf", "Default_Coeff_Base_Uv_Cdf"),
    ("kCoeffBaseLfUvCdf", "Default_Coeff_Base_Lf_Uv_Cdf"),
    ("kCoeffBaseEobUvCdf", "Default_Coeff_Base_Eob_Uv_Cdf"),
    ("kCoeffBaseLfEobUvCdf", "Default_Coeff_Base_Lf_Eob_Uv_Cdf"),
    ("kCoeffBrUvCdf", "Default_Coeff_Br_Uv_Cdf"),
    ("kTxbSkipCdf", "Default_Txb_Skip_Cdf"),
    ("kVTxbSkipCdf", "Default_V_Txb_Skip_Cdf"),
    ("kDcSignCdf", "Default_Dc_Sign_Cdf"),
]


def wrap(values: list[int], indent: str) -> str:
    line = indent
    out = []
    for value in values:
        token = f"{value}, "
        if len(line) + len(token) > 78:
            out.append(line.rstrip())
            line = indent
        line += token
    if line.strip():
        out.append(line.rstrip())
    return "\n".join(out)


def emit_array(name: str, values: list[int], shape: list[int]) -> str:
    """Emit a nested C++ initializer for a flat row-major array."""
    if len(shape) == 1:
        body = "{\n" + wrap(values, "    ") + "\n};"
    else:
        lines: list[str] = []

        def recurse(offset: int, depth: int, indent: str) -> int:
            if depth == len(shape) - 1:
                count = shape[-1]
                lines.append(indent + "{")
                lines.append(
                    indent + "  " + wrap(values[offset : offset + count],
                                         indent + "  ")
                )
                lines.append(indent + "},")
                return offset + count
            lines.append(indent + "{")
            offset = recurse(offset, depth + 1, indent + "  ")
            for _ in range(shape[depth] - 1):
                offset = recurse(offset, depth + 1, indent + "  ")
            lines.append(indent + ("};" if depth == 0 else "},"))
            return offset

        recurse(0, 0, "    ")
        body = "\n".join(lines)
    dims = "".join(f"[{dim}]" for dim in shape)
    return f"inline constexpr std::uint16_t {name}{dims} =\n{body}"


def main() -> None:
    source = json.loads(SOURCE.read_text())
    arrays = source["arrays"]
    chunks = [
        "// Generated by src/codec/rate/rdoq/generate_rdoq_cdf.py from",
        "// spec/tables/default_cdf.json (AV2 v1.0.0 §9.3, qctx slice 0).",
        "// Do not hand-edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::rdoq::cdf {",
        "",
    ]
    for cpp_name, json_name in TABLES:
        entry = arrays[json_name]
        shape = entry["shape"]
        if shape[0] != 4:
            raise SystemExit(f"{json_name}: expected a qctx axis, got {shape}")
        inner = shape[1:]
        values = entry["data"]
        stride = len(values) // shape[0]
        slice0 = values[:stride]
        chunks.append(
            f"// {json_name} {inner}, COEFF_CDF_Q_CTXS = 0"
        )
        chunks.append(emit_array(cpp_name, slice0, inner))
        chunks.append("")
    chunks.append("}  // namespace av2enc::rdoq::cdf")
    chunks.append("")
    OUTPUT.write_text("\n".join(chunks))
    print(f"wrote {OUTPUT} ({len(TABLES)} tables)")


if __name__ == "__main__":
    main()
