#!/usr/bin/env python3
"""Generate the normative quantizer lookup tables for the rate-control component.

Source:
  spec/tables/quant.json  (AV2 v1.0.0 clause 7.14.2)

Run from anywhere:

    python3 src/codec/rate/rc/generate_rc_tables.py

Output: src/codec/rate/rc/rc_tables.h

The tables are committed so the standalone build has no Python dependency.
Do not hand-edit the generated header; rerun this script after regenerating
spec/tables/quant.json with tools/spec_extract.
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
QUANT = ROOT / "spec" / "tables" / "quant.json"
OUT = HERE / "rc_tables.h"


def fmt_flat(values, per_line=12):
    lines = []
    for i in range(0, len(values), per_line):
        chunk = ", ".join(str(v) for v in values[i : i + per_line])
        lines.append("    " + chunk + ",")
    return "\n".join(lines)


def main():
    quant = json.loads(QUANT.read_text())
    ac = quant["Ac_Qlookup"]
    qlookup = quant["qlookup_q0_255"]
    maxq = quant["maxq_8bit"]
    assert len(ac) == 25, len(ac)
    assert len(qlookup) == maxq + 1, (len(qlookup), maxq)
    assert qlookup[0] == ac[0]

    lines = [
        "// Generated by src/codec/rate/rc/generate_rc_tables.py from",
        "// spec/tables/quant.json (AV2 v1.0.0 clause 7.14.2). Do not hand-edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace av2enc::rc {",
        "",
        "// Ac_Qlookup[0..24]: the base quantizer step table.",
        "inline constexpr std::int32_t kAcQLookup[25] = {",
        fmt_flat(ac),
        "};",
        "",
        "// qlookup(q) for q = 0..%d (8-bit). qlookup(0) is the lossless" % maxq,
        "// special case (64), not a real quantizer; rate control uses 1..%d." % maxq,
        "inline constexpr std::int32_t kQlookupQ0To255[%d] = {" % len(qlookup),
        fmt_flat(qlookup),
        "};",
        "",
        "inline constexpr std::int32_t kMaxQIndex8Bit = %d;" % maxq,
        "",
        "}  // namespace av2enc::rc",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
