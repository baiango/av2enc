#!/usr/bin/env python3
"""Emit the §8.3 CDF tables used by the IBC syntax adapter.

Source: spec/tables/default_cdf.json (§9.3, AV2 v1.0.0).  The generated
header is checked in; rerun from the repository root:

    python3 src/codec/intra/ibc/stream/generate_ibc_cdfs.py

Only the arrays read by `read_intrabc_info()`, `read_skip()`, the non-IBC
palette flag, and the shell motion-vector syntax are emitted.  Layout is the
entropy coder's N+1 inverse-CDF form: cdf[N-1] is the base adaptation rate and
cdf[N] is the use count.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
JSON_PATH = ROOT / "spec" / "tables" / "default_cdf.json"
OUT_PATH = Path(__file__).resolve().parent / "ibc_cdfs.h"

# (C++ name, JSON name, comment)
ARRAYS = [
    ("kIntrabcCdf", "Default_Intrabc_Cdf", "Default_Intrabc_Cdf[3][3]"),
    ("kIntrabcModeCdf", "Default_Intrabc_Mode_Cdf",
     "Default_Intrabc_Mode_Cdf[3]"),
    ("kIntrabcPrecisionCdf", "Default_Intrabc_Precision_Cdf",
     "Default_Intrabc_Precision_Cdf[3]"),
    ("kSkipCdf", "Default_Skip_Cdf", "Default_Skip_Cdf[6][3]"),
    ("kPaletteYModeCdf", "Default_Palette_Y_Mode_Cdf",
     "Default_Palette_Y_Mode_Cdf[3]"),
    ("kJointShellSetCdf", "Default_Joint_Shell_Set_Cdf",
     "Default_Joint_Shell_Set_Cdf[3]"),
    ("kJointShellLastTwoClassesCdf",
     "Default_Joint_Shell_Last_Two_Classes_Cdf",
     "Default_Joint_Shell_Last_Two_Classes_Cdf[3]"),
    ("kShellOffsetClass2Cdf", "Default_Shell_Offset_Class2_Cdf",
     "Default_Shell_Offset_Class2_Cdf[3]"),
    ("kShellOffsetLowClassCdf", "Default_Shell_Offset_Low_Class_Cdf",
     "Default_Shell_Offset_Low_Class_Cdf[2][3]"),
    ("kShellOffsetOtherClassCdf", "Default_Shell_Offset_Other_Class_Cdf",
     "Default_Shell_Offset_Other_Class_Cdf[16][3]"),
    ("kColMvGreaterCdf", "Default_Col_Mv_Greater_Cdf",
     "Default_Col_Mv_Greater_Cdf[2][3]"),
    ("kColMvIndexCdf", "Default_Col_Mv_Index_Cdf",
     "Default_Col_Mv_Index_Cdf[4][3]"),
]

for p in (0, 1, 3, 4, 5, 6):
    ARRAYS.append(
        (f"kJointShell{p}Class0Cdf", f"Default_Joint_Shell{p}_Class0_Cdf",
         f"Default_Joint_Shell{p}_Class0_Cdf"))
    ARRAYS.append(
        (f"kJointShell{p}Class1Cdf", f"Default_Joint_Shell{p}_Class1_Cdf",
         f"Default_Joint_Shell{p}_Class1_Cdf"))


def shape_suffix(shape: list[int]) -> str:
    return "".join(f"[{n}]" for n in shape)


def row_initializer(data: list[int], shape: list[int]) -> str:
    if not shape:
        return str(data[0])
    inner = shape[0]
    if len(shape) == 1:
        return ", ".join(str(v) for v in data[:inner])
    stride = 1
    for n in shape[1:]:
        stride *= n
    rows = []
    for i in range(inner):
        chunk = data[i * stride:(i + 1) * stride]
        rows.append("{" + row_initializer(chunk, shape[1:]) + "}")
    return ", ".join(rows)


def main() -> None:
    table = json.loads(JSON_PATH.read_text())["arrays"]
    lines = [
        "// Generated by generate_ibc_cdfs.py from spec/tables/default_cdf.json.",
        "// Source: AV2 v1.0.0 §9.3 default CDFs. Do not hand-edit.",
        "//",
        "// Every array uses av2enc::av2's inverse-CDF form: cdf[N-1] is the base",
        "// adaptation rate and cdf[N] is the use count.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace av2enc::still::ibc_stream {",
        "",
    ]
    for cpp_name, json_name, comment in ARRAYS:
        entry = table[json_name]
        shape = entry["shape"]
        data = entry["data"]
        assert len(data) == eval("*".join(str(n) for n in shape)), json_name
        lines.append(f"// {comment} (§9.3)")
        lines.append(
            f"inline constexpr std::uint16_t {cpp_name}{shape_suffix(shape)} = {{")
        lines.append(f"    {row_initializer(data, shape)},")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace av2enc::still::ibc_stream")
    lines.append("")
    OUT_PATH.write_text("\n".join(lines))
    print(f"wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
