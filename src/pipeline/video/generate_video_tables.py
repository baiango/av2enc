#!/usr/bin/env python3
"""Generate the M2 inter CDF header from spec/tables/default_cdf.json.

Only the arrays the M2 P-frame writer can actually select are emitted.  The
tables are §9.3 defaults (AV2 v1.0.0, commit 38f28e7).  Intra / partition /
coefficient CDFs come from the existing M0/M1 headers and are not duplicated.

Usage:
  python3 src/pipeline/video/generate_video_tables.py > src/pipeline/video/video_cdf_tables.h
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "spec" / "tables" / "default_cdf.json"

# (C++ symbol, JSON array name)
ARRAYS = [
    ("kSingleModeCdf", "Default_Single_Mode_Cdf"),
    ("kSkipCdf", "Default_Skip_Cdf"),
    ("kSkipModeCdf", "Default_Skip_Mode_Cdf"),
    ("kIsInterCdf", "Default_Is_Inter_Cdf"),
    ("kSingleRefCdf", "Default_Single_Ref_Cdf"),
    ("kDrlModeCdf", "Default_Drl_Mode_Cdf"),
    ("kJointShellSetCdf", "Default_Joint_Shell_Set_Cdf"),
    ("kJointShell6Class0Cdf", "Default_Joint_Shell6_Class0_Cdf"),
    ("kJointShell6Class1Cdf", "Default_Joint_Shell6_Class1_Cdf"),
    ("kJointShellLastTwoClassesCdf", "Default_Joint_Shell_Last_Two_Classes_Cdf"),
    ("kShellOffsetLowClassCdf", "Default_Shell_Offset_Low_Class_Cdf"),
    ("kShellOffsetClass2Cdf", "Default_Shell_Offset_Class2_Cdf"),
    ("kShellOffsetOtherClassCdf", "Default_Shell_Offset_Other_Class_Cdf"),
    ("kColMvGreaterCdf", "Default_Col_Mv_Greater_Cdf"),
    ("kColMvIndexCdf", "Default_Col_Mv_Index_Cdf"),
    # Inter residual: transform-type symbols.  AV2 codes an inter TX_TYPE for
    # every luma TX block whose transform set is not DCTONLY, unlike M1's
    # intra-only type syntax.
    ("kInterTxTypeSet1Cdf", "Default_Inter_Tx_Type_Set1_Cdf"),
    ("kInterTxTypeSet2Cdf", "Default_Inter_Tx_Type_Set2_Cdf"),
    ("kInterTxTypeSet3Cdf", "Default_Inter_Tx_Type_Set3_Cdf"),
    ("kInterTxTypeLongCdf", "Default_Inter_Tx_Type_Long_Cdf"),
    ("kInterTxTypeIndexSet1Cdf", "Default_Inter_Tx_Type_Index_Set1_Cdf"),
    ("kInterTxTypeOffsetSet1Cdf", "Default_Inter_Tx_Type_Offset_Set1_Cdf"),
    ("kInterTxTypeIndexSet2Cdf", "Default_Inter_Tx_Type_Index_Set2_Cdf"),
    ("kInterTxTypeOffsetSet2Cdf", "Default_Inter_Tx_Type_Offset_Set2_Cdf"),
]


def flatten(data):
    if isinstance(data, list):
        out = []
        for item in data:
            out.extend(flatten(item))
        return out
    return [data]


def dims(shape):
    return "".join(f"[{n}]" for n in shape)


def main() -> None:
    payload = json.loads(SOURCE.read_text())
    arrays = payload["arrays"]
    print("// Generated by src/encoder/m2/generate_video_tables.py.")
    print("// Source: AV2 v1.0.0 §9.3 default CDFs (commit 38f28e7).")
    print("// Do not hand-edit.")
    print("#pragma once")
    print()
    print("namespace av2enc::video {")
    print()
    for symbol, name in ARRAYS:
        entry = arrays[name]
        shape = entry["shape"]
        values = flatten(entry["data"])
        expected = 1
        for n in shape:
            expected *= n
        if len(values) != expected:
            raise SystemExit(
                f"{name}: got {len(values)} values, shape {shape} needs {expected}"
            )
        print(f"// {name} {shape}")
        print(f"inline constexpr unsigned short {symbol}{dims(shape)} = {{")
        line = "   "
        for value in values:
            piece = f" {value},"
            if len(line) + len(piece) > 78:
                print(line)
                line = "   "
            line += piece
        if line.strip():
            print(line)
        print("};")
        print()
    print("}  // namespace av2enc::video")
    print()


if __name__ == "__main__":
    main()
